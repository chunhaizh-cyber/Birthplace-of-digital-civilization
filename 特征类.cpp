std::vector<抽象特征节点类*> 特征类::枚举命中抽象状态(const 特征节点类* 实例特征) const
{
    std::vector<抽象特征节点类*> 命中{};
    if (!基础信息_ || !实例特征) return 命中;

    const auto* 实例主信息 = 取特征主信息(实例特征);
    const auto* 当前值 = 实例主信息 ? std::get_if<I64>(&实例主信息->当前值) : nullptr;
    auto* 抽象特征 = 实例主信息 ? 实例主信息->抽象特征.指针 : nullptr;
    if (!实例主信息 || !当前值 || !抽象特征) return 命中;

    if (实例主信息->局部区间覆盖.has_value()
        && 实例主信息->局部区间覆盖->有效()
        && 实例主信息->局部区间覆盖->包含(*当前值)) {
        命中.push_back(static_cast<抽象特征节点类*>(抽象特征));
        return 命中;
    }

    for (auto* 子节点 : 基础信息_->枚举子节点_按类型<抽象特征主信息类>(抽象特征)) {
        const auto* 子主信息 = 取抽象特征主信息(static_cast<const 抽象特征节点类*>(子节点));
        if (子主信息 && 子主信息->是叶子特征() && 子主信息->值域.has_value()
            && 特征值命中值域(实例主信息->当前值, 子主信息->值域.value())) {
            命中.push_back(static_cast<抽象特征节点类*>(子节点));
        }
    }

    if (命中.empty()) {
        const auto* 抽象主信息 = 取抽象特征主信息(static_cast<const 抽象特征节点类*>(抽象特征));
        if (抽象主信息 && 抽象主信息->是叶子特征() && 抽象主信息->值域.has_value()
            && 特征值命中值域(实例主信息->当前值, 抽象主信息->值域.value())) {
            命中.push_back(static_cast<抽象特征节点类*>(抽象特征));
        }
    }

    return 命中;
}

抽象特征节点类* 特征类::解析实例特征命中抽象特征(特征节点类* 实例特征)
{
    auto* 实例主信息 = 取特征主信息(实例特征);
    if (!实例主信息) return nullptr;

    const auto 命中集合 = 枚举命中抽象状态(实例特征);
    if (命中集合.empty()) {
        实例主信息->当前命中抽象特征.清空();
        return nullptr;
    }

    auto* 最佳命中 = 命中集合.front();
    I64 最佳宽度 = I64_MAX;
    for (auto* 候选 : 命中集合) {
        const auto* 候选主信息 = 取抽象特征主信息(候选);
        if (!候选主信息) continue;
        const auto 宽度 = 私有_抽象值域宽度(候选主信息);
        if (宽度 < 最佳宽度) {
            最佳宽度 = 宽度;
            最佳命中 = 候选;
        }
    }

    实例主信息->当前命中抽象特征.绑定(最佳命中);
    return 最佳命中;
}

