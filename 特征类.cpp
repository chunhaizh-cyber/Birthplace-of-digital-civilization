// 功能：创建并返回或登记对应对象。
特征节点类* 特征类::创建特征(基础信息节点类* 宿主, 特征节点主信息类* 主信息)
{
    if (!基础信息_ || !主信息) return nullptr;
    return static_cast<特征节点类*>(基础信息_->添加子节点(宿主, 主信息));
}

// 功能：创建并返回或登记对应对象。
特征节点类* 特征类::创建特征_按类型(
    基础信息节点类* 宿主,
    const 语素入口节点类* 特征类型,
    const 特征值& 当前值)
{
    if (!特征类型) return nullptr;

    auto* 主信息 = new 特征节点主信息类{};
    主信息->名称 = 特征类型;
    主信息->类型 = 特征类型;
    主信息->当前值 = 当前值;
    return 创建特征(宿主, 主信息);
}

// 功能：创建并返回或登记对应对象。
特征节点类* 特征类::取或创建子特征_按类型(基础信息节点类* 宿主, const 语素入口节点类* 特征类型)
{
    if (auto* 命中 = 查找子特征_按类型(宿主, 特征类型)) {
        return 命中;
    }
    return 创建特征_按类型(宿主, 特征类型);
}

