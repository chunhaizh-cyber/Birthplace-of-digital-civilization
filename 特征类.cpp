// 功能：比较当前值、目标值或历史基准。
结构_轮廓比较结果 特征类::比较轮廓VecI64_按特征类型(
    const 语素入口节点类* 特征类型,
    const VecI64& 左值,
    const VecI64& 右值) noexcept
{
    const auto 维度 = 轮廓坐标维度_按特征类型(特征类型);
    if (!维度.has_value()) {
        结构_轮廓比较结果 结果{};
        结果.状态 = 枚举_轮廓比较状态::维度不支持;
        return 结果;
    }

    if (*维度 == 2) return 比较平面轮廓VecI64(左值, 右值);
    if (*维度 == 3) return 比较空间极值轮廓VecI64(左值, 右值);

    结构_轮廓比较结果 结果{};
    结果.坐标维度 = *维度;
    结果.状态 = 枚举_轮廓比较状态::维度不支持;
    return 结果;
}

// 功能：比较当前值、目标值或历史基准。
结构_特征状态比较结果 特征类::比较状态(
    const 状态节点类* 当前状态,
    const 状态节点类* 目标状态) const
{
    结构_特征状态比较结果 输出{};
    if (!当前状态 || !目标状态) {
        输出.说明 = "状态为空";
        return 输出;
    }

    状态类 状态服务{ 基础信息_ };
    特征节点类* 当前状态特征 = nullptr;
    特征节点类* 目标状态特征 = nullptr;
    特征值 当前状态值{};
    特征值 目标状态值{};
    if (!状态服务.读取状态特征和值(当前状态, 当前状态特征, 当前状态值)
        || !状态服务.读取状态特征和值(目标状态, 目标状态特征, 目标状态值)) {
        输出.说明 = "状态主信息为空";
        return 输出;
    }

    const auto* 当前特征主信息 = 取特征主信息(当前状态特征);
    const auto* 目标特征主信息 = 取特征主信息(目标状态特征);
    const auto* 当前特征类型 = 当前特征主信息 ? 当前特征主信息->类型 : nullptr;
    const auto* 目标特征类型 = 目标特征主信息 ? 目标特征主信息->类型 : nullptr;
    if (!当前特征类型 || !目标特征类型 || !语素入口同一(当前特征类型, 目标特征类型)) {
        输出.说明 = "状态特征类型不一致";
        return 输出;
    }

    const auto 比较结果 = 获取比较方法结果(
        当前特征类型,
        当前状态值,
        目标状态值,
        当前特征主信息,
        目标特征主信息);
    if (!比较结果.可比较) {
        输出.说明 = "状态值不可比较";
        return 输出;
    }

    输出.可比较 = true;
    输出.特征类型 = 当前特征类型;
    输出.比较方式 = 比较结果.比较方式;
    输出.差值 = 比较结果.差值;
    if (比较结果.差值 == 0) {
        输出.关系 = 枚举_三向关系::等于;
        输出.说明 = "当前状态等于目标状态";
    } else if (比较结果.比较方式 == 枚举_特征值比较模式::有序标量) {
        输出.关系 = 比较结果.差值 > 0
            ? 枚举_三向关系::小于
            : 枚举_三向关系::大于;
        输出.说明 = 比较结果.差值 > 0
            ? "当前状态小于目标状态"
            : "当前状态大于目标状态";
    } else {
        输出.关系 = 枚举_三向关系::大于;
        输出.说明 = "当前状态与目标状态不等";
    }
    return 输出;
}

// 功能：比较当前值、目标值或历史基准。
存在比较结果 特征类::比较特征集合(const 特征集合& A, const 特征集合& B, const 集合比较参数& 参数) const
{
    存在比较结果 结果{};

    std::unordered_map<const 语素入口节点类*, const 特征节点类*> 左表{};
    std::unordered_map<const 语素入口节点类*, const 特征节点类*> 右表{};

    const auto 构建索引 = [](const 特征集合& 集合, auto& 输出表) {
        for (const auto* 节点 : 集合) {
            if (!节点 || !节点->主信息) continue;
            const auto* 主信息 = dynamic_cast<const 特征节点主信息类*>(节点->主信息);
            if (!主信息 || !主信息->类型 || 输出表.contains(主信息->类型)) continue;
            输出表.emplace(主信息->类型, 节点);
        }
    };

    构建索引(A, 左表);
    构建索引(B, 右表);

    std::unordered_map<const 语素入口节点类*, bool> 全类型{};
    for (const auto& [类型, _] : 左表) 全类型.emplace(类型, true);
    for (const auto& [类型, _] : 右表) 全类型.emplace(类型, true);

    I64 加权差异和 = 0;
    I64 权重和 = 0;

    for (const auto& [类型, _] : 全类型) {
        constexpr I64 比较权重 = 10000;
        I64 差异度 = 0;
        bool 缺失A = false;
        bool 缺失B = false;
        ++结果.比较特征数;

        const auto 左迭代器 = 左表.find(类型);
        const auto 右迭代器 = 右表.find(类型);
        if (左迭代器 == 左表.end()) {
            缺失A = true;
            差异度 = 参数.缺失惩罚;
        } else if (右迭代器 == 右表.end()) {
            缺失B = true;
            差异度 = 参数.缺失惩罚;
        } else {
            const auto* 左主信息 = 取特征主信息(左迭代器->second);
            const auto* 右主信息 = 取特征主信息(右迭代器->second);
            if (!左主信息 || !右主信息 || !特征值有效(左主信息->当前值) || !特征值有效(右主信息->当前值)) {
                差异度 = 参数.缺失惩罚;
            } else if (差异度函数_) {
                差异度 = 差异度函数_(类型, 左主信息->当前值, 右主信息->当前值);
            } else if (const auto* 左标量 = std::get_if<I64>(&左主信息->当前值)) {
                if (const auto* 右标量 = std::get_if<I64>(&右主信息->当前值)) {
                    差异度 = 私有_绝对值饱和(私有_饱和减(*左标量, *右标量));
                } else {
                    差异度 = 参数.缺失惩罚;
                }
            } else {
                差异度 = 私有_特征值严格相等(左主信息->当前值, 右主信息->当前值)
                    ? 0
                    : 参数.缺失惩罚;
            }
        }

        if (!缺失A && !缺失B && 差异度 == 0) {
            ++结果.命中特征数;
        }

        权重和 = 私有_饱和加(权重和, 比较权重);
        if (比较权重 > 0) {
            if (差异度 > 0 && 差异度 > I64_MAX / 比较权重) {
                加权差异和 = I64_MAX;
            } else {
                加权差异和 = 私有_饱和加(加权差异和, 差异度 * 比较权重);
            }
        }
    }

    结果.总差异度 = 权重和 > 0 ? (加权差异和 / 10000) : 0;
    结果.归一化差异度 = (参数.归一化 && 权重和 > 0)
        ? (加权差异和 / 权重和)
        : 结果.总差异度;
    return 结果;
}

// 功能：根据当前输入生成目标数据、场景、动态或回执。
std::string 特征类::生成度量签名(const 特征节点类* 节点) const
{
    const auto* 主信息 = 取特征主信息(节点);
    std::ostringstream 输出;
    输出 << "Feature";
    if (主信息 && 主信息->类型) {
        输出 << "|T=" << 主信息->类型->获取主键();
    }
    if (主信息 && 主信息->名称) {
        输出 << "|N=" << 主信息->名称->获取主键();
    }

    if (主信息) {
        if (std::holds_alternative<I64>(主信息->当前值)) {
            输出 << "|V=I64";
        } else if (std::holds_alternative<VecU句柄>(主信息->当前值)) {
            输出 << "|V=VecU";
        } else if (std::holds_alternative<指针句柄>(主信息->当前值)) {
            输出 << "|V=Ptr";
        } else {
            输出 << "|V=None";
        }
    }
    return 输出.str();
}
