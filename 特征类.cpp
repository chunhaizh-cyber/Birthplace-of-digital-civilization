// 功能：按函数名执行对应处理。
bool 特征类::校验抽象特征子链(const 基础信息节点类* 抽象特征节点) const
{
    if (!基础信息_ || !抽象特征节点) return false;

    const auto* 主信息 = 取抽象特征主信息(static_cast<const 抽象特征节点类*>(抽象特征节点));
    if (!主信息 || !主信息->校验结构()) return false;

    const auto 子抽象 = 私有_直接基础信息子节点_按类型<抽象特征主信息类>(*基础信息_, 抽象特征节点);
    const auto 全部子 = 私有_直接基础信息子节点(*基础信息_, 抽象特征节点);

    if (主信息->是叶子特征()) {
        return true;
    }

    if (全部子.size() != 子抽象.size()) {
        return false;
    }

    std::vector<const 语素入口节点类*> 已见名称{};
    for (auto* 子节点 : 子抽象) {
        const auto* 子信息 = 取抽象特征主信息(static_cast<const 抽象特征节点类*>(子节点));
        if (!子信息 || !子信息->校验结构() || !子信息->名称) {
            return false;
        }
        for (const auto* 已见 : 已见名称) {
            if (语素入口同一(已见, 子信息->名称)) {
                return false;
            }
        }
        已见名称.push_back(子信息->名称);

        if (!校验抽象特征子链(static_cast<const 抽象特征节点类*>(子节点))) {
            return false;
        }
    }

    return true;
}

