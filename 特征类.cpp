// 功能：按函数名执行对应处理。
抽象特征节点类* 特征类::升格当前稳态为抽象区间(特征节点类* 实例特征)
{
    auto* 实例主信息 = 取特征主信息(实例特征);
    auto* 抽象特征 = 实例主信息 ? 实例主信息->抽象特征.指针 : nullptr;
    auto* 抽象主信息 = 取抽象特征主信息(static_cast<抽象特征节点类*>(抽象特征));
    if (!实例主信息 || !抽象特征 || !抽象主信息) return nullptr;
    if (实例主信息->当前稳态索引 < 0
        || 实例主信息->当前稳态索引 >= static_cast<int>(实例主信息->稳态列表.size())) {
        return nullptr;
    }

    const auto& 稳态 = 实例主信息->稳态列表[static_cast<std::size_t>(实例主信息->当前稳态索引)];
    const auto* 标量 = std::get_if<I64>(&稳态.值);
    if (!标量 && !稳态.区间.has_value()) return nullptr;

    const I64区间 新区间 = (稳态.区间.has_value() && 稳态.区间->有效())
        ? *稳态.区间
        : I64区间::点(*标量);

    if (!抽象主信息->区间.has_value() || !抽象主信息->区间->有效()) {
        抽象主信息->区间 = 新区间;
        抽象主信息->设为叶子特征(I64值域{ { I64值域项{新区间} } });
        抽象主信息->来源实例特征.emplace_back(static_cast<基础信息节点类*>(实例特征));
        return static_cast<抽象特征节点类*>(抽象特征);
    }

    if (私有_区间相同(*抽象主信息->区间, 新区间)) {
        return static_cast<抽象特征节点类*>(抽象特征);
    }

    for (auto* 子节点 : 私有_直接基础信息子节点_按类型<抽象特征主信息类>(*基础信息_, 抽象特征)) {
        auto* 子主信息 = 取抽象特征主信息(static_cast<抽象特征节点类*>(子节点));
        if (子主信息 && 子主信息->区间.has_value() && 私有_区间相同(*子主信息->区间, 新区间)) {
            return static_cast<抽象特征节点类*>(子节点);
        }
    }

    auto* 新主信息 = new 抽象特征主信息类{};
    新主信息->名称 = 抽象主信息->名称;
    新主信息->类型 = 抽象主信息->类型;
    新主信息->区间 = 新区间;
    新主信息->设为叶子特征(I64值域{ { I64值域项{新区间} } });
    新主信息->来源实例特征.emplace_back(static_cast<基础信息节点类*>(实例特征));
    return 创建抽象特征(抽象特征, 新主信息);
}

