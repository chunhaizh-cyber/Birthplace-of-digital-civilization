// 功能：按函数名执行对应处理。
bool 特征类::特征值命中值域(const 特征值& 值, const 特征值域& 值域) const
{
    if (std::holds_alternative<空集合值域>(值域)) {
        return false;
    }
    if (std::holds_alternative<空值值域>(值域)) {
        return std::holds_alternative<std::monostate>(值);
    }
    if (const auto* I64域 = std::get_if<I64值域>(&值域)) {
        const auto* 标量 = std::get_if<I64>(&值);
        if (!标量) return false;
        for (const auto& 项 : I64域->项集) {
            if (私有_I64值域项包含(项, *标量)) {
                return true;
            }
        }
        return false;
    }
    if (const auto* VecU域 = std::get_if<VecU句柄值域>(&值域)) {
        const auto* 句柄 = std::get_if<VecU句柄>(&值);
        if (!句柄) return false;
        return std::find(VecU域->允许句柄.begin(), VecU域->允许句柄.end(), *句柄) != VecU域->允许句柄.end();
    }
    if (const auto* 指针域 = std::get_if<指针句柄值域>(&值域)) {
        const auto* 句柄 = std::get_if<指针句柄>(&值);
        if (!句柄 || !句柄->有效()) return false;

        auto* 具体目标 = reinterpret_cast<基础信息节点类*>(句柄->指针);
        if (!具体目标) return false;

        for (const auto& 抽象引用 : 指针域->允许目标抽象) {
            auto* 抽象目标 = 抽象引用.指针;
            if (!抽象目标 && 抽象引用.主键.empty()) {
                continue;
            }
            if (!抽象目标 && 基础信息_) {
                for (auto* 节点 : 基础信息_->枚举全部节点()) {
                    if (节点 && 节点->获取主键() == 抽象引用.主键) {
                        抽象目标 = 节点;
                        break;
                    }
                }
            }
            if (!抽象目标) {
                continue;
            }
            if (抽象目标 == 具体目标) {
                return true;
            }
            if (取抽象特征主信息(static_cast<抽象特征节点类*>(抽象目标))
                && 取特征主信息(static_cast<特征节点类*>(具体目标))
                && 匹配抽象特征(
                    static_cast<抽象特征节点类*>(抽象目标),
                    static_cast<特征节点类*>(具体目标))) {
                return true;
            }
        }
        return false;
    }
    return false;
}

// 功能：按函数名执行对应处理。
bool 特征类::匹配抽象特征(const 抽象特征节点类* 抽象特征, const 特征节点类* 实例特征) const
{
    const auto* 抽象主信息 = 取抽象特征主信息(抽象特征);
    const auto* 实例主信息 = 取特征主信息(实例特征);
    if (!抽象主信息 || !实例主信息 || !抽象主信息->校验结构()) {
        return false;
    }

    if (!语素入口同一(抽象主信息->名称, 实例主信息->名称)
        || !语素入口同一(抽象主信息->类型, 实例主信息->类型)) {
        return false;
    }

    if (抽象主信息->是叶子特征()) {
        const auto* 值域 = 抽象主信息->取值域();
        return 值域 && 特征值命中值域(实例主信息->当前值, *值域);
    }

    if (!抽象主信息->是复合特征() || 抽象主信息->值域.has_value()) {
        return false;
    }

    if (!校验抽象特征子链(抽象特征)) {
        return false;
    }

    for (auto* 抽象子节点 : 私有_直接基础信息子节点_按类型<抽象特征主信息类>(*基础信息_, 抽象特征)) {
        const auto* 抽象子信息 = 取抽象特征主信息(static_cast<const 抽象特征节点类*>(抽象子节点));
        if (!抽象子信息 || !抽象子信息->名称) {
            return false;
        }
        auto* 实例子节点 = 查找子特征_按名称(实例特征, 抽象子信息->名称);
        if (!实例子节点) {
            return false;
        }
        if (!匹配抽象特征(static_cast<const 抽象特征节点类*>(抽象子节点), 实例子节点)) {
            return false;
        }
    }
    return true;
}

// 功能：按条件查找目标对象、方法或事实。
特征节点类* 特征类::查找实例特征_按抽象特征(
    const 基础信息节点类* 宿主,
    const 抽象特征节点类* 抽象特征) const
{
    if (!宿主 || !抽象特征) return nullptr;

    const auto* 抽象主信息 = 取抽象特征主信息(抽象特征);
    for (auto* 节点 : 获取子特征(宿主)) {
        const auto* 主信息 = 取特征主信息(节点);
        if (主信息 && 私有_节点引用相同(抽象特征, 主信息->抽象特征)) {
            return 节点;
        }
        if (抽象主信息
            && 主信息
            && 语素入口同一(抽象主信息->名称, 主信息->名称)
            && 语素入口同一(抽象主信息->类型, 主信息->类型)
            && 匹配抽象特征(抽象特征, 节点)) {
            return 节点;
        }
    }
    return nullptr;
}

// 功能：创建并返回或登记对应对象。
特征节点类* 特征类::取或创建实例特征_按抽象特征(
    基础信息节点类* 宿主,
    抽象特征节点类* 抽象特征)
{
    if (!宿主 || !抽象特征) return nullptr;
    if (auto* 命中 = 查找实例特征_按抽象特征(宿主, 抽象特征)) {
        return 命中;
    }

    const auto* 抽象主信息 = 取抽象特征主信息(抽象特征);
    if (!抽象主信息) return nullptr;

    auto* 主信息 = new 特征节点主信息类{};
    主信息->名称 = 抽象主信息->名称;
    主信息->类型 = 抽象主信息->类型;
    主信息->抽象特征.绑定(抽象特征);
    return 创建特征(宿主, 主信息);
}

// 功能：把处理结果写入指定对象、场景或日志。
特征写入结果 特征类::写入特征值_按参数(特征节点类* 节点, const 特征值& 值, const 写入参数& 参数)
{
    特征写入结果 结果{};
    结果.特征 = 节点;

    auto* 主信息 = 取特征主信息(节点);
    if (!主信息 || !特征值有效(值)) return 结果;

    const auto 现在 = 参数.ts != 0 ? 参数.ts : 结构体_时间戳::当前_微秒();
    主信息->当前值 = 值;
    主信息->统计.记录观测(现在);
    主信息->近帧候选.push(值);
    主信息->近帧时间.push(现在);
    (void)解析实例特征命中抽象特征(节点);

    if (参数.仅更新当前值) {
        return 结果;
    }

    const auto 计算差异度 = [&](const 特征值& 左值, const 特征值& 右值) noexcept -> I64 {
        I64 差异度 = 私有_默认不同值;
        if (差异度函数_) {
            差异度 = 差异度函数_(主信息->类型, 左值, 右值);
        } else if (const auto* 左标量 = std::get_if<I64>(&左值)) {
            if (const auto* 右标量 = std::get_if<I64>(&右值)) {
                差异度 = 私有_绝对值饱和(私有_饱和减(*左标量, *右标量));
            } else {
                差异度 = 私有_默认不同值;
            }
        } else {
            差异度 = 私有_特征值严格相等(左值, 右值) ? 0 : 私有_默认不同值;
        }

        if (const auto* 左标量 = std::get_if<I64>(&左值)) {
            const auto* 右标量 = std::get_if<I64>(&右值);
            if (右标量 && 主信息->连续测量误差区间.有效()) {
                const I64 delta = 私有_饱和减(*左标量, *右标量);
                return 私有_点到区间距离(delta, 主信息->连续测量误差区间);
            }
        }
        return 差异度;
    };

    const auto& 策略 = 参数.稳态;
    const int 连续帧要求 = std::max(2, 策略.连续N);
    if (主信息->近帧候选.size < static_cast<std::size_t>(连续帧要求)) {
        return 结果;
    }

    bool 稳定 = true;
    for (int i = 1; i < 连续帧要求; ++i) {
        const auto* 历史值 = 主信息->近帧候选.get_from_latest(static_cast<std::size_t>(i));
        if (!历史值 || 计算差异度(值, *历史值) > 策略.阈值_判稳) {
            稳定 = false;
            break;
        }
    }

    结果.通过候选门 = 稳定;
    if (!稳定) {
        return 结果;
    }

    const int 旧稳态索引 = 主信息->当前稳态索引;
    int 命中稳态索引 = -1;
    for (std::size_t i = 0; i < 主信息->稳态列表.size(); ++i) {
        auto& 稳态 = 主信息->稳态列表[i];
        if (!特征值有效(稳态.值)) continue;
        if (计算差异度(值, 稳态.值) <= 策略.阈值_命中原型) {
            命中稳态索引 = static_cast<int>(i);
            稳态.命中次数 += 1;
            稳态.最后命中 = 现在;
            if (const auto* 标量 = std::get_if<I64>(&值)) {
                稳态.区间 = I64区间::点(*标量);
            }
            break;
        }
    }

    if (命中稳态索引 < 0 && 参数.允许创建稳态) {
        特征稳态 新稳态{};
        新稳态.值 = 值;
        新稳态.命中次数 = 1;
        新稳态.最后命中 = 现在;
        if (const auto* 标量 = std::get_if<I64>(&值)) {
            新稳态.区间 = I64区间::点(*标量);
        }
        主信息->稳态列表.push_back(新稳态);
        命中稳态索引 = static_cast<int>(主信息->稳态列表.size()) - 1;
    }

    主信息->当前稳态索引 = 命中稳态索引;
    结果.稳态发生变化 = (命中稳态索引 >= 0 && 命中稳态索引 != 旧稳态索引);

    if (参数.允许淘汰 && 策略.淘汰_超时 > 0) {
        auto& 稳态列表 = 主信息->稳态列表;
        int 新当前稳态索引 = 主信息->当前稳态索引;
        for (std::size_t i = 0; i < 稳态列表.size();) {
            const auto& 稳态 = 稳态列表[i];
            const bool 超时 = 稳态.最后命中 > 0
                && 现在 > 稳态.最后命中
                && (现在 - 稳态.最后命中) > 策略.淘汰_超时;
            if (!超时) {
                ++i;
                continue;
            }

            if (新当前稳态索引 == static_cast<int>(i)) {
                新当前稳态索引 = -1;
            } else if (新当前稳态索引 > static_cast<int>(i)) {
                --新当前稳态索引;
            }
            稳态列表.erase(稳态列表.begin() + static_cast<std::ptrdiff_t>(i));
        }
        主信息->当前稳态索引 = 新当前稳态索引;
    }

    if (策略.Kmax_points > 0 && static_cast<int>(主信息->稳态列表.size()) > 策略.Kmax_points) {
        auto& 稳态列表 = 主信息->稳态列表;
        while (static_cast<int>(稳态列表.size()) > 策略.Kmax_points) {
            std::size_t 最弱索引 = 0;
            for (std::size_t i = 1; i < 稳态列表.size(); ++i) {
                const auto& 候选 = 稳态列表[i];
                const auto& 当前最弱 = 稳态列表[最弱索引];
                if (候选.命中次数 < 当前最弱.命中次数
                    || (候选.命中次数 == 当前最弱.命中次数 && 候选.最后命中 < 当前最弱.最后命中)) {
                    最弱索引 = i;
                }
            }

            if (主信息->当前稳态索引 == static_cast<int>(最弱索引)) {
                主信息->当前稳态索引 = -1;
            } else if (主信息->当前稳态索引 > static_cast<int>(最弱索引)) {
                --主信息->当前稳态索引;
            }

            稳态列表.erase(稳态列表.begin() + static_cast<std::ptrdiff_t>(最弱索引));
        }
    }

    return 结果;
}

