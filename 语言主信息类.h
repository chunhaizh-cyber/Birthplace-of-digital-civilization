#pragma once

#include "语言节点类型.h"
#include "语素节点类型.h"
#include "基础信息节点类型.h"

#include "基础数据类型.h"

// ============================================================================
// 自然语言成分
// ============================================================================
class 自然语言成分基类 {
public:
    virtual ~自然语言成分基类() = default;
};

class 文章主信息类 : public 自然语言成分基类 {
public:
    // 文章主信息只保存自然语言文档结构和文本解析入口。
    // 文章内容触发需求、任务、动态或因果时，必须通过解析结果与正式领域入口生成，不能把治理结论写回文章主信息。
    std::string 标题{};
    std::string 原始文本{};
    std::string 作者{};
    std::string 来源{};
    // 仅作为文本解析进入世界层的场景锚点；该引用本身不是世界事实或任务/需求状态。
    可解析引用<场景节点类> 对应文本世界场景{};
};

class 段落主信息类 : public 自然语言成分基类 {
public:
    // 段落主信息只表达文档中的段落位置和原始文本。
    // 段落解析出的需求、任务、方法或世界事实必须写入对应领域结构，不回写为段落字段。
    std::size_t 在文章中的序号 = 0;
    std::string 原始文本{};
};

class 自然句主信息类 : public 自然语言成分基类 {
public:
    // 自然句主信息只保存句子在段落中的位置、词序列和原始文本。
    // 句子解析出的治理含义必须转入正式特征、需求、任务或因果链，不在自然句字段中缓存结论。
    std::size_t 在段落中的序号 = 0;
    std::vector<可解析引用<const 语素入口节点类>> 词序列{};
    std::string 原始文本{};
};

class 子句主信息类 : public 自然语言成分基类 {
public:
    // 子句主信息只表达自然语言子句的结构片段和解析锚点。
    // 子句产生的需求候选、方法候选、动态候选或因果候选必须通过正式领域入口生成。
    枚举_原子结构类型 原子结构类型 = 枚举_原子结构类型::未定义;
    std::size_t 起始词索引 = 0;
    std::size_t 结束词索引 = 0;
    std::vector<可解析引用<const 语素入口节点类>> 局部词序列{};

    // 以下引用仅表示文本解析结果关联到世界层对象；引用目标本身才承载事实，子句主信息不复制这些事实。
    可解析引用<场景节点类> 对应场景{};
    可解析引用<状态节点类> 对应状态{};
    可解析引用<动态节点类> 对应动态{};
    可解析引用<因果节点类> 对应因果{};
};
