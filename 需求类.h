    static 节点类* 获取独立树根_已加锁(节点类* 节点) noexcept
    {
        while (节点 && 节点->父) {
            节点 = static_cast<节点类*>(节点->父);
        }
        return 节点;
    }

    // 功能：按函数名执行对应处理。
    static 节点类* 按主键定位节点_已加锁(
        节点类* 需求根节点,
        const std::string& 主键) noexcept
    {
        if (!需求根节点 || 主键.empty()) {
            return nullptr;
        }

        for (auto* 当前节点 = 需求根节点->链下;
             当前节点 && 当前节点 != 需求根节点;
             当前节点 = 当前节点->链下) {
            if (当前节点->获取主键() == 主键) {
                return 当前节点;
            }
        }
        return nullptr;
    }

    // 功能：按函数名执行对应处理。
    static bool 节点属于独立树_已加锁(
        const 节点类* 需求根节点,
        const 节点类* 候选节点) noexcept
    {
        if (!需求根节点 || !候选节点) {
            return false;
        }
        if (需求根节点 == 候选节点) {
            return true;
        }

        for (auto* 当前节点 = 需求根节点->链下;
             当前节点 && 当前节点 != 需求根节点;
             当前节点 = 当前节点->链下) {
            if (当前节点 == 候选节点) {
                return true;
            }
        }
        return false;
    }

