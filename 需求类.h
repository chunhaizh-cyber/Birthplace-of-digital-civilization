    // 功能：计算权重、状态、差值或派生结果。
    static 结构_子需求平分权重 计算子需求权重(
        const std::int64_t 父需求安全权重,
        const std::int64_t 父需求服务权重,
        const std::int64_t 活跃子需求数量,
        const std::int64_t 活跃子需求序号,
        const bool OR关系) noexcept
    {
        结构_子需求平分权重 输出{};
        if (活跃子需求数量 <= 0) {
            return 输出;
        }

        const auto 计算单向权重 = [活跃子需求数量, 活跃子需求序号, OR关系](
            const std::int64_t 父权重) noexcept -> std::int64_t {
            if (父权重 <= 0) {
                return 0;
            }
            if (OR关系) {
                return 父权重;
            }
            const auto 基础份额 = 父权重 / 活跃子需求数量;
            const auto 余数 = 父权重 % 活跃子需求数量;
            return 基础份额 + (活跃子需求序号 < 余数 ? 1 : 0);
        };

        输出.安全权重 = 计算单向权重(父需求安全权重);
        输出.服务权重 = 计算单向权重(父需求服务权重);
        return 输出;
    }

    // 功能：计算权重、状态、差值或派生结果。
    static 结构_子需求平分权重 计算子需求平分权重(
        const std::int64_t 父需求安全权重,
        const std::int64_t 父需求服务权重,
        const std::int64_t 子需求数量) noexcept
    {
        return 计算子需求权重(
            父需求安全权重,
            父需求服务权重,
            子需求数量,
            0,
            false);
    }

    // 功能：计算权重、状态、差值或派生结果。
    static 结构_子需求平分权重 计算子需求平分权重(const 节点类* 父需求) noexcept
    {
        if (!父需求 || 父需求->子节点数量 <= 0) {
            return {};
        }
        return 计算子需求权重(
            父需求->主信息.安全权重,
            父需求->主信息.服务权重,
            父需求->子节点数量,
            0,
            子需求权重采用OR关系(父需求));
    }

    // 功能：按函数名执行对应处理。
    static bool 子需求权重采用OR关系(const 节点类* 父需求) noexcept
    {
        return 需求目标语义视图(父需求).逻辑组织类型
            == 枚举_逻辑组织需求类型::OR组;
    }

    // 功能：按函数名执行对应处理。
