    template<class T节点>
    static bool 写入引用_来自指令_已加锁(
        可解析引用<T节点>& 输出,
        const std::uintptr_t 指针,
        const std::string& 主键) noexcept
    {
        if (指针 == 0 && 主键.empty()) {
            return false;
        }

        if (指针 != 0) {
            auto* 节点 = reinterpret_cast<T节点*>(指针);
            输出.指针 = 节点;
            输出.主键 = 节点 ? 节点->获取主键() : 主键;
            if (输出.主键.empty()) {
                输出.主键 = 主键;
            }
            return true;
        }

        输出.指针 = nullptr;
        输出.主键 = 主键;
        return true;
    }

