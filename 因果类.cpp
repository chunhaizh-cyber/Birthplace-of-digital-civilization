// 功能：判断因果模板结果侧是否命中指定动态的状态迁移。
static bool 私有_因果模板状态迁移命中动态(
    基础信息类* 基础信息,
    const 因果主信息类* 模板,
    const 动态节点类* 动态节点,
    const std::vector<二次特征节点类*>& 状态迁移模板集合,
    const 特征节点类* 动态结果特征)
{
    if (!模板 || !动态节点) return false;
    if (!私有_因果模板果侧可用(模板)) return false;
    if (动态结果特征 && !私有_因果模板结果命中特征(基础信息, 模板, 动态结果特征)) {
        return false;
    }
    if (!模板->主果比较模板.有效()) {
        return false;
    }
    for (auto* 状态迁移模板 : 状态迁移模板集合) {
        if (私有_引用等于节点(模板->主果比较模板, 状态迁移模板)) {
            return true;
        }
        if (私有_状态迁移方向相同_因果(
                模板->主果比较模板.指针,
                状态迁移模板)) {
            return true;
        }
    }
    return 私有_状态迁移模板命中动态(
        基础信息,
        模板->主果比较模板.指针,
        动态节点);
}

// 功能：判断动作因果模板是否命中指定动态动作来源。
static bool 私有_因果模板动作命中动态(
    const 因果主信息类* 模板,
    基础信息类* 基础信息,
    const 动态节点类* 动态节点,
    const std::string& 动作语义键)
{
    if (!模板 || !动态节点 || !私有_因果模板有动作(模板)) return false;
    auto* base = 私有_选择基础信息(基础信息);
    状态节点类* 初始状态 = nullptr;
    状态节点类* 结果状态 = nullptr;
    方法节点类* 来源动作 = nullptr;
    const 语素入口节点类* 来源动作名 = nullptr;
    const 语素入口节点类* 动态类型 = nullptr;
    std::uint32_t 动态层级 = 0;
    动态类 动态服务(base);
    if (!动态服务.读取动态因果生成输入(
            动态节点,
            初始状态,
            结果状态,
            来源动作,
            来源动作名,
            动态类型,
            动态层级)) {
        return false;
    }
    if (模板->因方法模板.有效()) {
        if (!来源动作) return false;
        if (!私有_方法引用命中目标(模板->因方法模板, 来源动作)) return false;
    } else if (来源动作) {
        return false;
    }
    if (!模板->因动作语义键.empty() || !动作语义键.empty()) {
        if (模板->因动作语义键.empty() || 动作语义键.empty()) return false;
        if (模板->因动作语义键 != 动作语义键) return false;
    }
    const auto 动态动作名称 = 私有_动作名键(来源动作名);
    if (!模板->因动作名称.empty()) {
        if (动态动作名称.empty() || 模板->因动作名称 != 动态动作名称) {
            return false;
        }
    } else if (!动态动作名称.empty()) {
        return false;
    }
    return true;
}

