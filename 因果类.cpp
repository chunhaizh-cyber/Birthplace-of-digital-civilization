// 功能：服务所在模块的内部辅助流程。
static bool 私有_状态引用命中目标(
    基础信息类* 基础信息,
    const 可解析引用<状态节点类>& 状态引用,
    const 状态节点类* 目标状态)
{
    if (!目标状态) return false;
    if (私有_引用等于节点(状态引用, 目标状态)) return true;

    auto* 基础信息集 = 基础信息 ? 基础信息 : &获取基础信息集();
    const auto* 候选状态 = 状态引用.指针;
    if (!候选状态 && !状态引用.主键.empty() && 基础信息集) {
        候选状态 = reinterpret_cast<const 状态节点类*>(
            基础信息集->查找主键(状态引用.主键));
    }
    if (!候选状态) return false;

    特征类 特征服务(基础信息集);
    const auto 比较 = 特征服务.比较状态(候选状态, 目标状态);
    return 比较.可比较 && 比较.关系 == 枚举_三向关系::等于;
}

// 功能：判断两个特征节点是否指向同一特征。
static bool 私有_特征节点命中目标(const 特征节点类* 候选特征, const 特征节点类* 目标特征) noexcept
{
    if (!候选特征 || !目标特征) return false;
    const auto 候选键 = 私有_节点键(候选特征);
    const auto 目标键 = 私有_节点键(目标特征);
    return !候选键.empty() && 候选键 == 目标键;
}

// 功能：判断特征引用是否指向目标特征。
static bool 私有_特征引用命中目标(
    基础信息类* 基础信息,
    const 可解析引用<特征节点类>& 特征引用,
    const 特征节点类* 目标特征) noexcept
{
    if (!目标特征) return false;
    if (私有_引用等于节点(特征引用, 目标特征)) return true;
    return 私有_特征节点命中目标(
        私有_解析特征引用_因果(基础信息, 特征引用),
        目标特征);
}

// 功能：判断因果模板条件侧是否与动态条件特征相同。
static bool 私有_因果模板条件命中特征(
    基础信息类* 基础信息,
    const 因果主信息类* 模板,
    const 特征节点类* 条件特征) noexcept
{
    if (!模板) return false;
    if (!条件特征) {
        return 模板->条件比较模板.empty();
    }
    if (模板->条件比较模板.size() != 1) {
        return false;
    }
    return 私有_特征引用命中目标(基础信息, 模板->条件比较模板.front(), 条件特征);
}

// 功能：判断状态节点是否命中目标状态。
static bool 私有_状态节点命中目标(
    基础信息类* 基础信息,
    const 状态节点类* 候选状态,
    const 状态节点类* 目标状态)
{
    if (!候选状态 || !目标状态) return false;
    if (私有_节点键(候选状态) == 私有_节点键(目标状态)) return true;
    auto* 基础信息集 = 基础信息 ? 基础信息 : &获取基础信息集();
    特征类 特征服务(基础信息集);
    const auto 比较 = 特征服务.比较状态(候选状态, 目标状态);
    return 比较.可比较 && 比较.关系 == 枚举_三向关系::等于;
}

// 功能：判断状态节点的结果特征是否命中目标特征。
static bool 私有_状态结果特征命中目标(
    基础信息类* 基础信息,
    const 状态节点类* 状态,
    const 特征节点类* 目标特征) noexcept
{
    return 私有_特征节点命中目标(
        私有_状态结果特征_因果(基础信息, 状态),
        目标特征);
}

// 功能：服务所在模块的内部辅助流程。
