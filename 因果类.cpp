// 功能：按函数名执行对应处理。
std::vector<因果节点类*> 因果类::枚举全部因果() const
{
    std::vector<因果节点类*> out;
    auto* base = 私有_选择基础信息(基础信息_);
    if (!base) return out;
    for (auto* n : base->枚举节点_按类型<因果主信息类>()) {
        out.push_back(reinterpret_cast<因果节点类*>(n));
    }
    return out;
}

// 功能：按函数名执行对应处理。
std::vector<因果模板节点类*> 因果类::枚举因果模板() const
{
    std::vector<因果模板节点类*> out;
    for (auto* n : 枚举全部因果()) {
        auto* 主信息 = 取因果主信息(n);
        if (主信息
            && 主信息->主果比较模板.有效()
            && 私有_因果模板果侧可用(主信息)) {
            out.push_back(reinterpret_cast<因果模板节点类*>(n));
        }
    }
    return out;
}

// 功能：为生成因果信息命中的现有模板追加证据动态。
bool 因果类::追加证据动态样本(因果模板节点类* 节点, 动态节点类* 证据动态)
{
    auto* m = 取模板主信息(节点);
    if (!m || !证据动态) return false;
    if (!私有_因果模板果侧可用(m)) return false;
    if (私有_登记证据动态样本(m->证据动态样本, 证据动态)) {
        更新因果证据计数(
            节点,
            !m->条件比较模板.empty(),
            true,
            true,
            true,
            0);
    }
    return true;
}

// 功能：按函数名执行对应处理。
bool 因果类::二次特征匹配模板(const 二次特征节点类* 二次特征, const 二次特征节点类* 模板) const noexcept
{
    auto* base = 私有_选择基础信息(基础信息_);
    二次特征类 二次特征服务(base);
    return 二次特征服务.二次特征模板匹配(二次特征, 模板);
}

// 功能：按函数名执行对应处理。
bool 因果类::因果模板匹配二次特征(
    const 因果模板节点类* 模板,
    const std::vector<二次特征节点类*>&,
    const std::vector<二次特征节点类*>& 结果候选) const noexcept
{
    auto* m = 取模板主信息(模板);
    if (!m) return false;
    if (!私有_因果模板果侧可用(m)) return false;

    if (!m->主果比较模板.有效()) {
        return false;
    }
    bool 主果命中 = false;
    for (auto* c : 结果候选) {
        if (m->主果比较模板.指针 && 二次特征匹配模板(c, m->主果比较模板.指针)) {
            主果命中 = true;
            break;
        }
    }
    return 主果命中;
}

// 功能：按条件查找目标对象、方法或事实。
std::vector<因果模板节点类*> 因果类::查找匹配因果模板(
    枚举_因果锚点类型 锚点类型,
    std::uint32_t 状态层级,
    const std::vector<二次特征节点类*>& 条件候选,
    const std::vector<二次特征节点类*>& 结果候选) const
{
    std::vector<因果模板节点类*> out;
    for (auto* n : 枚举因果模板()) {
        auto* m = 取模板主信息(n);
        if (!m) continue;
        if (锚点类型 != 枚举_因果锚点类型::未定义 && m->适用锚点类型 != 锚点类型) continue;
        if (状态层级 != 0 && m->适用层级 != 状态层级) continue;
        if (因果模板匹配二次特征(n, 条件候选, 结果候选)) out.push_back(n);
    }
    return out;
}

// 功能：把因果模板转换为基础命名显示使用的自然语言。
std::string 因果类::生成抽象因果自然语言(const 因果模板节点类* 节点) const
{
    auto* m = 取模板主信息(节点);
    if (!m) return {};

    std::vector<std::string> 条件短语{};
    for (const auto& c : m->条件比较模板) {
        条件短语.push_back("条件比较模板:" + 私有_引用键(c));
    }

    std::string 主结果短语{};
    if (m->主果比较模板.有效()) {
        主结果短语 = "主果比较模板:" + 私有_引用键(m->主果比较模板);
    }
    if (主结果短语.empty() && !m->证据动态样本.empty()) {
        auto* d = m->证据动态样本.front().指针;
        状态节点类* 初始状态 = nullptr;
        状态节点类* 结果状态 = nullptr;
        方法节点类* 来源动作 = nullptr;
        const 语素入口节点类* 来源动作名 = nullptr;
        const 语素入口节点类* 动态类型 = nullptr;
        std::uint32_t 动态层级 = 0;
        auto* base = 私有_选择基础信息(基础信息_);
        动态类 动态服务(base);
        if (动态服务.读取动态因果生成输入(
                d,
                初始状态,
                结果状态,
                来源动作,
                来源动作名,
                动态类型,
                动态层级)
            && 结果状态) {
            主结果短语 = "状态:" + 私有_节点键(结果状态);
        }
    }

    const std::string 动作短语 = !m->因动作语义键.empty() ? m->因动作语义键 : m->因动作名称;
    std::ostringstream os;
    if (!条件短语.empty()) {
        os << "若";
        for (std::size_t i = 0; i < 条件短语.size(); ++i) {
            if (i) os << "、";
            os << 条件短语[i];
        }
        os << "，";
    }
    if (!动作短语.empty()) os << "动作[" << 动作短语 << "]会导致";
    else os << "会发生";
    os << (主结果短语.empty() ? "状态变化" : 主结果短语);
    os << "；证据成立" << m->成立次数 << "次，失败" << m->失败次数 << "次。";
    return os.str();
}
