// 功能：根据当前输入生成目标数据、场景、动态或回执。
static std::vector<私有_目标投影路径> 私有_按目标特征类型生成规则投影路径(
    基础信息节点类* 目标宿主,
    特征节点类* 目标特征,
    const 语素入口节点类* 目标特征类型词,
    const 需求节点类* 来源需求)
{
    std::vector<私有_目标投影路径> out;
    auto 追加 = [&](std::uint32_t 层级) {
        out.push_back(私有_构造规则投影路径(目标宿主, 目标特征, 目标特征类型词, 层级));
    };

    if (!目标特征 && !目标特征类型词) return out;

    if (私有_目标特征类型是安全账务值(目标特征类型词)) {
        auto 路径 = 私有_构造规则投影路径(
            目标宿主,
            目标特征,
            目标特征类型词,
            0);
        私有_追加因果缺失证据(
            路径.缺失证据,
            枚举_因果缺失证据类型::安全账务目标需先证明安全目标特征实际变化);
        out.push_back(std::move(路径));
        return out;
    }
    if (私有_目标特征类型是服务账务值(目标特征类型词)) {
        auto 路径 = 私有_构造规则投影路径(
            目标宿主,
            目标特征,
            目标特征类型词,
            0);
        私有_追加因果缺失证据(
            路径.缺失证据,
            枚举_因果缺失证据类型::服务账务目标需先证明服务目标特征实际变化);
        out.push_back(std::move(路径));
        return out;
    }

    if (私有_目标特征类型是直接安全目标(目标特征类型词)) {
        追加(1);
        return out;
    }

    if (私有_目标特征类型是任务层状态(目标特征类型词)) {
        if (需求类::来源需求有安全方向(来源需求)) {
            追加(2);
            return out;
        }
        追加(需求类::来源需求有服务方向(来源需求) ? 2 : 0);
        return out;
    }

    if (私有_目标特征类型是方法层状态(目标特征类型词) || 私有_目标特征类型是学习层状态(目标特征类型词)) {
        追加((需求类::来源需求有安全方向(来源需求) || 需求类::来源需求有服务方向(来源需求)) ? 3 : 1);
        return out;
    }

    追加(私有_按特征语义推断结算贡献层级(目标特征类型词, 来源需求));
    return out;
}

// 功能：根据当前输入生成目标数据、场景、动态或回执。
static 私有_目标投影路径 私有_从状态转换边生成目标投影路径(
    const 私有_状态转换因果边& 边)
{
    私有_目标投影路径 路径{};
    auto* base = 私有_当前世界树基础信息();
    状态类 状态服务(base);
    基础信息节点类* 状态主体 = nullptr;
    特征节点类* 状态特征 = nullptr;
    if (!状态服务.读取状态主体与特征(边.结果状态, 状态主体, 状态特征)) {
        私有_追加因果缺失证据(路径.缺失证据, 枚举_因果缺失证据类型::缺结果状态主信息);
        return 路径;
    }

    路径.目标宿主 = 状态主体;
    路径.目标特征类型 = 状态特征;
    路径.目标特征类型词 = 私有_特征语义类型(路径.目标特征类型);
    路径.因果距离层级 = 1;
    路径.结算贡献层级 = 私有_按特征语义推断结算贡献层级(路径.目标特征类型, nullptr);

    if (!路径.目标特征类型) {
        私有_追加因果缺失证据(路径.缺失证据, 枚举_因果缺失证据类型::缺目标特征类型);
    }
    if (路径.结算贡献层级 == 0) {
        私有_追加因果缺失证据(路径.缺失证据, 枚举_因果缺失证据类型::缺结算贡献层级判定规则);
    }
    return 路径;
}

// 功能：生成内部状态转换因果投影，供因果类内部链路查询使用。
static 私有_状态转换因果投影 私有_生成状态转换因果投影_内部(
    const 因果类& 因果,
    基础信息类* base,
    bool 包含未验证路径)
{
    私有_状态转换因果投影 out{};
    if (!base) {
        私有_追加因果缺失证据(out.缺失证据, 枚举_因果缺失证据类型::缺基础信息集);
        return out;
    }

    auto 追加边 = [&](私有_状态转换因果边 边) {
        if (!边.原因状态 || !边.结果状态) return;
        const bool 已存在 = std::any_of(
            out.边.begin(),
            out.边.end(),
            [&](const auto& 已有) {
                return 私有_状态节点命中目标(base, 已有.原因状态, 边.原因状态)
                    && 私有_状态节点命中目标(base, 已有.结果状态, 边.结果状态)
                    && 已有.动作动态 == 边.动作动态
                    && 已有.因果模板 == 边.因果模板;
            });
        if (已存在) return;

        auto 路径 = 私有_从状态转换边生成目标投影路径(边);
        out.目标投影路径.push_back(std::move(路径));
        out.目标投影来源因果模板.push_back(边.因果模板);
        out.边.push_back(std::move(边));
    };

    动态类 动态服务(base);
    for (auto* 动态 : 动态服务.枚举全部动态()) {
        状态节点类* 初始状态 = nullptr;
        状态节点类* 结果状态 = nullptr;
        方法节点类* 来源动作 = nullptr;
        const 语素入口节点类* 来源动作名 = nullptr;
        const 语素入口节点类* 动态类型 = nullptr;
        std::uint32_t 动态层级 = 0;
        if (!动态服务.读取动态因果生成输入(
                动态,
                初始状态,
                结果状态,
                来源动作,
                来源动作名,
                动态类型,
                动态层级)) {
            continue;
        }
        if (!初始状态 || !结果状态) continue;
        追加边(私有_构造动态状态转换边(动态));
    }

    for (auto* 模板节点 : 因果.枚举因果模板()) {
        auto* 模板信息 = 因果.取模板主信息(模板节点);
        if (!模板信息) continue;
        if (!私有_因果模板果侧可用(模板信息)) continue;
        if (!包含未验证路径 && !模板信息->已验证) continue;

        for (const auto& 证据 : 模板信息->证据动态样本) {
            if (!证据.指针) continue;
            auto 边 = 私有_构造动态状态转换边(证据.指针);
            if (!边.原因状态 || !边.结果状态) continue;
            边.因果模板 = 模板节点;
            追加边(std::move(边));
        }

        if (模板信息->主果比较模板.有效()) {
            auto* 迁移 = 模板信息->主果比较模板.指针;
            二次特征类 二次特征服务(base);
            状态节点类* 起始状态 = nullptr;
            状态节点类* 结果状态 = nullptr;
            动态节点类* 来源动态 = nullptr;
            if (二次特征服务.读取状态迁移来源(迁移, 起始状态, 结果状态, 来源动态)
                && 起始状态
                && 结果状态) {
                私有_状态转换因果边 边{};
                边.原因状态 = 起始状态;
                边.结果状态 = 结果状态;
                边.动作动态 = 来源动态;
                边.因果模板 = 模板节点;
                追加边(std::move(边));
            }
        }
    }

    if (out.边.empty()) {
        私有_追加因果缺失证据(out.缺失证据, 枚举_因果缺失证据类型::缺可投影状态转换边);
    }
    return out;
}

