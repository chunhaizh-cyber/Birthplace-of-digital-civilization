// 功能：读取因果证据状态和基础计数判断，不创建或修改节点。
void 因果类::读取因果证据状态(
    const 因果节点类* 因果,
    bool& 是初始模板,
    bool& 已验证,
    std::uint64_t& 证据动态样本数,
    I64& 稳定度,
    bool& 证据足够) const noexcept
{
    constexpr std::uint64_t 最小观察次数 = 3;
    constexpr std::uint64_t 最小成立次数 = 1;

    是初始模板 = false;
    已验证 = false;
    证据动态样本数 = 0;
    稳定度 = 0;
    证据足够 = false;

    const auto* 主信息 = 取因果主信息(因果);
    if (!主信息) {
        return;
    }

    是初始模板 = !主信息->已验证 && 主信息->证据动态样本.empty();
    已验证 = 主信息->已验证;
    证据动态样本数 = static_cast<std::uint64_t>(主信息->证据动态样本.size());
    稳定度 = 主信息->计算稳定度();

    if (是初始模板 || 已验证) {
        证据足够 = true;
        return;
    }
    if (主信息->观察次数 < 最小观察次数) {
        return;
    }
    if (主信息->成立次数 < 最小成立次数) {
        return;
    }
    证据足够 = 主信息->失败次数 <= 主信息->成立次数;
}

// 功能：更新因果模板基础证据计数，不保存失败动态样本。
void 因果类::更新因果证据计数(
    因果模板节点类* 模板,
    bool 条件命中,
    bool 因出现,
    bool 果出现,
    bool 成立,
    时间戳 评价时间)
{
    auto* 主信息 = 取模板主信息(模板);
    if (!主信息) {
        return;
    }

    ++主信息->观察次数;
    if (条件命中) ++主信息->条件命中次数;
    if (因出现) ++主信息->因出现次数;
    if (果出现) ++主信息->果出现次数;

    if (成立) {
        ++主信息->成立次数;
        主信息->最近命中时间 = 评价时间;
    }
    else {
        ++主信息->失败次数;
        主信息->最近失败时间 = 评价时间;
    }
}

// 功能：验收动作动态的预测结果与实际结果，并更新命中因果模板计数。
void 因果类::验收动作结果因果证据(
    动态节点类* 动作动态,
    状态节点类* 预测结果状态,
    状态节点类* 实际结果状态,
    bool& 命中预测,
    std::vector<因果模板节点类*>& 更新模板,
    std::vector<结构_因果缺失证据项>& 缺失证据)
{
    命中预测 = false;
    更新模板.clear();
    缺失证据.clear();

    auto* base = 私有_选择基础信息(基础信息_);
    if (!base) {
        私有_追加因果缺失证据(缺失证据, 枚举_因果缺失证据类型::缺基础信息集);
        return;
    }
    if (!动作动态) {
        私有_追加因果缺失证据(缺失证据, 枚举_因果缺失证据类型::缺动作动态);
        return;
    }
    if (!预测结果状态) {
        私有_追加因果缺失证据(缺失证据, 枚举_因果缺失证据类型::缺预测结果状态);
        return;
    }
    if (!实际结果状态) {
        私有_追加因果缺失证据(缺失证据, 枚举_因果缺失证据类型::缺实际结果状态);
        return;
    }

    状态节点类* 动态初始状态 = nullptr;
    状态节点类* 动态结果状态 = nullptr;
    方法节点类* 来源动作 = nullptr;
    const 语素入口节点类* 来源动作名 = nullptr;
    const 语素入口节点类* 动态类型 = nullptr;
    std::uint32_t 动态层级 = 0;
    动态类 动态服务(base);
    if (!动态服务.读取动态因果生成输入(
            动作动态,
            动态初始状态,
            动态结果状态,
            来源动作,
            来源动作名,
            动态类型,
            动态层级)) {
        私有_追加因果缺失证据(
            缺失证据,
            枚举_因果缺失证据类型::动作动态缺因果生成输入,
            nullptr,
            {},
            nullptr,
            nullptr,
            nullptr,
            nullptr,
            动作动态);
        return;
    }

    命中预测 = 私有_状态节点命中目标(base, 实际结果状态, 预测结果状态);
    const auto* 无动作状态变化动态类型 =
        语素集.添加信息入口词("无动作状态变化动态", 枚举_信息入口类型::动态模板入口);
    if (语素入口同一(动态类型, 无动作状态变化动态类型) && !来源动作 && !来源动作名) {
        私有_追加因果缺失证据(
            缺失证据,
            枚举_因果缺失证据类型::动作动态缺动作来源,
            nullptr,
            {},
            nullptr,
            nullptr,
            nullptr,
            nullptr,
            动作动态);
        return;
    }

    std::string 动作语义键{};
    if (!来源动作 && !来源动作名) {
        动作语义键 = 私有_节点键(动态类型);
    }

    auto* 动态条件特征 = 私有_动态条件特征_因果(base, 动作动态);
    const auto 评价时间 = 结构体_时间戳::当前_微秒();
    for (auto* 模板节点 : 枚举因果模板()) {
        auto* 主信息 = 取模板主信息(模板节点);
        if (!主信息 || !私有_因果模板有动作(主信息)) continue;
        if (!私有_因果模板动作命中动态(主信息, base, 动作动态, 动作语义键)) continue;
        if (!私有_因果模板结果命中状态(base, 主信息, 预测结果状态)) continue;

        const bool 条件命中 = 主信息->条件比较模板.empty()
            || 私有_因果模板条件命中特征(base, 主信息, 动态条件特征);
        const bool 因出现 = true;
        const bool 果出现 = 私有_因果模板结果命中状态(base, 主信息, 实际结果状态);
        const bool 成立 = 条件命中 && 因出现 && 果出现;
        更新因果证据计数(模板节点, 条件命中, 因出现, 果出现, 成立, 评价时间);
        更新模板.push_back(模板节点);
    }

    if (更新模板.empty()) {
        私有_追加因果缺失证据(缺失证据, 枚举_因果缺失证据类型::缺匹配动作和预测结果因果模板);
    }
}

// 功能：按目标二次特征比较查询主果同向和反向命中的因果节点，不创建或修改节点。
void 因果类::查询主果方向命中因果(
    const 二次特征节点类* 目标比较,
    bool 包含未验证路径,
    std::size_t& 因果节点数量,
    std::size_t& 主果可解析数量,
    std::vector<因果节点类*>& 同向命中因果,
    std::vector<因果节点类*>& 反向命中因果,
    std::vector<结构_因果缺失证据项>& 缺失证据) const
{
    因果节点数量 = 0;
    主果可解析数量 = 0;
    同向命中因果.clear();
    反向命中因果.clear();
    缺失证据.clear();

    auto* base = 私有_选择基础信息(基础信息_);
    if (!base) {
        私有_追加因果缺失证据(缺失证据, 枚举_因果缺失证据类型::基础信息为空);
        return;
    }
    if (!目标比较) {
        私有_追加因果缺失证据(缺失证据, 枚举_因果缺失证据类型::目标比较为空);
        return;
    }

    for (auto* 因果节点 : 枚举全部因果()) {
        ++因果节点数量;
        const auto* 主信息 = 取因果主信息(因果节点);
        if (!主信息) {
            continue;
        }
        if (!包含未验证路径) {
            bool 是初始模板 = false;
            bool 已验证 = false;
            bool 证据足够 = false;
            std::uint64_t 证据动态样本数 = 0;
            I64 稳定度 = 0;
            读取因果证据状态(
                因果节点,
                是初始模板,
                已验证,
                证据动态样本数,
                稳定度,
                证据足够);
            if (!证据足够) {
                私有_追加因果缺失证据(
                    缺失证据,
                    枚举_因果缺失证据类型::来源因果证据不足,
                    nullptr,
                    私有_节点键(因果节点),
                    因果节点);
                continue;
            }
        }
        if (!主信息->主果比较模板.有效()) {
            continue;
        }

        auto* 主果 = 私有_解析二次特征引用_因果(base, 主信息->主果比较模板);
        if (!主果) {
            私有_追加因果缺失证据(
                缺失证据,
                枚举_因果缺失证据类型::来源因果主果不可解析,
                nullptr,
                私有_节点键(因果节点),
                因果节点);
            continue;
        }

        ++主果可解析数量;
        const auto 方向比较 = 需求类::比较需求方向(主果, 目标比较);
        if (方向比较 == 需求类::枚举_需求方向比较结果::同向) {
            同向命中因果.push_back(因果节点);
        } else if (方向比较 == 需求类::枚举_需求方向比较结果::反向) {
            反向命中因果.push_back(因果节点);
        }
    }
}

// 功能：判断因果节点是否登记了条件模板，不创建或修改节点。
