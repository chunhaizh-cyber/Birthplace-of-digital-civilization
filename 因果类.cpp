// 功能：判断方法引用是否命中目标方法。
static bool 私有_方法引用命中目标(
    const 可解析引用<方法节点类>& 方法引用,
    const 方法节点类* 目标方法)
{
    if (!目标方法) return false;
    if (方法引用.指针 && 方法引用.指针 == 目标方法) return true;
    const auto 引用键 = 私有_引用键(方法引用);
    const auto 目标键 = 私有_指针键(目标方法);
    return !引用键.empty() && !目标键.empty() && 引用键 == 目标键;
}

// 功能：判断状态迁移二次特征是否来自指定动态的初始状态和结果状态。
static bool 私有_状态迁移模板命中动态(
    基础信息类* 基础信息,
    const 二次特征节点类* 迁移,
    const 动态节点类* 动态节点)
{
    auto* base = 私有_选择基础信息(基础信息);
    二次特征类 二次特征服务(base);
    if (!二次特征服务.是状态迁移二次特征(迁移) || !动态节点) return false;

    状态节点类* 迁移起始状态 = nullptr;
    状态节点类* 迁移结果状态 = nullptr;
    动态节点类* 迁移来源动态 = nullptr;
    if (!二次特征服务.读取状态迁移来源(
            迁移,
            迁移起始状态,
            迁移结果状态,
            迁移来源动态)) {
        return false;
    }
    if (迁移来源动态 && 私有_节点键(迁移来源动态) == 私有_节点键(动态节点)) {
        return true;
    }

    状态节点类* 初始状态 = nullptr;
    状态节点类* 结果状态 = nullptr;
    方法节点类* 来源动作 = nullptr;
    const 语素入口节点类* 来源动作名 = nullptr;
    const 语素入口节点类* 动态类型 = nullptr;
    std::uint32_t 动态层级 = 0;
    动态类 动态服务(base);
    if (!动态服务.读取动态因果生成输入(
            动态节点,
            初始状态,
            结果状态,
            来源动作,
            来源动作名,
            动态类型,
            动态层级)) {
        return false;
    }
    return 初始状态
        && 结果状态
        && 私有_状态节点命中目标(基础信息, 迁移起始状态, 初始状态)
        && 私有_状态节点命中目标(基础信息, 迁移结果状态, 结果状态);
}

