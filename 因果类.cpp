enum class 枚举_动态因果生成类别 : std::uint8_t {
    无动作状态变化 = 0,
    主动动作致变 = 1,
    被动动作致变 = 2,
};

// 功能：返回动态到因果生成分类的日志文本。
static const char* 私有_动态因果生成类别文本(枚举_动态因果生成类别 类别) noexcept
{
    switch (类别) {
    case 枚举_动态因果生成类别::主动动作致变: return "主动动作致变";
    case 枚举_动态因果生成类别::被动动作致变: return "被动动作致变";
    default: return "无动作状态变化";
    }
}

// 功能：按动态主信息推导因果生成类别。
static 枚举_动态因果生成类别 私有_推导动态因果生成类别(const 动态节点主信息类& 动态)
{
    const auto 推导语义 = 动态类::推导业务语义类型(动态);
    const auto 业务语义 = 推导语义 != 枚举_动态业务语义类型::未定义
        ? 推导语义
        : 动态.业务语义类型;

    if (动态.来源类型 == 枚举_动态来源类型::内部机制动作
        || 业务语义 == 枚举_动态业务语义类型::被动记账动态
        || 业务语义 == 枚举_动态业务语义类型::治理过程动态) {
        return 枚举_动态因果生成类别::被动动作致变;
    }

    if (动态.来源类型 == 枚举_动态来源类型::方法调用
        && 动态.来源动作.有效()) {
        return 枚举_动态因果生成类别::主动动作致变;
    }

    if (业务语义 == 枚举_动态业务语义类型::动作事实动态
        && (动态.来源动作.有效() || 动态.来源动作名)) {
        return 动态.来源类型 == 枚举_动态来源类型::内部机制动作
            ? 枚举_动态因果生成类别::被动动作致变
            : 枚举_动态因果生成类别::主动动作致变;
    }

    if (业务语义 == 枚举_动态业务语义类型::边界结束动态
        && 动态.来源类型 == 枚举_动态来源类型::内部机制动作) {
        return 枚举_动态因果生成类别::被动动作致变;
    }

    return 枚举_动态因果生成类别::无动作状态变化;
}

// 功能：解析状态引用对应的节点。
