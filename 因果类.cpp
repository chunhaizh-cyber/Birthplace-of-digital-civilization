// 功能：创建并返回或登记对应对象。
因果模板节点类* 因果类::创建因果模板(基础信息节点类* 父节点, 因果主信息类* 主信息)
{
    auto* base = 基础信息_ ? 基础信息_ : &获取基础信息集();
    if (!base || !主信息) return nullptr;
    if (主信息->主果比较模板.有效()) {
        (void)私有_补入因果结果特征_因果(
            主信息,
            私有_状态迁移结果特征_因果(base, 主信息->主果比较模板.指针));
    }
    if (!主信息->主果比较模板.有效()) {
        项目运行错误日志(
            "因果类/拒绝创建缺主果方向抽象因果模板"
            " | 原因=抽象因果必须由状态迁移二次特征提供结果方向"
            " | 名称入口=" + (主信息->名称 ? 私有_节点键(主信息->名称) : std::string("空"))
            + " | 适用层级=" + std::to_string(static_cast<I64>(主信息->适用层级)));
        return nullptr;
    }
    if (!私有_因果模板果侧可用(主信息)) {
        项目运行错误日志(
            "因果类/拒绝创建空果抽象因果模板"
            " | 原因=抽象因果必须由实例证据和结果特征形成"
            " | 名称入口=" + (主信息->名称 ? 私有_节点键(主信息->名称) : std::string("空"))
            + " | 适用层级=" + std::to_string(static_cast<I64>(主信息->适用层级)));
        return nullptr;
    }
    auto* parent = 父节点 ? 父节点 : base->世界根();
    return reinterpret_cast<因果模板节点类*>(base->添加子节点(parent, 主信息));
}

// 功能：按条件特征查询抽象因果模板，不创建或修改因果节点。
std::vector<因果模板节点类*> 因果类::查询条件相关因果(特征节点类* 条件特征) const
{
    std::vector<因果模板节点类*> out;
    if (!条件特征) return out;
    auto* base = 基础信息_ ? 基础信息_ : &获取基础信息集();
    for (auto* 模板节点 : 枚举因果模板()) {
        auto* 主信息 = 取模板主信息(模板节点);
        if (!主信息) continue;
        for (const auto& 条件 : 主信息->条件比较模板) {
            if (私有_特征引用命中目标(base, 条件, 条件特征)) {
                out.push_back(模板节点);
                break;
            }
        }
    }
    return out;
}

// 功能：按结果特征或结果状态查询抽象因果模板，不创建或修改因果节点。
std::vector<因果模板节点类*> 因果类::查询结果相关因果(
    特征节点类* 结果特征,
    状态节点类* 结果状态) const
{
    std::vector<因果模板节点类*> out;
    if (!结果特征 && !结果状态) return out;
    auto* base = 基础信息_ ? 基础信息_ : &获取基础信息集();
    auto* 目标特征 = 结果特征
        ? 结果特征
        : 私有_状态结果特征_因果(base, 结果状态);
    for (auto* 模板节点 : 枚举因果模板()) {
        auto* 主信息 = 取模板主信息(模板节点);
        if (!主信息 || !私有_因果模板果侧可用(主信息)) continue;
        if (结果状态 && !私有_因果模板结果命中状态(base, 主信息, 结果状态)) continue;
        if (目标特征 && !私有_因果模板结果命中特征(base, 主信息, 目标特征)) continue;
        out.push_back(模板节点);
    }
    return out;
}

// 功能：按方法模板或动作语义键查询抽象因果模板，不创建或修改因果节点。
std::vector<因果模板节点类*> 因果类::查询动作相关因果(
    const 方法节点类* 因方法,
    const std::string& 动作语义键) const
{
    std::vector<因果模板节点类*> out;
    if (!因方法 && 动作语义键.empty()) return out;
    for (auto* 模板节点 : 枚举因果模板()) {
        auto* 主信息 = 取模板主信息(模板节点);
        if (!主信息) continue;
        if (因方法 && !私有_方法引用命中目标(主信息->因方法模板, 因方法)) continue;
        if (!动作语义键.empty() && 主信息->因动作语义键 != 动作语义键) continue;
        out.push_back(模板节点);
    }
    return out;
}

// 功能：根据当前输入生成目标数据、场景、动态或回执。
结构_状态转换因果投影 因果类::生成状态转换因果投影(
    const 结构_状态转换因果投影输入& 输入) const
{
    结构_状态转换因果投影 out{};
    auto* base = 基础信息_ ? 基础信息_ : &获取基础信息集();
    auto 内部投影 = 私有_生成状态转换因果投影_内部(*this, base, 输入);
    out.节点 = std::move(内部投影.节点);
    out.边数量 = 内部投影.边.size();
    out.目标投影路径 = std::move(内部投影.目标投影路径);
    out.缺失证据 = std::move(内部投影.缺失证据);
    return out;
}

// 功能：从目标结果状态或目标结果特征回溯现有状态转换因果边。
结构_因果链查询结果 因果类::查询因果链(
    const 结构_因果链查询输入& 输入) const
{
    结构_因果链查询结果 out{};
    auto* base = 基础信息_ ? 基础信息_ : &获取基础信息集();
    if (!base) {
        out.缺失证据.push_back("缺基础信息集");
        return out;
    }
    if (!输入.目标结果状态 && !输入.目标结果特征) {
        out.缺失证据.push_back("缺目标结果状态或目标结果特征");
        return out;
    }

    结构_状态转换因果投影输入 投影输入{};
    投影输入.包含未验证路径 = 输入.包含未验证路径;
    auto 投影 = 私有_生成状态转换因果投影_内部(*this, base, 投影输入);
    for (const auto& 缺失 : 投影.缺失证据) {
        out.缺失证据.push_back(缺失);
    }

    const auto 最大深度 = 输入.最大深度 == 0 ? 8 : 输入.最大深度;
    auto* 目标特征 = 输入.目标结果特征
        ? 输入.目标结果特征
        : 私有_状态结果特征_因果(base, 输入.目标结果状态);

    std::vector<状态节点类*> 已展开状态{};
    std::vector<std::pair<状态节点类*, std::uint32_t>> 待展开状态{};
    std::vector<const 私有_状态转换因果边*> 已追加边{};

    auto 追加节点 = [&](状态节点类* 状态, 动态节点类* 动态, 因果模板节点类* 模板) {
        auto 节点 = 私有_构造状态转换因果节点(状态, 动态, 模板);
        if (!节点.状态节点) return;
        const bool 已存在 = std::any_of(
            out.节点.begin(),
            out.节点.end(),
            [&](const auto& 已有) {
                return 私有_状态节点命中目标(base, 已有.状态节点, 节点.状态节点)
                    && 已有.来源动态 == 节点.来源动态
                    && 已有.来源因果模板 == 节点.来源因果模板;
            });
        if (!已存在) {
            out.节点.push_back(std::move(节点));
        }
    };

    auto 追加模板 = [&](因果模板节点类* 模板) {
        if (!模板) return;
        if (std::find(out.来源因果模板.begin(), out.来源因果模板.end(), 模板) == out.来源因果模板.end()) {
            out.来源因果模板.push_back(模板);
        }
    };

    auto 追加边 = [&](const 私有_状态转换因果边& 边, std::uint32_t 深度) {
        if (!边.原因状态 || !边.结果状态) return;
        const bool 已存在 = std::any_of(
            已追加边.begin(),
            已追加边.end(),
            [&](const auto& 已有) {
                return 已有
                    && 私有_状态节点命中目标(base, 已有->原因状态, 边.原因状态)
                    && 私有_状态节点命中目标(base, 已有->结果状态, 边.结果状态)
                    && 已有->动作动态 == 边.动作动态
                    && 已有->因果模板 == 边.因果模板;
            });
        if (已存在) return;
        已追加边.push_back(&边);
        ++out.边数量;
        追加节点(边.原因状态, 边.动作动态, 边.因果模板);
        追加节点(边.结果状态, 边.动作动态, 边.因果模板);
        追加模板(边.因果模板);
        if (深度 < 最大深度 && 边.原因状态) {
            待展开状态.push_back({ 边.原因状态, 深度 + 1 });
        }
    };

    if (输入.目标结果状态) {
        待展开状态.push_back({ 输入.目标结果状态, 0 });
    } else {
        for (const auto& 边 : 投影.边) {
            if (私有_因果边结果命中查询(base, 边, nullptr, 目标特征)) {
                追加边(边, 0);
            }
        }
    }

    for (std::size_t i = 0; i < 待展开状态.size(); ++i) {
        auto* 当前状态 = 待展开状态[i].first;
        const auto 当前深度 = 待展开状态[i].second;
        if (!当前状态 || 当前深度 > 最大深度) continue;
        const bool 已展开 = std::any_of(
            已展开状态.begin(),
            已展开状态.end(),
            [&](const auto* 已有状态) {
                return 私有_状态节点命中目标(base, 已有状态, 当前状态);
            });
        if (已展开) {
            continue;
        }
        已展开状态.push_back(当前状态);
        for (const auto& 边 : 投影.边) {
            if (!私有_状态节点命中目标(base, 边.结果状态, 当前状态)) {
                continue;
            }
            if (当前深度 == 0
                && 输入.目标结果特征
                && !私有_状态结果特征命中目标(base, 边.结果状态, 输入.目标结果特征)) {
                continue;
            }
            追加边(边, 当前深度);
        }
    }

    if (out.边数量 == 0) {
        out.缺失证据.push_back("未找到命中目标的因果链");
    }
    return out;
}

// 功能：按函数名执行对应处理。
结构_叶子任务因果投影预判 因果类::查询叶子任务目标投影层级(
    const 结构_叶子任务因果投影输入& 输入) const
{
    结构_叶子任务因果投影预判 out{};

    if (!输入.叶子任务) {
        out.缺失证据.push_back("缺叶子任务");
    }
    if (!输入.来源需求) {
        out.缺失证据.push_back("缺来源需求");
    }
    if (!输入.目标宿主) {
        out.缺失证据.push_back("缺目标宿主");
    }
    if (!输入.目标特征类型) {
        out.缺失证据.push_back("缺目标特征类型");
    }

    out.是否允许形成D0 = 输入.目标宿主 != nullptr && 输入.目标特征类型 != nullptr;

    结构_状态转换因果投影输入 投影输入{};
    投影输入.包含未验证路径 = 输入.允许未验证路径;
    auto 投影 = 生成状态转换因果投影(投影输入);

    for (auto 路径 : 投影.目标投影路径) {
        if (输入.目标特征类型 && 路径.目标特征类型 != 输入.目标特征类型) {
            continue;
        }
        if (输入.目标宿主 && 路径.目标宿主 && 路径.目标宿主 != 输入.目标宿主) {
            continue;
        }
        out.候选投影路径.push_back(std::move(路径));
    }

    if (out.候选投影路径.empty()) {
        // 因果本体里尚未沉淀到对应 D0 证据时，仍按目标特征语义生成
        // 只读规则候选路径。候选路径只说明结算贡献层级，
        // 正式结算证据由结算链后续采集。
        auto 规则路径 = 私有_按目标特征生成规则投影路径(
            输入.目标宿主,
            输入.目标特征类型,
            输入.来源需求);
        for (auto& 路径 : 规则路径) {
            out.候选投影路径.push_back(std::move(路径));
        }
    }

    if (out.候选投影路径.empty()) {
        out.缺失证据.push_back("缺目标投影路径");
        for (const auto& 缺失 : 投影.缺失证据) {
            out.缺失证据.push_back(缺失);
        }
    }

    if (!out.候选投影路径.empty()) {
        auto 追加缺失证据 = [&](const std::string& 证据) {
            if (证据.empty()) return;
            if (std::find(out.缺失证据.begin(), out.缺失证据.end(), 证据)
                == out.缺失证据.end()) {
                out.缺失证据.push_back(证据);
            }
        };
        for (const auto& 路径 : out.候选投影路径) {
            for (const auto& 证据 : 路径.缺失证据) {
                追加缺失证据(证据);
            }
        }
    }

    return out;
}

// 功能：按函数名执行对应处理。
结构_自检原子目标因果投影结果 因果类::查询自检原子目标投影(
    const 结构_自检原子目标因果投影输入& 输入) const
{
    结构_自检原子目标因果投影结果 out{};
    const auto* 目标特征类型词 = 输入.目标特征类型词
        ? 输入.目标特征类型词
        : 私有_特征语义类型(输入.目标特征类型);

    auto 追加缺失证据 = [&](const std::string& 缺失) {
        if (缺失.empty()) return;
        if (std::find(out.缺失证据.begin(), out.缺失证据.end(), 缺失)
            == out.缺失证据.end()) {
            out.缺失证据.push_back(缺失);
        }
    };

    if (!输入.固定来源任务) {
        追加缺失证据("缺固定来源任务");
    }
    if (!输入.固定来源需求) {
        追加缺失证据("缺固定来源需求");
    }
    if (!输入.目标宿主) {
        追加缺失证据("缺目标宿主");
    }
    if (!输入.目标特征类型 && !目标特征类型词) {
        追加缺失证据("缺目标特征类型");
    }

    结构_状态转换因果投影输入 投影输入{};
    投影输入.包含未验证路径 = 输入.允许未验证路径;
    auto* base = 基础信息_ ? 基础信息_ : &获取基础信息集();
    auto 投影 = 私有_生成状态转换因果投影_内部(*this, base, 投影输入);

    std::vector<因果模板节点类*> 已计来源因果{};
    auto 追加来源因果 = [&](因果模板节点类* 模板) {
        auto* 主信息 = 模板 ? 取模板主信息(模板) : nullptr;
        if (!模板 || !主信息) {
            return;
        }
        if (std::find(已计来源因果.begin(), 已计来源因果.end(), 模板) == 已计来源因果.end()) {
            已计来源因果.push_back(模板);
            out.来源因果主键集.push_back(模板->获取主键());
        }
    };

    for (std::size_t 路径索引 = 0; 路径索引 < 投影.目标投影路径.size(); ++路径索引) {
        auto 路径 = 投影.目标投影路径[路径索引];
        if (输入.目标特征类型 && 路径.目标特征类型 != 输入.目标特征类型) {
            continue;
        }
        if (!输入.目标特征类型
            && 目标特征类型词
            && !语素入口同一(路径.目标特征类型词, 目标特征类型词)
            && !私有_特征类型同一(路径.目标特征类型, 目标特征类型词)) {
            continue;
        }
        if (输入.目标宿主 && 路径.目标宿主 && 路径.目标宿主 != 输入.目标宿主) {
            continue;
        }
        if (路径索引 < 投影.目标投影来源因果模板.size()) {
            追加来源因果(投影.目标投影来源因果模板[路径索引]);
        }
        out.候选投影路径.push_back(std::move(路径));
    }

    if (out.候选投影路径.empty()) {
        auto 规则路径 = 输入.目标特征类型
            ? 私有_按目标特征生成规则投影路径(
                输入.目标宿主,
                输入.目标特征类型,
                输入.固定来源需求)
            : 私有_按目标特征类型生成规则投影路径(
            输入.目标宿主,
                nullptr,
                目标特征类型词,
                输入.固定来源需求);
        for (auto& 路径 : 规则路径) {
            out.候选投影路径.push_back(std::move(路径));
        }
    }

    for (const auto& 路径 : out.候选投影路径) {
        for (const auto& 缺失 : 路径.缺失证据) {
            追加缺失证据(缺失);
        }
    }

    if (out.候选投影路径.empty()) {
        追加缺失证据("缺目标投影路径");
        for (const auto& 缺失 : 投影.缺失证据) {
            追加缺失证据(缺失);
        }
    }

    if (out.来源因果主键集.empty() && !out.候选投影路径.empty()) {
        追加缺失证据("缺来源因果信息");
    }

    return out;
}

// 功能：按条件查找目标对象、方法或事实。
static std::vector<二次特征节点类*> 私有_查找动态果状态迁移模板(基础信息类* base, 动态节点类* d)
{
    std::vector<二次特征节点类*> out;
    if (!base || !d) return out;
    auto* dm = dynamic_cast<动态节点主信息类*>(d->主信息);
    if (!dm) return out;

    for (auto* n0 : base->枚举节点_按类型<二次特征主信息类>()) {
        auto* n = reinterpret_cast<二次特征节点类*>(n0);
        auto* m = dynamic_cast<二次特征主信息类*>(n->主信息);
        if (!m) continue;
        if (m->形态 != 二次特征主信息类::枚举_形态::状态迁移) continue;

        bool hit = false;
        if (私有_引用等于节点(m->来源动态, d)) hit = true;
        if (!hit && dm->初始状态.指针 && dm->结果状态.指针) {
            hit = 私有_引用等于节点(m->来源起始状态, dm->初始状态.指针)
                && 私有_引用等于节点(m->来源结果状态, dm->结果状态.指针);
        }
        if (hit) out.push_back(n);
    }
    return out;
}

// 功能：内部生成或命中因果模板，并返回公开入口使用的首选模板。
