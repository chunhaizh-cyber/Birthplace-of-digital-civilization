// 功能：服务所在模块的内部辅助流程。
static 私有_因果阶段时间点 私有_因果阶段当前时间点() noexcept
{
    return 私有_因果阶段时钟::now();
}

// 功能：服务所在模块的内部辅助流程。
static std::uint64_t 私有_因果阶段耗时微秒(
    const 私有_因果阶段时间点& 开始,
    const 私有_因果阶段时间点& 结束) noexcept
{
    return static_cast<std::uint64_t>(
        std::chrono::duration_cast<std::chrono::microseconds>(结束 - 开始).count());
}

// 功能：服务所在模块的内部辅助流程。
static void 私有_累加因果阶段耗时(
    std::uint64_t& 累计,
    const 私有_因果阶段时间点& 开始) noexcept
{
    累计 += 私有_因果阶段耗时微秒(开始, 私有_因果阶段当前时间点());
}

// 功能：服务所在模块的内部辅助流程。
static std::uint64_t 私有_生成因果信息采样序号(std::uint64_t 总耗时微秒) noexcept
{
    if (总耗时微秒 < 5000) {
        return 0;
    }
    static std::atomic<std::uint64_t> s_慢生成因果信息序号{0};
    const auto 序号 = s_慢生成因果信息序号.fetch_add(1, std::memory_order_relaxed) + 1;
    if (序号 <= 10 || (序号 % 50) == 0 || 总耗时微秒 >= 50000) {
        return 序号;
    }
    return 0;
}

template<class T节点>
static std::string 私有_节点键(const T节点* 节点)
{
    if (!节点) return {};
    return 节点->获取主键();
}

template<class T节点>
static std::string 私有_引用键(const 可解析引用<T节点>& 引用)
{
    if (!引用.主键.empty()) return 引用.主键;
    return 引用.指针 ? 引用.指针->获取主键() : std::string{};
}

template<class T节点>
static bool 私有_引用等于节点(const 可解析引用<T节点>& 引用, const T节点* 节点)
{
    if (!节点) return false;
    const auto k = 私有_引用键(引用);
    return !k.empty() && k == 节点->获取主键();
}

template<class T节点>
static 可解析引用<T节点> 私有_制引用(T节点* 节点)
{
    可解析引用<T节点> r{};
    r.指针 = 节点;
    if (节点) r.主键 = 节点->获取主键();
    return r;
}

// 功能：服务所在模块的内部辅助流程。
static std::string 私有_指针键(const void* p)
{
    if (!p) return {};
    std::ostringstream os;
    os << "ptr:" << reinterpret_cast<std::uintptr_t>(p);
    return os.str();
}

// 功能：服务所在模块的内部辅助流程。
static std::string 私有_引用键(const 可解析引用<方法节点类>& 引用)
{
    if (!引用.主键.empty()) return 引用.主键;
    // 方法节点类在因果主信息层以弱引用出现；这里不强制包含其完整定义，
    // 避免把因果沉淀工具耦合到方法树节点实现。
    return 私有_指针键(引用.指针);
}

// 功能：服务所在模块的内部辅助流程。
static std::string 私有_动作名键(const 语素入口节点类* 名)
{
    return 私有_指针键(名);
}

// 功能：服务所在模块的内部辅助流程。
static bool 私有_向量含动态(
    const std::vector<可解析引用<动态节点类>>& v,
    const 动态节点类* d,
    const std::string& 动态主键)
{
    if (!d) return false;
    if (动态主键.empty()) {
        return std::any_of(v.begin(), v.end(), [&](const auto& r) { return 私有_引用等于节点(r, d); });
    }
    return std::any_of(v.begin(), v.end(), [&](const auto& r) {
        const auto k = 私有_引用键(r);
        return !k.empty() && k == 动态主键;
    });
}

// 功能：服务所在模块的内部辅助流程。
static 可解析引用<动态节点类> 私有_制动态引用(动态节点类* 节点, const std::string& 动态主键)
{
    可解析引用<动态节点类> r{};
    r.指针 = 节点;
    r.主键 = !动态主键.empty()
        ? 动态主键
        : 私有_节点键(节点);
    return r;
}

// 功能：登记方法、模板、对象或运行入口。
static bool 私有_登记证据动态样本_已加锁(
    std::vector<可解析引用<动态节点类>>& v,
    动态节点类* d,
    const std::string& 动态主键)
{
    if (!d) return false;

    if (私有_向量含动态(v, d, 动态主键)) {
        return false;
    }

    // 证据动态样本是可追溯样本，不是完整日志。完整发生次数由基础计数表达；
    // 这里限制样本向量扩容，避免长时间内部循环把模板证据表写成无界容器。
    if (v.size() < 私有_证据动态样本上限) {
        if (v.capacity() < 私有_证据动态样本上限) {
            v.reserve(私有_证据动态样本上限);
        }
        v.push_back(私有_制动态引用(d, 动态主键));
    }

    return true;
}

// 功能：登记方法、模板、对象或运行入口。
static bool 私有_登记证据动态样本(std::vector<可解析引用<动态节点类>>& v, 动态节点类* d)
{
    if (!d) return false;

    const auto 动态主键 = 私有_节点键(d);
    std::lock_guard<std::mutex> guard(私有_因果证据样本互斥);
    return 私有_登记证据动态样本_已加锁(v, d, 动态主键);
}

