static std::string 私有_指针键(const void* p)
{
    if (!p) return {};
    std::ostringstream os;
    os << "ptr:" << reinterpret_cast<std::uintptr_t>(p);
    return os.str();
}

// 功能：服务所在模块的内部辅助流程。
static std::string 私有_引用键(const 可解析引用<方法节点类>& 引用)
{
    if (!引用.主键.empty()) return 引用.主键;
    // 方法节点类在因果主信息层以弱引用出现；这里不强制包含其完整定义，
    // 避免把因果沉淀工具耦合到方法树节点实现。
    return 私有_指针键(引用.指针);
}

