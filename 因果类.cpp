    auto* 迁移信息 = 迁移 ? dynamic_cast<const 二次特征主信息类*>(迁移->主信息) : nullptr;
    if (!迁移信息) return nullptr;
    auto* 结果状态 = 私有_解析状态引用_因果(基础信息, 迁移信息->来源结果状态);
    return 私有_状态结果特征_因果(基础信息, 结果状态);
