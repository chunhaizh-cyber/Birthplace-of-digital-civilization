// 功能：向因果主信息补入结果特征和主果迁移方向。
static bool 私有_补入因果果侧模板_因果(
    因果主信息类* 主信息,
    基础信息类* 基础信息,
    特征节点类* 结果特征,
    二次特征节点类* 状态迁移模板,
    bool 设为主迁移)
{
    if (!主信息) return false;
    bool changed = 私有_补入因果结果特征_因果(
        主信息,
        结果特征 ? 结果特征 : 私有_状态迁移结果特征_因果(基础信息, 状态迁移模板));
    if (状态迁移模板 && (设为主迁移 || !主信息->主果比较模板.有效())) {
        主信息->主果比较模板 = 私有_制引用(状态迁移模板);
        changed = true;
    }
    return changed;
}

