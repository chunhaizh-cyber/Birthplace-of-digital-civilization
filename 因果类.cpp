// 功能：结算任务、需求、价值或结果贡献。
static std::uint32_t 私有_按特征语义推断结算贡献层级(
    const 语素入口节点类* 特征类型,
    const 需求节点类* 来源需求)
{
    if (私有_目标特征类型是安全账务值(特征类型) || 私有_目标特征类型是服务账务值(特征类型)) {
        return 0;
    }
    if (私有_目标特征类型是直接安全目标(特征类型)) {
        return 1;
    }
    const bool 来源有安全或服务方向 =
        需求类::来源需求有安全方向(来源需求)
        || 需求类::来源需求有服务方向(来源需求);
    if (私有_目标特征类型是任务层状态(特征类型)) {
        return 来源有安全或服务方向 ? 2 : 0;
    }
    if (私有_目标特征类型是方法层状态(特征类型) || 私有_目标特征类型是学习层状态(特征类型)) {
        return 来源有安全或服务方向 ? 3 : 1;
    }
    return 0;
}

// 功能：结算任务、需求、价值或结果贡献。
static std::uint32_t 私有_按特征语义推断结算贡献层级(
    const 特征节点类* 特征,
    const 需求节点类* 来源需求)
{
    return 私有_按特征语义推断结算贡献层级(私有_特征语义类型(特征), 来源需求);
}

