// 功能：启动线程、模块或运行流程。
bool 自检线程类::启动(bool 只读观察模式)
{
    bool 需要唤醒 = false;
    bool 已处于运行态 = false;
    bool 需要从只读切换到运行中 = false;
    {
        std::lock_guard<std::mutex> 锁(状态锁_);
        if (生命周期_ == 枚举_自检线程生命周期状态::运行中
            || 生命周期_ == 枚举_自检线程生命周期状态::启动中) {
            if (!只读观察模式 && 只读观察模式_) {
                已处于运行态 = true;
                需要从只读切换到运行中 = true;
            } else {
                return true;
            }
        }
    }

    if (已处于运行态) {
        if (需要从只读切换到运行中) {
            std::lock_guard<std::mutex> 锁(状态锁_);
            只读观察模式_ = false;
            记录事件_已加锁(
                结构体_时间戳::当前_微秒(),
                "自检线程切换到运行中模式 | 基础信息由线程内预检闸门等待");
            需要唤醒 = true;
            if (需要唤醒) {
                唤醒条件_.notify_all();
            }
            return true;
        }
        return true;
    }

    {
        std::lock_guard<std::mutex> 锁(状态锁_);
        if (生命周期_ == 枚举_自检线程生命周期状态::运行中
            || 生命周期_ == 枚举_自检线程生命周期状态::启动中) {
            return true;
        }
        生命周期_ = 枚举_自检线程生命周期状态::启动中;
        只读观察模式_ = 只读观察模式;
        停止请求_.store(false);
        健康运行_ = false;
        记录事件_已加锁(
            结构体_时间戳::当前_微秒(),
            std::string("自检线程启动请求 | 模式=") + (只读观察模式 ? "只读观察" : "运行中")
            + " | 基础信息由线程内预检闸门等待");
    }

    try {
        工作线程_ = std::thread(&自检线程类::主循环_, this);
        return true;
    } catch (const std::exception& 异常) {
        std::lock_guard<std::mutex> 锁(状态锁_);
        生命周期_ = 枚举_自检线程生命周期状态::故障;
        健康运行_ = false;
        记录事件_已加锁(结构体_时间戳::当前_微秒(), std::string("自检线程启动失败 | ") + 异常.what());
        项目记录异常日志(异常, "自检线程启动");
        return false;
    }
}

