    // 功能：从指定来源读取数据或状态。
    bool 私有_读取抽象特征I64区间_自检(
        const 抽象特征主信息类* 主信息,
        I64区间& 输出) noexcept
    {
        if (!主信息) {
            return false;
        }
        if (主信息->区间.has_value() && 主信息->区间->有效()) {
            输出 = *主信息->区间;
            return true;
        }
        if (!主信息->值域.has_value()) {
            return false;
        }
        const auto* I64域 = std::get_if<I64值域>(&主信息->值域.value());
        if (!I64域) {
            return false;
        }

        bool 已命中 = false;
        I64 低值 = 0;
        I64 高值 = 0;
        for (const auto& 项 : I64域->项集) {
            I64区间 当前区间{ 0, -1 };
            if (const auto* 区间 = std::get_if<I64区间>(&项)) {
                当前区间 = *区间;
            }
            else if (const auto* 点 = std::get_if<I64>(&项)) {
                当前区间 = I64区间::点(*点);
            }
            if (!当前区间.有效()) {
                continue;
            }
            if (!已命中) {
                低值 = 当前区间.低值;
                高值 = 当前区间.高值;
                已命中 = true;
            }
            else {
                低值 = (std::min<I64>)(低值, 当前区间.低值);
                高值 = (std::max<I64>)(高值, 当前区间.高值);
            }
        }
        if (!已命中) {
            return false;
        }
        输出 = I64区间{ 低值, 高值 };
        return 输出.有效();
    }

