    // 功能：服务所在模块的内部辅助流程。
    bool 私有_语素入口主键相等_自检(
        const 语素入口节点类* 左,
        const 语素入口节点类* 右) noexcept
    {
        if (左 == 右) {
            return 左 != nullptr;
        }
        if (!左 || !右) {
            return false;
        }
        const auto 左主键 = 左->获取主键();
        const auto 右主键 = 右->获取主键();
        return !左主键.empty() && 左主键 == 右主键;
    }

