        候选.原子最初状态主键 = 当前状态节点->获取主键();
        候选.原子当前状态指针 = reinterpret_cast<std::uintptr_t>(当前状态节点);
        候选.原子当前状态主键 = 当前状态节点->获取主键();
        候选.原子目标状态指针 = reinterpret_cast<std::uintptr_t>(目标状态);
        候选.原子目标状态主键 = 目标状态->获取主键();
        候选.原子满足关系 = 关系_大于等于;

