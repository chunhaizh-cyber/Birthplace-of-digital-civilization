    结构_方法结构计数 私有_统计方法直接结构(const 方法节点* 方法头) noexcept
    {
        结构_方法结构计数 计数{};
        if (!方法头 || !方法头->子) {
            return 计数;
        }

        auto* 首节点 = reinterpret_cast<const 方法节点*>(方法头->子);
        auto* 当前 = 首节点;
        std::size_t 保护 = 0;
        do {
            if (当前->主信息.公共.节点种类 == 枚举_方法节点种类::方法条件节点) {
                ++计数.条件数;
                if (当前->子) {
                    auto* 首结果 = reinterpret_cast<const 方法节点*>(当前->子);
                    auto* 结果 = 首结果;
                    std::size_t 结果保护 = 0;
                    do {
                        if (结果
                            && 结果->主信息.公共.节点种类 == 枚举_方法节点种类::方法结果节点) {
                            ++计数.结果数;
                        }
                        结果 = 结果 ? reinterpret_cast<const 方法节点*>(结果->下) : nullptr;
                        ++结果保护;
                    } while (结果 && 结果 != 首结果 && 结果保护 < 1024);
                }
            }
            当前 = 当前 ? reinterpret_cast<const 方法节点*>(当前->下) : nullptr;
            ++保护;
        } while (当前 && 当前 != 首节点 && 保护 < 2048);
        return 计数;
    }

