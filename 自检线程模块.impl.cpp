// 功能：按函数名执行对应处理。
void 自检线程类::主循环_()
{
    {
        std::lock_guard<std::mutex> 锁(状态锁_);
        生命周期_ = 枚举_自检线程生命周期状态::运行中;
        健康运行_ = true;
        记录事件_已加锁(结构体_时间戳::当前_微秒(), "自检线程已启动");
    }

    while (!停止请求_.load()) {
        const auto now = 结构体_时间戳::当前_微秒();
        try {
            bool 当前只读观察模式 = false;
            {
                std::lock_guard<std::mutex> 锁(状态锁_);
                ++Tick计数_;
                最近检查时间_ = now;
                当前只读观察模式 = 只读观察模式_;
                if (当前只读观察模式) {
                    最近模式_ = 枚举_自检线程模式::只读观察;
                }
            }

            bool 本轮基础信息就绪 = true;
            if (!当前只读观察模式) {
                std::string 预检摘要;
                const bool 预检通过 = 私有_检查自检基础信息_自检(false, 预检摘要);
                if (!预检通过) {
                    bool 需要记录等待 = false;
                    {
                        std::lock_guard<std::mutex> 锁(状态锁_);
                        最近模式_ = 枚举_自检线程模式::运行中;
                        健康运行_ = true;
                        需要记录等待 =
                            最近基础信息预检摘要_ != 预检摘要
                            || 最近基础信息预检记录时间_ == 0
                            || now < 最近基础信息预检记录时间_
                            || now - 最近基础信息预检记录时间_ >= 私有_自检基础信息等待日志间隔_微秒;
                        if (需要记录等待) {
                            最近基础信息预检摘要_ = 预检摘要;
                            最近基础信息预检记录时间_ = now;
                            记录事件_已加锁(
                                now,
                                "自检线程等待基础信息 | " + 预检摘要);
                        }
                    }
                    if (需要记录等待) {
                        项目运行警告日志(预检摘要 + " | 结果=线程内等待基础信息");
                    }
                    本轮基础信息就绪 = false;
                } else {
                    {
                        std::lock_guard<std::mutex> 锁(状态锁_);
                        if (!最近基础信息预检摘要_.empty()) {
                            最近基础信息预检摘要_.clear();
                            最近基础信息预检记录时间_ = now;
                            记录事件_已加锁(now, "自检线程基础信息预检通过 | " + 预检摘要);
                        }
                    }
                    执行运行中自检_(now);
                }
            }
            if (本轮基础信息就绪 && 当前只读观察模式 && 休眠期自检请求_.exchange(false)) {
                std::lock_guard<std::mutex> 锁(状态锁_);
                记录事件_已加锁(now, "只读观察模式忽略休眠期自检请求");
            }
            if (本轮基础信息就绪 && !当前只读观察模式 && 休眠期自检请求_.exchange(false)) {
                std::string 预检摘要;
                const bool 预检通过 = 私有_检查自检基础信息_自检(false, 预检摘要);
                if (!预检通过) {
                    bool 需要记录等待 = false;
                    {
                        std::lock_guard<std::mutex> 锁(状态锁_);
                        需要记录等待 =
                            最近基础信息预检摘要_ != 预检摘要
                            || 最近基础信息预检记录时间_ == 0
                            || now < 最近基础信息预检记录时间_
                            || now - 最近基础信息预检记录时间_ >= 私有_自检基础信息等待日志间隔_微秒;
                        if (需要记录等待) {
                            最近基础信息预检摘要_ = 预检摘要;
                            最近基础信息预检记录时间_ = now;
                            记录事件_已加锁(
                                now,
                                "休眠期自检等待基础信息 | " + 预检摘要);
                        }
                    }
                    if (需要记录等待) {
                        项目运行警告日志(预检摘要 + " | 结果=休眠期自检请求等待基础信息");
                    }
                } else {
                    执行休眠期自检_(now);
                }
            }
        } catch (const std::exception& 异常) {
            项目记录异常日志(异常, "自检线程/主循环");
            std::lock_guard<std::mutex> 锁(状态锁_);
            生命周期_ = 枚举_自检线程生命周期状态::故障;
            健康运行_ = false;
            记录事件_已加锁(now, std::string("自检线程故障 | ") + 异常.what());
        } catch (...) {
            项目致命日志("自检线程/主循环 | 未知异常");
            std::lock_guard<std::mutex> 锁(状态锁_);
            生命周期_ = 枚举_自检线程生命周期状态::故障;
            健康运行_ = false;
            记录事件_已加锁(now, "自检线程故障 | 未知异常");
        }

        std::unique_lock<std::mutex> 锁(状态锁_);
        唤醒条件_.wait_for(锁, 配置_.Tick间隔, [&] {
            return 停止请求_.load() || 休眠期自检请求_.load();
        });
    }

    {
        std::lock_guard<std::mutex> 锁(状态锁_);
        生命周期_ = 枚举_自检线程生命周期状态::已停止;
        健康运行_ = false;
        记录事件_已加锁(结构体_时间戳::当前_微秒(), "自检线程已停止");
    }
}

// 功能：执行对应模块、线程或方法的运行逻辑。
void 自检线程类::执行运行中自检_(时间戳 now)
{
    std::size_t 本轮需求型提交 = 0;
    std::size_t 本轮报告型提交 = 0;
    const auto 停止检查 = [&](const char* 阶段) {
        if (!停止请求_.load()) {
            return false;
        }
        项目运行日志(
            std::string("自检线程/运行中自检停止检查 | 阶段=")
            + (阶段 ? 阶段 : "未命名")
            + " | 跳过剩余自检=1");
        return true;
    };
    const auto 本轮总提交 = [&]() noexcept {
        return 本轮需求型提交 + 本轮报告型提交;
    };
    const auto 抑制微秒 =
        static_cast<时间戳>(std::chrono::duration_cast<std::chrono::microseconds>(配置_.去重抑制间隔).count());

    if (本轮报告型提交 < 配置_.每轮提交上限
        && 私有_到期(最近检查时刻_, "自我根特征", 配置_.方法结构检查间隔)) {
        if (停止检查("根特征收集前")) {
            return;
        }
        auto 候选集 = 私有_收集根特征自检缺口候选_自检(
            去重账_,
            now,
            抑制微秒,
            配置_.每轮提交上限 - 本轮报告型提交,
            &停止请求_);
        if (停止检查("根特征收集后")) {
            return;
        }
        for (const auto& 候选 : 候选集) {
            if (停止检查("根特征提交循环")) {
                return;
            }
            if (私有_提交自检报告(候选, now, 自检范围_自我根特征)) {
                ++本轮报告型提交;
                std::lock_guard<std::mutex> 锁(状态锁_);
                最近模式_ = 枚举_自检线程模式::运行中;
                ++累计提交报告数_;
                ++累计发现问题数_;
                最近提交时间_ = now;
                最近需求摘要_ = 私有_构造自检缺口候选文本(候选);
                记录事件_已加锁(now, "发现并提交根特征自检报告 | " + 最近需求摘要_);
            }
        }
    }

    if (私有_到期(最近检查时刻_, "方法结构", 配置_.方法结构检查间隔)) {
        for (auto* 方法 : 私有_枚举方法首节点(配置_.单类扫描上限, &方法扫描游标_)) {
            if (停止检查("方法结构扫描循环")) {
                return;
            }
            if (!方法) {
                break;
            }
            if (方法->主信息.首节点信息().动作句柄.类型 != 枚举_动作句柄类型::本能函数ID) {
                continue;
            }
            I64 条件数 = 0;
            I64 结果数 = 0;
            私有_统计方法直接结构_自检(方法, 条件数, 结果数);
            I64 条件结果对数量 = 0;
            I64 条件结果对命中次数总和 = 0;
            I64 条件结果对最大命中次数 = 0;
            私有_统计方法条件结果对_自检(
                方法,
                条件结果对数量,
                条件结果对命中次数总和,
                条件结果对最大命中次数);
            const bool 有对应动作 = 私有_本能方法有对应动作_自检(方法);
            const bool 有条件结果对 = 条件结果对数量 > 0;
            const bool 条件结果对已命中 = 条件结果对最大命中次数 > 0;
            if (有对应动作 && 有条件结果对 && 条件结果对已命中) {
                continue;
            }
            const bool 方法可练习 = 私有_方法可作为练习目标_自检(方法);
            const bool 缺对应动作 = !有对应动作;
            const bool 缺条件结果对 = 有对应动作 && !有条件结果对;
            const bool 缺条件结果对命中 = 有对应动作 && 有条件结果对 && !条件结果对已命中;
            const bool 建议生成需求 =
                方法可练习 && (缺条件结果对 || 缺条件结果对命中);
            const auto* 证据特征类型 = 缺条件结果对
                ? 私有_特征_条件结果对数量_自检()
                : (缺条件结果对命中
                    ? 私有_特征_条件结果对命中次数_自检()
                    : 私有_特征_方法动作状态_自检());
            const I64 证据当前值 = 缺条件结果对
                ? 条件结果对数量
                : (缺条件结果对命中 ? 条件结果对最大命中次数 : (有对应动作 ? 1 : 0));
            const auto* 原子特征类型 = 建议生成需求
                ? 私有_特征_方法状态_自检()
                : 证据特征类型;
            const I64 方法状态当前值 = 私有_推导方法自检当前状态值_自检(
                有对应动作,
                条件数,
                结果数,
                条件结果对数量);
            const I64 原子当前值 = 建议生成需求
                ? 方法状态当前值
                : 证据当前值;
            const I64 原子目标值 = 建议生成需求
                ? 私有_方法状态_好用值_自检()
                : 1;
            const I64 缺失结构类型 = 缺对应动作
                ? 自检缺失结构_本能方法对应动作
                : (缺条件结果对
                    ? 自检缺失结构_条件结果对
                    : 自检缺失结构_条件结果对命中次数);
            const auto 需求类型 = 缺对应动作
                ? 枚举_任务管理派生需求类型::缺信息
                : 枚举_任务管理派生需求类型::方法结构;
            const auto 阻塞级别 = 缺对应动作
                ? 枚举_任务管理阻塞级别::严重
                : 枚举_任务管理阻塞级别::中等;

            const std::string 去重键 = "自检|方法结构|"
                + 方法->获取主键()
                + "|对应动作=" + (有对应动作 ? "1" : "0")
                + "|条件=" + std::to_string(条件数)
                + "|结果=" + std::to_string(结果数)
                + "|条件结果对=" + std::to_string(条件结果对数量)
                + "|配对命中最大=" + std::to_string(条件结果对最大命中次数);
            const I64 本能ID值 = 方法->主信息.首节点信息().动作句柄.本能ID;
            const auto 本能枚举ID = static_cast<枚举_本能方法ID>(
                static_cast<std::uint32_t>(本能ID值));
            const char* 本能动作名称 = 本能方法类::查询默认动作名称(本能枚举ID);

            std::ostringstream 观察;
            观察 << "本能方法自检缺口 | 方法=" << 私有_方法标题(方法)
                << " | 本能ID=" << 本能ID值
                << " | 本能动作=" << (本能动作名称 ? 本能动作名称 : "")
                << " | 对应动作=" << 布尔文本_是或否(有对应动作)
                << " | 动作句柄有效=" << 布尔文本_是或否(方法->主信息.首节点信息().动作句柄.有效())
                << " | 条件数=" << 条件数
                << " | 结果数=" << 结果数
                << " | 条件结果对数量=" << 条件结果对数量
                << " | 条件结果对命中总数=" << 条件结果对命中次数总和
                << " | 条件结果对最大命中次数=" << 条件结果对最大命中次数
                << " | 检查口径=方法状态维护目标/条件结果对证据";
            if (建议生成需求) {
                if (本轮需求型提交 >= 配置_.每轮提交上限) {
                    break;
                }
            } else if (本轮报告型提交 >= 配置_.每轮提交上限) {
                continue;
            }
            if (私有_是否去重抑制中(去重账_, 去重键, now, 抑制微秒)) {
                continue;
            }

            观察 << " | 练习目标=" << 布尔文本_是或否(方法可练习);
            if (建议生成需求) {
                观察 << " | 正式目标=方法状态>=好用"
                    << " | 方法状态当前值=" << 方法状态当前值
                    << " | 方法状态目标值=" << 原子目标值
                    << " | 证据特征=" << (证据特征类型 ? 证据特征类型->获取主键() : std::string())
                    << " | 证据当前值=" << 证据当前值;
            }
            if (缺对应动作) {
                观察 << " | 处置=报告型"
                    << " | 原因=方法头动作句柄未能对应到本能动作注册，不生成正式练习需求";
            } else if (!方法可练习) {
                观察 << " | 处置=报告型"
                    << " | 原因=目标本能不允许练习，等待领域治理入口";
            } else if (缺条件结果对) {
                观察 << " | 处置=需求型"
                    << " | 原因=缺条件结果对，作为方法状态好用目标证据提交";
            } else {
                观察 << " | 处置=需求型"
                    << " | 原因=条件结果对尚无命中，作为方法状态好用目标证据提交";
            }
            const auto 候选 = 私有_构造自检缺口候选(
                去重键,
                方法,
                原子特征类型 ? 原子特征类型->获取主键() : std::string("本能方法自检"),
                观察.str(),
                缺失结构类型,
                需求类型,
                阻塞级别,
                建议生成需求,
                now,
                原子特征类型,
                原子当前值,
                原子目标值,
                关系_大于等于);
            if (私有_提交自检报告(候选, now)) {
                if (建议生成需求) {
                    ++本轮需求型提交;
                } else {
                    ++本轮报告型提交;
                }
                std::lock_guard<std::mutex> 锁(状态锁_);
                最近模式_ = 枚举_自检线程模式::运行中;
                ++累计提交报告数_;
                ++累计发现问题数_;
                最近提交时间_ = now;
                最近需求摘要_ = 私有_构造自检缺口候选文本(候选);
                记录事件_已加锁(now, "发现并提交报告 | " + 最近需求摘要_);
            }
        }
    }

    if (本轮报告型提交 < 配置_.每轮提交上限
        && 私有_到期(最近检查时刻_, "方法运行账", 配置_.方法运行账检查间隔)) {
        for (auto* 方法 : 私有_枚举方法首节点(配置_.单类扫描上限, &方法扫描游标_)) {
            if (停止检查("方法运行账扫描循环")) {
                return;
            }
            if (!方法 || 本轮报告型提交 >= 配置_.每轮提交上限) {
                break;
            }
            const auto 最近执行时间 = 私有_读取方法运行账时间_自检(
                方法,
                私有_特征_最近执行时间_自检());
            const auto 最近完成时间 = 私有_读取方法运行账时间_自检(
                方法,
                私有_特征_最近完成时间_自检());
            const bool 运行账不完整 =
                方法->主信息.公共.统计.命中次数 > 0
                && 最近执行时间 == 0
                && 最近完成时间 == 0;
            if (!运行账不完整) {
                continue;
            }
            const std::string 去重键 = "自检|方法运行账|" + 方法->获取主键();
            if (私有_是否去重抑制中(去重账_, 去重键, now, 抑制微秒)) {
                continue;
            }
            std::ostringstream 观察;
            观察 << "方法运行账不完整 | 方法=" << 私有_方法标题(方法)
                << " | 命中次数=" << 方法->主信息.公共.统计.命中次数
                << " | 最近执行时间=" << 最近执行时间
                << " | 最近完成时间=" << 最近完成时间;
            const auto 候选 = 私有_构造自检缺口候选(
                去重键,
                方法,
                "方法运行账完整性",
                观察.str(),
                自检缺失结构_方法运行账,
                枚举_任务管理派生需求类型::缺信息,
                枚举_任务管理阻塞级别::轻微,
                false,
                now);
            if (私有_提交自检报告(候选, now)) {
                ++本轮报告型提交;
                {
                    std::lock_guard<std::mutex> 锁(状态锁_);
                    最近模式_ = 枚举_自检线程模式::运行中;
                    ++累计提交报告数_;
                    ++累计发现问题数_;
                    最近提交时间_ = now;
                    最近需求摘要_ = 私有_构造自检缺口候选文本(候选);
                    记录事件_已加锁(now, "发现并提交报告 | " + 最近需求摘要_);
                }
                私有_提示自检代码缺陷报告(候选);
            }
        }
    }

    if (本轮报告型提交 < 配置_.每轮提交上限
        && 私有_到期(最近检查时刻_, "状态清理", 配置_.方法补齐停滞检查间隔)) {
        if (停止检查("状态清理检查前")) {
            return;
        }
        const auto 快照 = 世界树.状态().读取最近清理问题快照();
        if (快照.需要自检报告) {
            const std::string 场景键 = !快照.场景.主键.empty()
                ? 快照.场景.主键
                : std::to_string(reinterpret_cast<std::uintptr_t>(快照.场景.指针));
            const std::string 去重键 = "自检|状态清理|"
                + 场景键
                + "|当前=" + std::to_string(快照.活动状态数量)
                + "|上限=" + std::to_string(快照.活动状态上限)
                + "|目标=" + std::to_string(快照.目标清理数量);
            if (!私有_是否去重抑制中(去重账_, 去重键, now, 抑制微秒)) {
                std::ostringstream 证据;
                证据 << "状态活动索引超限但未找到可清理状态"
                    << " | 场景=" << 场景键
                    << " | 当前=" << 快照.活动状态数量
                    << " | 上限=" << 快照.活动状态上限
                    << " | 目标清理=" << 快照.目标清理数量
                    << " | 已清理=" << 快照.已清理数量
                    << " | 被引用状态=" << 快照.被引用状态数量;
                const auto 候选 = 私有_构造自检缺口候选(
                    去重键,
                    nullptr,
                    "状态清理阻塞",
                    证据.str(),
                    自检缺失结构_状态清理阻塞,
                    枚举_任务管理派生需求类型::缺信息,
                    枚举_任务管理阻塞级别::轻微,
                    false,
                    now);
                if (私有_提交自检报告(候选, now, 自检范围_状态清理)) {
                    ++本轮报告型提交;
                    世界树.状态().清除最近清理问题快照();
                    {
                        std::lock_guard<std::mutex> 锁(状态锁_);
                        最近模式_ = 枚举_自检线程模式::运行中;
                        ++累计提交报告数_;
                        ++累计发现问题数_;
                        最近提交时间_ = now;
                        最近需求摘要_ = 私有_构造自检缺口候选文本(候选);
                        记录事件_已加锁(now, "发现并提交报告 | " + 最近需求摘要_);
                    }
                    私有_提示自检代码缺陷报告(候选);
                }
            }
        }
    }

    if (本轮总提交() == 0) {
        std::lock_guard<std::mutex> 锁(状态锁_);
        最近模式_ = 枚举_自检线程模式::运行中;
        记录事件_已加锁(now, "运行中自检完成 | 未发现需提交缺口");
    }
}

// 功能：执行任务、方法或动作的主体逻辑。
void 自检线程类::执行休眠期自检_(时间戳 now)
{
    项目运行日志("自检线程/休眠期自检 | 开始");
    ++休眠批次号_;
    std::size_t 本轮提交 = 0;
    const auto 抑制微秒 =
        static_cast<时间戳>(std::chrono::duration_cast<std::chrono::microseconds>(配置_.去重抑制间隔).count());

    {
        auto 候选集 = 私有_收集根特征自检缺口候选_自检(
            去重账_,
            now,
            抑制微秒,
            配置_.每轮提交上限 - 本轮提交,
            &停止请求_);
        for (const auto& 候选 : 候选集) {
            if (停止请求_.load()) {
                项目运行日志("自检线程/休眠期自检停止检查 | 阶段=根特征提交循环 | 跳过剩余自检=1");
                return;
            }
            if (私有_提交自检报告(候选, now, 自检范围_自我根特征)) {
                ++本轮提交;
                std::lock_guard<std::mutex> 锁(状态锁_);
                最近模式_ = 枚举_自检线程模式::休眠期;
                ++累计提交报告数_;
                ++累计发现问题数_;
                最近提交时间_ = now;
                最近需求摘要_ = 私有_构造自检缺口候选文本(候选);
                记录事件_已加锁(now, "休眠期提交根特征自检报告 | " + 最近需求摘要_);
            }
        }
    }

    auto* 自我存在 = 自我.获取自我存在();
    for (auto* 方法 : 私有_枚举方法首节点(配置_.单类扫描上限, &休眠方法扫描游标_)) {
        if (!方法 || 本轮提交 >= 配置_.每轮提交上限) {
            break;
        }
        if (方法->主信息.首节点信息().方法虚拟存在.有效()) {
            continue;
        }
        const std::string 去重键 = "自检|休眠|方法虚拟存在|" + 方法->获取主键();
        if (私有_是否去重抑制中(去重账_, 去重键, now, 抑制微秒)) {
            continue;
        }
        std::ostringstream 观察;
        观察 << "方法虚拟存在完整性缺口 | 方法=" << 私有_方法标题(方法);
        const auto 候选 = 私有_构造自检缺口候选(
            去重键,
            方法,
            "方法虚拟存在完整性",
            观察.str(),
            自检缺失结构_方法虚拟存在,
            枚举_任务管理派生需求类型::缺资源,
            枚举_任务管理阻塞级别::轻微,
            false,
            now);
        if (私有_提交自检报告(候选, now)) {
            ++本轮提交;
            {
                std::lock_guard<std::mutex> 锁(状态锁_);
                最近模式_ = 枚举_自检线程模式::休眠期;
                ++累计提交报告数_;
                ++累计发现问题数_;
                最近提交时间_ = now;
                最近需求摘要_ = 私有_构造自检缺口候选文本(候选);
                记录事件_已加锁(now, "休眠期发现并提交报告 | " + 最近需求摘要_);
            }
            私有_提示自检代码缺陷报告(候选);
        }
    }

    if (本轮提交 < 配置_.每轮提交上限 && 自我存在) {
        I64 当前可用方法数量 = 0;
        const I64 统计可用方法数量 = 私有_统计结构可用方法数量();
        if (自我.读取自我I64特征当前值(
                自我特征定义类::类型_自我_可用方法数量(),
                当前可用方法数量)
            && 当前可用方法数量 != 统计可用方法数量) {
            (void)自我.同步可用方法数量镜像(统计可用方法数量, now);
            I64 同步后可用方法数量 = 当前可用方法数量;
            if (自我.读取自我I64特征当前值(
                    自我特征定义类::类型_自我_可用方法数量(),
                    同步后可用方法数量)
                && 同步后可用方法数量 == 统计可用方法数量) {
                项目运行日志(
                    "自检线程/已同步可用方法数量镜像"
                    " | 旧值=" + std::to_string(当前可用方法数量)
                    + " | 新值=" + std::to_string(同步后可用方法数量));
                当前可用方法数量 = 同步后可用方法数量;
            }
        }
        if (自我.读取自我I64特征当前值(
                自我特征定义类::类型_自我_可用方法数量(),
                当前可用方法数量)
            && 当前可用方法数量 != 统计可用方法数量) {
            const std::string 去重键 = "自检|休眠|可用方法数量镜像|"
                + std::to_string(当前可用方法数量)
                + "->"
                + std::to_string(统计可用方法数量);
            if (!私有_是否去重抑制中(去重账_, 去重键, now, 抑制微秒)) {
                std::ostringstream 观察;
                观察 << "可用方法数量镜像不一致 | 当前=" << 当前可用方法数量
                    << " | 统计=" << 统计可用方法数量;
                const auto 候选 = 私有_构造自检缺口候选(
                    去重键,
                    nullptr,
                    "可用方法数量",
                    观察.str(),
                    自检缺失结构_可用方法数量镜像,
                    枚举_任务管理派生需求类型::补偿动作,
                    枚举_任务管理阻塞级别::轻微,
                    false,
                    now);
                if (私有_提交自检报告(候选, now)) {
                    ++本轮提交;
                    {
                        std::lock_guard<std::mutex> 锁(状态锁_);
                        最近模式_ = 枚举_自检线程模式::休眠期;
                        ++累计提交报告数_;
                        ++累计发现问题数_;
                        最近提交时间_ = now;
                        最近需求摘要_ = 私有_构造自检缺口候选文本(候选);
                        记录事件_已加锁(
                            now,
                            std::string("休眠期发现并提交报告 | ")
                                + 最近需求摘要_);
                    }
                    私有_提示自检代码缺陷报告(候选);
                }
            }
        }
    }

    if (本轮提交 == 0) {
        std::lock_guard<std::mutex> 锁(状态锁_);
        最近模式_ = 枚举_自检线程模式::休眠期;
        记录事件_已加锁(
            now,
            "休眠期自检完成 | 批次=" + std::to_string(休眠批次号_) + " | 未发现需提交缺口");
    }
    项目运行日志("自检线程/休眠期自检 | 完成 | 提交=" + std::to_string(本轮提交));
}

