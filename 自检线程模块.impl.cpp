    {
        if (!根节点 || !节点) {
            return false;
        }
        if (根节点 == 节点) {
            return true;
        }
        for (auto* 当前 = reinterpret_cast<const T节点*>(根节点->链下);
             当前 && 当前 != 根节点;
             当前 = reinterpret_cast<const T节点*>(当前->链下)) {
            if (当前 == 节点) {
                return true;
            }
        }
        return false;
    }

