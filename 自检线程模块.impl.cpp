    bool 私有_检查自检基础信息_自检(
        bool 只读观察模式,
        std::string& 摘要文本) noexcept
    {
        摘要文本.clear();
        std::vector<std::string> 缺项{};
        const auto 追加缺项 = [&](std::string 文本) {
            if (!文本.empty()) {
                缺项.push_back(std::move(文本));
            }
        };

        auto& 自我线程 = 获取全局自我线程();
        const auto 生命周期 = 自我线程.读取生命周期状态();
        if (生命周期 != 枚举_线程生命周期状态::运行中
            || !自我线程.是否运行中()
            || !自我线程.是否健康运行()) {
            追加缺项("自我线程运行态未成立");
        }
        if (!自我线程.是否初始化完成()) {
            追加缺项("自我初始化未完成");
        }

        auto* 自我存在 = 自我.获取自我存在();
        if (!自我存在) {
            追加缺项("自我存在不可读");
        }

        auto* 安全根需求 = 自我.获取安全根需求();
        if (!安全根需求) {
            追加缺项("安全根需求不可读");
        } else if (安全根需求->主信息.需求有效截止 != 0) {
            追加缺项("安全根需求已截止");
        }

        auto* 安全根任务 = 自我.获取安全根任务();
        if (!安全根任务) {
            追加缺项("安全根任务来源锚点不可读");
        } else if (安全根需求
            && !私有_引用指向需求_自检(安全根任务->主信息.对应需求, 安全根需求)) {
            追加缺项("安全根任务来源需求未指向安全根需求");
        }

        if (!自我.获取自我内部世界()) {
            追加缺项("自我内部世界不可读");
        }

        if (!自我特征定义类::类型_自我_安全值()
            || !自我特征定义类::类型_自我_服务值()
            || !自我特征定义类::类型_线程_生命周期状态()) {
            追加缺项("状态/特征查询入口不可用");
        }

        const auto 默认本能方法集 = 本能方法类::枚举默认自我本能方法ID();
        if (默认本能方法集.empty()
            || !本能方法类::查询默认动作名称(枚举_本能方法ID::自我_尝试学习)) {
            追加缺项("本能方法表不可读");
        }
        if (!取本能动作集().查询(枚举_本能方法ID::自我_尝试学习).has_value()
            || !取本能动作集().查询(枚举_本能方法ID::自我_建立条件结果对).has_value()) {
            追加缺项("本能动作注册表不可读");
        }

        const bool 通过 = 缺项.empty();
        std::ostringstream 摘要;
        摘要 << "自检线程/基础信息预检"
            << " | 通过=" << (通过 ? 1 : 0)
            << " | 模式=" << (只读观察模式 ? "只读观察" : "运行中")
            << " | 自我线程生命周期=" << static_cast<I64>(生命周期)
            << " | 自我线程运行中=" << (自我线程.是否运行中() ? 1 : 0)
            << " | 自我线程健康=" << (自我线程.是否健康运行() ? 1 : 0)
            << " | 自我初始化完成=" << (自我线程.是否初始化完成() ? 1 : 0)
            << " | 安全根需求=" << (安全根需求 ? 安全根需求->获取主键() : std::string("空"))
            << " | 安全根任务=" << (安全根任务 ? 安全根任务->获取主键() : std::string("空"));
        if (!缺项.empty()) {
            摘要 << " | 缺项=";
            for (std::size_t i = 0; i < 缺项.size(); ++i) {
                if (i > 0) {
                    摘要 << ";";
                }
                摘要 << 缺项[i];
            }
        }
        摘要文本 = 摘要.str();
        return 通过;
    }

