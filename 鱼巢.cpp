    int 私有_执行内部循环多轮稳定回归检查()
    {
        项目运行日志("控制面板命令/内部循环多轮稳定回归检查 | 开始");
        if (!私有_确保自我线程已启动("鱼巢::main/控制面板/内部循环多轮稳定回归检查")) {
            std::cerr << "自我线程启动失败。\n";
            return 4;
        }

        const bool 采样前已稳定 = 私有_等待任务管理摘要快照稳定(std::chrono::milliseconds(15000));

        constexpr std::size_t 轮数 = 10;
        std::size_t 最大需求数 = 0;
        std::size_t 最大任务头数 = 0;
        std::size_t 最大等待工作包数 = 0;
        std::vector<std::string> 失败项{};
        结构_控制面板快照 最近快照{};
        const auto 快照已静稳 = [](const 结构_控制面板快照& 快照) noexcept {
            const bool 自我去向稳定 =
                快照.自我线程当前最终去向 == "待机"
                || 快照.自我线程当前最终去向 == "进入收束"
                || 快照.自我线程当前最终去向 == "停止";
            return 自我去向稳定
                && !快照.任务管理工作线程正在执行
                && 快照.任务管理工作线程当前排队数 == 0
                && !快照.任务管理界面线程正在处理
                && 快照.任务管理界面线程当前等待工作包数 == 0
                && 快照.任务管理界面线程当前上行队列长度 == 0
                && !快照.任务管理界面线程故障;
        };

        const auto 加失败 = [&](const bool 条件, const std::string& 字段) {
            if (!条件) {
                失败项.emplace_back(字段);
            }
        };

        for (std::size_t 轮次 = 1; 轮次 <= 轮数; ++轮次) {
            // 多轮稳定验收只采“本轮治理已收束”的状态，避免把任务完成回执
            // 和自我线程需求回写之间的异步中间态误判为稳定性失败。
            const bool 本轮已稳定 =
                私有_等待任务管理摘要快照稳定(std::chrono::milliseconds(3000));
            const auto 快照 = 私有_等待快照满足条件(
                "内部循环多轮稳定单轮收束",
                [&](const 结构_控制面板快照& 候选快照) noexcept {
                    return 快照已静稳(候选快照)
                        && 候选快照.需求树完成任务仍活动需求数 == 0
                        && 候选快照.任务完成但缺对应需求数 == 0
                        && 候选快照.需求树活动执行需求未任务化数 == 0
                        && !候选快照.需求树存在重复目标风险
                        && !候选快照.需求树父子权重异常
                        && 候选快照.任务状态失败数 == 0
                        && 候选快照.任务状态无法执行数 == 0;
                });
            最近快照 = 快照;
            最大需求数 = (std::max)(最大需求数, 快照.需求数);
            最大任务头数 = (std::max)(最大任务头数, 快照.任务头节点数);
            最大等待工作包数 = (std::max)(最大等待工作包数, 快照.任务管理界面线程当前等待工作包数);

            const std::string 前缀 = "第" + std::to_string(轮次) + "轮:";
            加失败(本轮已稳定, 前缀 + "进入稳定态");
            加失败(快照.自我线程健康运行, 前缀 + "自我线程健康");
            加失败(!快照.需求树存在重复目标风险, 前缀 + "重复目标风险==无");
            加失败(!快照.需求树父子权重异常, 前缀 + "父子权重异常==无");
            加失败(快照.需求树活动执行需求未任务化数 == 0, 前缀 + "活动执行需求未任务化==0");
            if (快照.需求树完成任务仍活动需求数 != 0) {
                std::ostringstream 详情;
                详情 << 前缀 << "完成任务仍活动需求==0"
                    << "(需求=" << (快照.需求树首个完成任务仍活动需求主键.empty()
                        ? std::string("空")
                        : 快照.需求树首个完成任务仍活动需求主键)
                    << ",任务=" << (快照.需求树首个完成任务仍活动任务主键.empty()
                        ? std::string("空")
                        : 快照.需求树首个完成任务仍活动任务主键)
                    << ")";
                加失败(false, 详情.str());
            }
            加失败(快照.任务完成但缺对应需求数 == 0, 前缀 + "完成任务缺对应需求==0");
            加失败(快照.任务状态失败数 == 0, 前缀 + "任务失败==0");
            加失败(快照.任务状态无法执行数 == 0, 前缀 + "任务无法执行==0");
            加失败(!快照.任务管理界面线程故障, 前缀 + "任务管理界面线程故障==无");
            加失败(快照.需求数 <= 128, 前缀 + "需求数未风暴增长");
            加失败(快照.任务头节点数 <= 128, 前缀 + "任务头未风暴增长");
        }

        const bool 采样后已稳定 = 快照已静稳(最近快照);
        if (!采样前已稳定 && !采样后已稳定) {
            失败项.emplace_back("采样窗口未进入稳定态");
        }

        std::cout << "自我内部循环多轮稳定回归检查\n"
            << "  - 结果=" << (失败项.empty() ? "通过" : "失败") << '\n'
            << "  - 轮数=" << 轮数
            << " | 最大需求数=" << 最大需求数
            << " | 最大任务头=" << 最大任务头数
            << " | 最大等待工作包=" << 最大等待工作包数 << '\n'
            << "  - 采样前稳定=" << (采样前已稳定 ? "是" : "否")
            << " | 采样后稳定=" << (采样后已稳定 ? "是" : "否") << '\n'
            << "  - 边界=仅检查多轮稳定硬错误，不判定自我苏醒或初步成熟\n";

        if (!失败项.empty()) {
            std::cout << 渲染需求树生长摘要(最近快照)
                << 渲染任务管理摘要(最近快照, 12);
        } else if (!采样前已稳定) {
            std::cout << 渲染任务管理摘要(最近快照, 12);
        }

        if (!失败项.empty()) {
            std::ostringstream 日志;
            日志 << "控制面板命令/内部循环多轮稳定回归检查 | 失败项=";
            for (std::size_t i = 0; i < 失败项.size(); ++i) {
                if (i > 0) {
                    日志 << ',';
                }
                日志 << 失败项[i];
                std::cerr << "内部循环多轮稳定回归检查失败: " << 失败项[i] << '\n';
            }
            项目运行错误日志(日志.str());
            return 11;
        }

        项目运行日志("控制面板命令/内部循环多轮稳定回归检查 | 通过");
        return 0;
    }

