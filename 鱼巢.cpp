    std::size_t 私有_计数需求树节点_不含根(需求类::节点类* 根节点) noexcept
    {
        if (!根节点) {
            return 0;
        }

        std::size_t 数量 = 0;
        std::size_t 保护计数 = 0;
        for (auto* 当前 = 根节点->链下;
             当前 && 当前 != 根节点 && 保护计数 < 100000;
             当前 = 当前->链下, ++保护计数) {
            ++数量;
        }
        return 数量;
    }

    std::size_t 私有_计数直接子需求(需求类::节点类* 父需求) noexcept
    {
        if (!父需求 || !父需求->子) {
            return 0;
        }

        std::size_t 数量 = 0;
        std::size_t 保护计数 = 0;
        auto* 首子 = 父需求->子;
        auto* 当前 = 首子;
        do {
            ++数量;
            当前 = 当前 ? 当前->下 : nullptr;
            ++保护计数;
        } while (当前 && 当前 != 首子 && 保护计数 < 100000);

        return 数量;
    }

