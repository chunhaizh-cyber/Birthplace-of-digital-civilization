    int 私有_执行命令行相机命令(枚举_命令行相机命令 命令)
    {
        if (命令 == 枚举_命令行相机命令::无) {
            return 0;
        }

        if (命令 == 枚举_命令行相机命令::状态) {
            const auto 结果 = 双目相机本能适配器::检查();
            私有_输出并记录相机结果("状态", 结果);
            return 结果.原因 == 双目相机本能适配器::失败原因::无 ? 0 : 2;
        }

        if (命令 == 枚举_命令行相机命令::打开) {
            const auto 结果 = 双目相机本能适配器::打开();
            私有_输出并记录相机结果("打开", 结果);
            return 结果.成功 ? 0 : 2;
        }

        if (命令 == 枚举_命令行相机命令::释放) {
            const auto 结果 = 双目相机本能适配器::释放();
            私有_输出并记录相机结果("释放", 结果);
            return 结果.成功 ? 0 : 2;
        }

        const auto 打开结果 = 双目相机本能适配器::打开();
        私有_输出并记录相机结果("单帧采集/打开", 打开结果);
        if (!打开结果.成功) {
            return 2;
        }

        const auto 采集结果 = 双目相机本能适配器::采集一帧();
        私有_输出并记录相机结果("单帧采集/采集", 采集结果);
        if (采集结果.成功) {
            const auto 证据卡 = 提交D455单帧材料包证据卡(采集结果);
            if (!证据卡.empty()) {
                const auto 文本 = "单帧采集/材料包 | " + 证据卡;
                项目运行日志("命令行相机控制/" + 文本);
                std::cout << 文本 << '\n';
            }
        }

        const auto 释放结果 = 双目相机本能适配器::释放();
        私有_输出并记录相机结果("单帧采集/释放", 释放结果);

        return 采集结果.成功 ? 0 : 2;
    }

