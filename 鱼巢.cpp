    方法类::节点类* 私有_查找方法节点_按主键_控制命令(
        const std::string& 主键) noexcept
    {
        if (主键.empty()) {
            return nullptr;
        }
        auto* 自我存在 = 世界树.自我指针;
        auto* 方法根节点 = 自我存在 ? 世界树.存在().获取方法根节点(自我存在) : nullptr;
        if (!方法根节点) {
            return nullptr;
        }

        std::vector<方法类::节点类*> 待访问{};
        std::vector<方法类::节点类*> 已入栈{};
        const auto 已记录 = [&](const 方法类::节点类* 节点) noexcept {
            for (const auto* 已有 : 已入栈) {
                if (已有 == 节点) {
                    return true;
                }
            }
            return false;
        };
        const auto 压入 = [&](方法类::节点类* 节点) {
            if (!节点 || 已记录(节点)) {
                return;
            }
            已入栈.push_back(节点);
            待访问.push_back(节点);
        };

        压入(方法根节点);
        std::size_t 保护计数 = 0;
        while (!待访问.empty() && 保护计数 < 65536) {
            auto* 当前 = 待访问.back();
            待访问.pop_back();
            ++保护计数;
            if (当前 && 当前->获取主键() == 主键) {
                return 当前;
            }
            auto* 首子 = 当前 ? static_cast<方法类::节点类*>(当前->子) : nullptr;
            auto* 子 = 首子;
            std::size_t 子保护计数 = 0;
            while (子 && 子保护计数 < 4096) {
                压入(子);
                子 = static_cast<方法类::节点类*>(子->下);
                ++子保护计数;
                if (子 == 首子) {
                    break;
                }
            }
        }
        return nullptr;
    }

