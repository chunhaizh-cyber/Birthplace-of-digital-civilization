// 功能：读取可用于因果融合的标量区间，不创建或修改节点。
bool 二次特征类::读取可融合标量区间(const 二次特征节点类* 二次特征, I64区间& 输出区间) const noexcept
{
    输出区间 = I64区间{ 0, -1 };
    const auto* 主信息 = 取二次特征主信息(二次特征);
    if (!主信息) {
        return false;
    }
    if (主信息->标量区间.has_value() && 主信息->标量区间->有效()) {
        输出区间 = *主信息->标量区间;
        return true;
    }
    if (主信息->差值.has_value()) {
        输出区间 = I64区间::点(*主信息->差值);
        return true;
    }
    if (主信息->值形态 == 枚举_二次特征值形态::标量) {
        输出区间 = I64区间::点(主信息->标量值);
        return true;
    }
    return false;
}

// 功能：把同向状态迁移候选的可融合标量区间合并到目标二次特征。
bool 二次特征类::融合同向状态迁移可融合标量区间(
    二次特征节点类* 目标二次特征,
    const std::vector<二次特征节点类*>& 候选集合) const noexcept
{
    auto* 目标主信息 = 取二次特征主信息(目标二次特征);
    if (!目标主信息) {
        return false;
    }

    I64区间 当前区间{ 0, -1 };
    bool 当前区间有效 = 读取可融合标量区间(目标二次特征, 当前区间);
    bool 已变化 = false;
    for (auto* 候选 : 候选集合) {
        if (!候选 || 候选 == 目标二次特征) {
            continue;
        }
        if (需求类::比较需求方向(目标二次特征, 候选)
            != 需求类::枚举_需求方向比较结果::同向) {
            continue;
        }
        I64区间 候选区间{ 0, -1 };
        if (!读取可融合标量区间(候选, 候选区间)) {
            continue;
        }
        if (!当前区间有效 || !当前区间.有效()) {
            当前区间 = 候选区间;
            当前区间有效 = true;
            已变化 = true;
            continue;
        }
        const I64 新低值 = std::min(当前区间.低值, 候选区间.低值);
        const I64 新高值 = std::max(当前区间.高值, 候选区间.高值);
        if (新低值 != 当前区间.低值 || 新高值 != 当前区间.高值) {
            当前区间 = I64区间{ 新低值, 新高值 };
            已变化 = true;
        }
    }

    if (!已变化 || !当前区间.有效()) {
        return false;
    }
    目标主信息->标量区间 = 当前区间;
    return true;
}

// 功能：判断二次特征是否命中二次特征模板。
