    template<class T节点>
    可解析引用<T节点> 私有_生成引用(T节点* 节点)
    {
        可解析引用<T节点> out{};
        out.指针 = 节点;
        if (节点) out.主键 = 节点->获取主键();
        return out;
    }

    template<class T节点>
    bool 私有_引用已存在(
        const std::vector<可解析引用<T节点>>& 列表,
        T节点* 节点,
        const std::string& 节点主键)
    {
        for (const auto& 项 : 列表) {
            if (项.指针 == 节点) return true;
            if (!节点主键.empty() && !项.主键.empty() && 项.主键 == 节点主键) return true;
        }
        return false;
    }

