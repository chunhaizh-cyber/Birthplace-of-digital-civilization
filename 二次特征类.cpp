    template<class T主信息>
    std::vector<基础信息节点类*> 私有_直接基础信息子节点_按类型(
        const 基础信息类& 基础信息,
        const 基础信息节点类* 父节点)
    {
        std::vector<基础信息节点类*> 结果{};
        auto lk = 基础信息.获取读锁();
        auto* 父 = 父节点 ? const_cast<基础信息节点类*>(父节点) : 基础信息.世界根();
        if (!父 || !父->子) return 结果;

        auto* 首节点 = static_cast<基础信息节点类*>(父->子);
        auto* 当前 = 首节点;
        do {
            if (dynamic_cast<T主信息*>(当前->主信息)) {
                结果.push_back(当前);
            }
            当前 = static_cast<基础信息节点类*>(当前->下);
        } while (当前 && 当前 != 首节点);
        return 结果;
    }

