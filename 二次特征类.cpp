// 功能：建立对象、任务、方法或因果之间的绑定关系。
bool 二次特征类::绑定来源(
    二次特征节点类* 节点,
    状态节点类* 来源起始状态,
    状态节点类* 来源结果状态,
    动态节点类* 来源动态,
    场景节点类* 来源场景,
    std::uint32_t 来源动态层级,
    std::uint64_t 来源动态路径签名,
    枚举_二次特征来源类型 来源类型,
    结构_时间段 来源时间段,
    时间戳 分步时长,
    时间戳 总时长,
    时间戳 窗口时长)
{
    auto* 主信息 = 取二次特征主信息(节点);
    if (!主信息) return false;

    主信息->来源起始状态 = 私有_生成引用(来源起始状态);
    主信息->来源结果状态 = 私有_生成引用(来源结果状态);
    主信息->来源动态 = 私有_生成引用(来源动态);
    主信息->来源场景 = 私有_生成引用(来源场景);

    if (来源动态 && 基础信息_) {
        if (const auto* 动态主信息 = 基础信息_->取主信息<动态节点主信息类>(来源动态)) {
            if (来源动态层级 == 0) {
                来源动态层级 = 动态主信息->动态层级;
            }
            if (来源动态路径签名 == 0) {
                来源动态路径签名 = 动态主信息->动态路径签名;
            }
            if (来源时间段.起 == 0 && 来源时间段.止 == 0) {
                来源时间段 = 动态主信息->时间;
            }
            if (!来源场景 && 来源动态->父) {
                主信息->来源场景 = 私有_生成引用(static_cast<场景节点类*>(来源动态->父));
            }
        }
    }

    if (来源类型 == 枚举_二次特征来源类型::未定义) {
        if (来源动态) {
            来源类型 = 枚举_二次特征来源类型::动态;
        } else if (来源起始状态 || 来源结果状态) {
            来源类型 = 枚举_二次特征来源类型::状态;
        }
    }
    if ((来源时间段.起 == 0 || 来源时间段.止 == 0) && (来源起始状态 || 来源结果状态) && 基础信息_) {
        const auto* 起始状态主信息 = 基础信息_->取主信息<状态节点主信息类>(来源起始状态);
        const auto* 结果状态主信息 = 基础信息_->取主信息<状态节点主信息类>(来源结果状态);
        if (来源时间段.起 == 0 && 起始状态主信息) {
            来源时间段.起 = 起始状态主信息->发生时间 != 0
                ? 起始状态主信息->发生时间
                : 起始状态主信息->收到时间;
        }
        if (来源时间段.止 == 0 && 结果状态主信息) {
            来源时间段.止 = 结果状态主信息->发生时间 != 0
                ? 结果状态主信息->发生时间
                : 结果状态主信息->收到时间;
        }
    }
    if (总时长 == 0
        && 来源时间段.起 != 0
        && 来源时间段.止 >= 来源时间段.起
        && 分步时长 == 0) {
        总时长 = 来源时间段.止 - 来源时间段.起;
    }

    主信息->来源类型 = 来源类型;
    主信息->来源时间段 = 来源时间段;
    主信息->分步时长 = 分步时长;
    主信息->总时长 = 总时长;
    主信息->窗口时长 = 窗口时长;
    主信息->来源动态层级 = 来源动态层级;
    主信息->来源动态路径签名 = 来源动态路径签名;
    主信息->刷新度量签名_链键();
    return true;
}

