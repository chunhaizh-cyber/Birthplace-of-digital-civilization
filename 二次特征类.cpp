// 功能：读取状态迁移二次特征的来源状态和动态，不创建或修改节点。
bool 二次特征类::读取状态迁移来源(
    const 二次特征节点类* 二次特征,
    状态节点类*& 来源起始状态,
    状态节点类*& 来源结果状态,
    动态节点类*& 来源动态) const noexcept
{
    来源起始状态 = nullptr;
    来源结果状态 = nullptr;
    来源动态 = nullptr;

    const auto* 主信息 = 取二次特征主信息(二次特征);
    if (!主信息 || 主信息->形态 != 二次特征主信息类::枚举_形态::状态迁移) {
        return false;
    }

    状态类 状态读取{ 基础信息_ };
    动态类 动态读取{ 基础信息_ };
    const auto 解析状态引用 = [&](const 可解析引用<状态节点类>& 引用) -> 状态节点类* {
        if (引用.指针 && 状态读取.取状态主信息(引用.指针)) {
            return 引用.指针;
        }
        return 状态读取.按主键解析状态节点(引用.主键);
    };
    const auto 解析动态引用 = [&](const 可解析引用<动态节点类>& 引用) -> 动态节点类* {
        if (引用.指针 && 动态读取.取动态主信息(引用.指针)) {
            return 引用.指针;
        }
        return 动态读取.按主键解析动态节点(引用.主键);
    };

    来源起始状态 = 解析状态引用(主信息->来源起始状态);
    来源结果状态 = 解析状态引用(主信息->来源结果状态);
    来源动态 = 解析动态引用(主信息->来源动态);
    return true;
}

