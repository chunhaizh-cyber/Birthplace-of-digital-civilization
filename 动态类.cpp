// 功能：设置对象字段、状态或运行参数。
bool 动态类::设置聚合信息(动态节点类* 节点, std::uint32_t 动态层级, 枚举_动态聚合方式 聚合方式)
{
    auto* 主信息 = 取动态主信息(节点);
    if (!主信息) return false;

    主信息->动态层级 = 动态层级;
    主信息->聚合方式 = 聚合方式;
    return true;
}

// 功能：按函数名执行对应处理。
bool 动态类::追加来源低层动态(动态节点类* 节点, 动态节点类* 来源低层动态)
{
    auto* 主信息 = 取动态主信息(节点);
    if (!主信息 || !来源低层动态) return false;

    if (!私有_引用已存在(主信息->来源低层动态, 来源低层动态)) {
        主信息->来源低层动态.push_back(私有_生成引用(来源低层动态));
    }
    return true;
}

// 功能：建立对象、任务、方法或因果之间的绑定关系。
bool 动态类::绑定来源方法(
    动态节点类* 节点,
    方法节点类* 来源动作,
    const 语素入口节点类* 来源动作名)
{
    auto* 主信息 = 取动态主信息(节点);
    if (!主信息 || !允许生成方法动作动态(来源动作)) return false;

    主信息->来源动作.指针 = 来源动作;
    const auto* 方法 = reinterpret_cast<const 方法类::节点类*>(来源动作);
    主信息->来源动作名 = 来源动作名 ? 来源动作名 : (方法 ? 方法->主信息.首节点信息().动作名 : nullptr);
    主信息->名称 = 私有_推导动态名称(*主信息);
    主信息->类型 = 私有_推导动态类型(*主信息);
    return true;
}

// 功能：建立对象、任务、方法或因果之间的绑定关系。
bool 动态类::绑定来源场景(动态节点类* 节点, 场景节点类* 输入场景, 场景节点类* 输出场景)
{
    auto* 主信息 = 取动态主信息(节点);
    if (!主信息) return false;

    主信息->来源输入场景 = 私有_生成引用(输入场景);
    主信息->来源输出场景 = 私有_生成引用(输出场景);
    return true;
}
