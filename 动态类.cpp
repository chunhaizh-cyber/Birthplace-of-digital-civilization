    // 功能：按条件查找目标对象、方法或事实。
    std::uint64_t 私有_相邻前状态查找采样序号(std::uint64_t 总耗时微秒) noexcept
    {
        if (总耗时微秒 < 100000) {
            return 0;
        }
        static std::atomic<std::uint64_t> s_慢查找序号{0};
        const auto 序号 = s_慢查找序号.fetch_add(1, std::memory_order_relaxed) + 1;
        if (序号 <= 3 || (序号 % 10) == 0 || 总耗时微秒 >= 500000) {
            return 序号;
        }
        return 0;
    }

