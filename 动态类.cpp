// 功能：读取动态来源输入场景和输出场景，不创建或修改节点。
bool 动态类::读取动态来源场景(
    const 动态节点类* 动态,
    场景节点类*& 输入场景,
    场景节点类*& 输出场景) const noexcept
{
    输入场景 = nullptr;
    输出场景 = nullptr;

    const auto* 主信息 = 取动态主信息(动态);
    if (!基础信息_ || !主信息) {
        return false;
    }

    场景类 场景服务(基础信息_);
    const auto 解析场景引用 = [&](const 可解析引用<场景节点类>& 引用) -> 场景节点类* {
        if (引用.指针 && 场景服务.取场景主信息(引用.指针)) {
            return 引用.指针;
        }
        return 场景服务.按主键解析场景节点(引用.主键);
    };

    输入场景 = 解析场景引用(主信息->来源输入场景);
    输出场景 = 解析场景引用(主信息->来源输出场景);
    return true;
}

