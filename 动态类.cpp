    // 功能：按动态结构字段推导名称语义入口。
    const 语素入口节点类* 私有_推导动态名称(const 动态节点主信息类& 主信息) noexcept
    {
        if (主信息.来源动作名) {
            return 主信息.来源动作名;
        }
        if (const auto* 方法动作名 = 私有_来源方法动作名(主信息)) {
            return 方法动作名;
        }
        if (主信息.初始状态.指针 || 主信息.结果状态.指针) {
            return 语素集.添加信息入口词("状态变化", 枚举_信息入口类型::动态模板入口);
        }
        if (主信息.动态特征.指针 && 主信息.动态特征.指针->主信息) {
            if (const auto* 特征类型 = 主信息.动态特征.指针->主信息->类型) {
                return 特征类型;
            }
        }
        return 语素集.添加信息入口词("未知动作", 枚举_信息入口类型::动态模板入口);
    }

    // 功能：按动态结构字段推导动态类别入口。
    const 语素入口节点类* 私有_推导动态类型(const 动态节点主信息类& 主信息) noexcept
    {
        if (主信息.来源动作.指针) {
            return 语素集.添加信息入口词("主动动作动态", 枚举_信息入口类型::动态模板入口);
        }
        if (主信息.来源动作名
            || ((!主信息.初始状态.指针 && !主信息.结果状态.指针)
                && (主信息.动态主体.指针 || 主信息.动态特征.指针))) {
            return 语素集.添加信息入口词("被动动作动态", 枚举_信息入口类型::动态模板入口);
        }
        return 语素集.添加信息入口词("无动作状态变化动态", 枚举_信息入口类型::动态模板入口);
    }

    // 功能：补齐动态名称语义和动态类别入口。
    void 私有_补齐动态名称类型(动态节点主信息类* 主信息) noexcept
    {
        if (!主信息) {
            return;
        }
        if (!主信息->名称) {
            主信息->名称 = 私有_推导动态名称(*主信息);
        }
        if (!主信息->类型) {
            主信息->类型 = 私有_推导动态类型(*主信息);
        }
    }

    template<class T节点>
    bool 私有_引用已存在(const std::vector<可解析引用<T节点>>& 列表, T节点* 节点)
    {
        for (const auto& 项 : 列表) {
            if (项.指针 == 节点) return true;
            if (节点 && !项.主键.empty() && 项.主键 == 节点->获取主键()) return true;
        }
        return false;
    }

    template<class T节点>
    bool 私有_引用匹配节点(const 可解析引用<T节点>& 引用, const T节点* 节点) noexcept
    {
        if (!节点) return false;
        if (引用.指针 == 节点) return true;
        return !引用.主键.empty() && 引用.主键 == 节点->获取主键();
    }

    template<class T节点, class T主信息>
    T节点* 私有_尝试按指针解析引用(基础信息类* 基础信息, const 可解析引用<T节点>& 引用) noexcept
    {
        if (!基础信息 || !引用.指针) {
            return nullptr;
        }
        auto* 节点 = 引用.指针;
        if (!基础信息->取主信息<T主信息>(节点)) {
            return nullptr;
        }
        if (!引用.主键.empty() && 节点->获取主键() != 引用.主键) {
            return nullptr;
        }
        return 节点;
    }

    // 功能：按指针或主键只读解析特征引用，不创建或修改节点。
    特征节点类* 私有_解析特征引用(基础信息类* 基础信息, const 可解析引用<特征节点类>& 引用) noexcept
    {
        if (!基础信息) {
            return nullptr;
        }

        if (auto* 指针节点 = 私有_尝试按指针解析引用<特征节点类, 特征节点主信息类>(基础信息, 引用)) {
            return 指针节点;
        }

        if (!引用.主键.empty()) {
            auto* 基础节点 = 基础信息->查找主键(引用.主键);
            auto* 特征节点 = 基础节点 ? static_cast<特征节点类*>(基础节点) : nullptr;
            if (特征节点 && 基础信息->取主信息<特征节点主信息类>(特征节点)) {
                return 特征节点;
            }
        }

        if (引用.指针) {
            const auto* 目标地址 = reinterpret_cast<const 基础信息节点类*>(引用.指针);
            for (auto* 基础节点 : 基础信息->枚举节点_按类型<特征节点主信息类>()) {
                if (基础节点 == 目标地址) {
                    return static_cast<特征节点类*>(基础节点);
                }
            }
        }

        return nullptr;
    }

