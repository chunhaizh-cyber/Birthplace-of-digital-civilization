    // 功能：计算权重、状态、差值或派生结果。
    std::uint64_t 私有_计算动态路径签名(
        const 状态节点主信息类* 初始状态,
        const 状态节点主信息类* 结果状态,
        const 基础信息节点类* 动态主体,
        const 特征节点类* 动态特征) noexcept
    {
        const std::uint64_t pack[6] = {
            static_cast<std::uint64_t>(reinterpret_cast<std::uintptr_t>(动态主体)),
            static_cast<std::uint64_t>(reinterpret_cast<std::uintptr_t>(动态特征)),
            static_cast<std::uint64_t>(reinterpret_cast<std::uintptr_t>(初始状态 ? 初始状态->状态主体.指针 : nullptr)),
            static_cast<std::uint64_t>(reinterpret_cast<std::uintptr_t>(结果状态 ? 结果状态->状态主体.指针 : nullptr)),
            static_cast<std::uint64_t>(初始状态 ? 私有_取状态时间(*初始状态) : 0),
            static_cast<std::uint64_t>(结果状态 ? 私有_取状态时间(*结果状态) : 0),
        };
        return static_cast<std::uint64_t>(std::hash<std::string_view>{}(
            std::string_view(reinterpret_cast<const char*>(pack), sizeof(pack))));
    }

    // 功能：解析输入文本、消息、场景或运行包。
    动态节点类* 私有_解析动态引用(基础信息类* 基础信息, const 可解析引用<动态节点类>& 引用)
    {
        if (!基础信息) {
            return nullptr;
        }

        if (auto* 指针节点 = 私有_尝试按指针解析引用<动态节点类, 动态节点主信息类>(基础信息, 引用)) {
            return 指针节点;
        }

        if (!引用.主键.empty()) {
            auto* 基础节点 = 基础信息->查找主键(引用.主键);
            auto* 动态节点 = 基础节点 ? static_cast<动态节点类*>(基础节点) : nullptr;
            if (动态节点 && 基础信息->取主信息<动态节点主信息类>(动态节点)) {
                return 动态节点;
            }
        }

        if (引用.指针) {
            const auto* 目标地址 = reinterpret_cast<const 基础信息节点类*>(引用.指针);
            for (auto* 基础节点 : 基础信息->枚举节点_按类型<动态节点主信息类>()) {
                if (基础节点 == 目标地址) {
                    return static_cast<动态节点类*>(基础节点);
                }
            }
        }

        return nullptr;
    }

    // 功能：解析输入文本、消息、场景或运行包。
    状态节点类* 私有_解析状态引用(基础信息类* 基础信息, const 可解析引用<状态节点类>& 引用)
    {
        if (!基础信息) {
            return nullptr;
        }

        if (auto* 指针节点 = 私有_尝试按指针解析引用<状态节点类, 状态节点主信息类>(基础信息, 引用)) {
            return 指针节点;
        }

        if (!引用.主键.empty()) {
            auto* 基础节点 = 基础信息->查找主键(引用.主键);
            auto* 状态节点 = 基础节点 ? static_cast<状态节点类*>(基础节点) : nullptr;
            if (状态节点 && 基础信息->取主信息<状态节点主信息类>(状态节点)) {
                return 状态节点;
            }
        }

        if (引用.指针) {
            const auto* 目标地址 = reinterpret_cast<const 基础信息节点类*>(引用.指针);
            for (auto* 基础节点 : 基础信息->枚举节点_按类型<状态节点主信息类>()) {
                if (基础节点 == 目标地址) {
                    return static_cast<状态节点类*>(基础节点);
                }
            }
        }

        return nullptr;
    }

    // 功能：按条件查找目标对象、方法或事实。
    动态节点类* 私有_查找已有状态动态(
        基础信息类* 基础信息,
        场景节点类* 场景,
        状态节点类* 初始状态,
        状态节点类* 结果状态,
        std::uint32_t 动态层级)
    {
        const auto* 场景主信息 = 基础信息 ? 基础信息->取主信息<场景节点主信息类>(场景) : nullptr;
        if (!基础信息 || !场景主信息 || !初始状态 || !结果状态) {
            return nullptr;
        }

        std::vector<可解析引用<动态节点类>> 动态索引快照;
        {
            std::lock_guard<std::recursive_mutex> 锁(借用场景索引全局互斥());
            动态索引快照 = 场景主信息->动态索引;
        }

        for (const auto& 项 : 动态索引快照) {
            auto* 动态节点 = 私有_解析动态引用(基础信息, 项);
            const auto* 主信息 = 基础信息->取主信息<动态节点主信息类>(动态节点);
            if (!动态节点 || !主信息) continue;
            if (主信息->动态层级 != 动态层级) continue;
            if (!私有_引用匹配节点(主信息->初始状态, 初始状态)) continue;
            if (!私有_引用匹配节点(主信息->结果状态, 结果状态)) continue;
            return 动态节点;
        }
        return nullptr;
    }

    // 功能：补齐条件、参数、证据或方法能力缺口。
    void 私有_自动补齐动态主体基础特征(基础信息类* 基础信息, 动态节点主信息类* 主信息) noexcept
    {
        if (!基础信息 || !主信息) {
            return;
        }

        auto* 初始状态 = 私有_解析状态引用(基础信息, 主信息->初始状态);
        auto* 结果状态 = 私有_解析状态引用(基础信息, 主信息->结果状态);
        const auto* 初始状态主信息 = 基础信息->取主信息<状态节点主信息类>(初始状态);
        const auto* 结果状态主信息 = 基础信息->取主信息<状态节点主信息类>(结果状态);

        if (!主信息->动态主体.有效()) {
            if (结果状态主信息 && 结果状态主信息->状态主体.有效()) {
                主信息->动态主体 = 结果状态主信息->状态主体;
            }
            else if (初始状态主信息 && 初始状态主信息->状态主体.有效()) {
                主信息->动态主体 = 初始状态主信息->状态主体;
            }
        }

        if (!主信息->动态特征.有效()) {
            if (结果状态主信息 && 结果状态主信息->状态特征.有效()) {
                主信息->动态特征 = 结果状态主信息->状态特征;
            }
            else if (初始状态主信息 && 初始状态主信息->状态特征.有效()) {
                主信息->动态特征 = 初始状态主信息->状态特征;
            }
        }
    }

    // 功能：服务所在模块的内部辅助流程。
    void 私有_按时间追加动态索引(
        基础信息类* 基础信息,
        场景节点主信息类* 场景主信息,
        动态节点类* 节点)
    {
        if (!场景主信息 || !节点) return;
        std::lock_guard<std::recursive_mutex> 锁(借用场景索引全局互斥());
        if (!私有_引用已存在(场景主信息->动态索引, 节点)) {
            场景主信息->动态索引.push_back(私有_生成引用(节点));
        }
        std::stable_sort(场景主信息->动态索引.begin(), 场景主信息->动态索引.end(), [基础信息](const auto& 左, const auto& 右) {
            const auto* 左主信息 = (基础信息 && 左.指针) ? 基础信息->取主信息<动态节点主信息类>(左.指针) : nullptr;
            const auto* 右主信息 = (基础信息 && 右.指针) ? 基础信息->取主信息<动态节点主信息类>(右.指针) : nullptr;
            const auto 左时间 = 左主信息 ? 私有_取动态时间(*左主信息) : 0;
            const auto 右时间 = 右主信息 ? 私有_取动态时间(*右主信息) : 0;
            if (左时间 != 右时间) return 左时间 < 右时间;
            return 左.主键 < 右.主键;
        });
    }
