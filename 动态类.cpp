    std::string 私有_引用主键(const 可解析引用<方法节点类>& 引用)
    {
        if (引用.指针) {
            const auto* 方法 = reinterpret_cast<const 方法类::节点类*>(引用.指针);
            return 方法 ? 方法->获取主键() : std::string{};
        }
        return 引用.主键;
    }

    template<class T节点>
    std::string 私有_引用主键(const 可解析引用<T节点>& 引用)
    {
        if (引用.指针) {
            return 引用.指针->获取主键();
        }
        return 引用.主键;
    }

    template<class T节点>
    可解析引用<T节点> 私有_生成引用(T节点* 节点)
    {
        可解析引用<T节点> out{};
        out.指针 = 节点;
        if (节点) out.主键 = 节点->获取主键();
        return out;
    }

    template<class T节点>
    bool 私有_引用同一(const 可解析引用<T节点>& 左, const 可解析引用<T节点>& 右) noexcept
    {
        if (!左.有效() || !右.有效()) return false;
        if (左.指针 && 右.指针) return 左.指针 == 右.指针;
        const auto 左主键 = 私有_引用主键(左);
        const auto 右主键 = 私有_引用主键(右);
        return !左主键.empty() && 左主键 == 右主键;
    }

    // 功能：向只读样本集合追加来源动态，限制容量避免分析视图无界膨胀。
    void 私有_追加影响来源动态样本(std::vector<动态节点类*>& 样本集合, 动态节点类* 来源动态)
    {
        if (!来源动态 || 样本集合.size() >= 64) {
            return;
        }
        for (auto* 已有 : 样本集合) {
            if (已有 == 来源动态) {
                return;
            }
        }
        样本集合.push_back(来源动态);
    }

