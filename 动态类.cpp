// 功能：删除指定对象、状态或登记项。
bool 动态类::删除动态(动态节点类* 节点)
{
    if (!基础信息_ || !节点) return false;

    auto* 父节点 = static_cast<基础信息节点类*>(节点->父);
    auto* 场景主信息 = 基础信息_->取主信息<场景节点主信息类>(父节点);
    if (场景主信息) {
        std::lock_guard<std::recursive_mutex> 锁(借用场景索引全局互斥());
        场景主信息->动态索引.erase(
            std::remove_if(
                场景主信息->动态索引.begin(),
                场景主信息->动态索引.end(),
                [&](const auto& 项) { return 项.指针 == 节点 || 项.主键 == 节点->获取主键(); }),
            场景主信息->动态索引.end());
    }

    return 基础信息_->删除节点(节点);
}

// 功能：按函数名执行对应处理。
std::vector<动态节点类*> 动态类::枚举全部动态() const
{
    std::vector<动态节点类*> out;
    if (!基础信息_) return out;

    for (auto* 节点 : 基础信息_->枚举节点_按类型<动态节点主信息类>()) {
        out.push_back(static_cast<动态节点类*>(节点));
    }
    return out;
}

// 功能：读取并返回指定对象、状态或运行材料。
std::vector<动态节点类*> 动态类::获取场景动态(const 场景节点类* 场景) const
{
    std::vector<动态节点类*> out;
    const auto* 场景主信息 = 基础信息_ ? 基础信息_->取主信息<场景节点主信息类>(场景) : nullptr;
    if (!场景主信息) return out;

    std::vector<可解析引用<动态节点类>> 动态索引快照;
    {
        std::lock_guard<std::recursive_mutex> 锁(借用场景索引全局互斥());
        动态索引快照 = 场景主信息->动态索引;
    }

    for (const auto& 项 : 动态索引快照) {
        if (auto* 动态节点 = 私有_解析动态引用(基础信息_, 项)) {
            out.push_back(动态节点);
        }
    }
    return out;
}

// 功能：按条件查找目标对象、方法或事实。
状态节点类* 动态类::查找相邻前状态(场景节点类* 场景, 状态节点类* 新状态) const
{
    if (!基础信息_ || !场景 || !新状态) return nullptr;

    const auto 查找开始 = 私有_动态阶段时间点();
    std::uint64_t 前置检查耗时微秒 = 0;
    std::uint64_t 状态索引快照耗时微秒 = 0;
    std::uint64_t 倒序扫描耗时微秒 = 0;
    std::size_t 状态索引数量 = 0;
    std::size_t 扫描数量 = 0;
    std::size_t 解析成功数量 = 0;
    std::size_t 主信息有效数量 = 0;
    std::size_t 当前状态跳过数量 = 0;
    std::size_t 基础动态失败数量 = 0;

    const auto 前置检查开始 = 私有_动态阶段时间点();
    const auto* 新状态主信息 = 基础信息_->取主信息<状态节点主信息类>(新状态);
    if (!新状态主信息 || !新状态主信息->状态主体.有效() || !新状态主信息->状态特征.有效()) {
        return nullptr;
    }

    const auto* 场景主信息 = 基础信息_->取主信息<场景节点主信息类>(场景);
    if (!场景主信息) {
        return nullptr;
    }
    前置检查耗时微秒 = 私有_动态阶段耗时微秒(
        前置检查开始,
        私有_动态阶段时间点());

    auto 记录慢查找 = [&](状态节点类* 前状态) {
        const auto 总耗时微秒 = 私有_动态阶段耗时微秒(
            查找开始,
            私有_动态阶段时间点());
        const auto 采样序号 = 私有_相邻前状态查找采样序号(总耗时微秒);
        if (采样序号 == 0) {
            return;
        }

        std::string 最慢阶段 = "前置检查";
        std::uint64_t 最慢阶段耗时微秒 = 前置检查耗时微秒;
        auto 记录最慢 = [&最慢阶段, &最慢阶段耗时微秒](
            const char* 阶段,
            std::uint64_t 耗时) {
            if (耗时 > 最慢阶段耗时微秒) {
                最慢阶段 = 阶段;
                最慢阶段耗时微秒 = 耗时;
            }
        };
        记录最慢("状态索引快照", 状态索引快照耗时微秒);
        记录最慢("倒序扫描", 倒序扫描耗时微秒);

        std::ostringstream 日志;
        日志 << "相邻前状态查找/内部阶段耗时"
            << " | 序号=" << 采样序号
            << " | 场景=" << (场景 ? 场景->获取主键() : std::string{})
            << " | 新状态=" << (新状态 ? 新状态->获取主键() : std::string{})
            << " | 主体=" << (新状态主信息 && 新状态主信息->状态主体.指针 ? 新状态主信息->状态主体.指针->获取主键() : std::string{})
            << " | 特征=" << (新状态主信息 && 新状态主信息->状态特征.指针 ? 新状态主信息->状态特征.指针->获取主键() : std::string{})
            << " | 命中=" << (前状态 ? 1 : 0)
            << " | 前状态=" << (前状态 ? 前状态->获取主键() : std::string{})
            << " | 状态索引数量=" << 状态索引数量
            << " | 扫描数量=" << 扫描数量
            << " | 解析成功数量=" << 解析成功数量
            << " | 主信息有效数量=" << 主信息有效数量
            << " | 当前状态跳过数量=" << 当前状态跳过数量
            << " | 基础动态失败数量=" << 基础动态失败数量
            << " | 总耗时微秒=" << 总耗时微秒
            << " | 最慢阶段=" << 最慢阶段
            << " | 最慢阶段耗时微秒=" << 最慢阶段耗时微秒
            << " | 前置检查=" << 前置检查耗时微秒
            << " | 状态索引快照=" << 状态索引快照耗时微秒
            << " | 倒序扫描=" << 倒序扫描耗时微秒;
        项目运行日志(日志.str());
    };

    std::vector<可解析引用<状态节点类>> 状态索引快照;
    {
        const auto 状态索引快照开始 = 私有_动态阶段时间点();
        std::lock_guard<std::recursive_mutex> 锁(借用场景索引全局互斥());
        状态索引快照 = 场景主信息->状态索引;
        状态索引快照耗时微秒 = 私有_动态阶段耗时微秒(
            状态索引快照开始,
            私有_动态阶段时间点());
    }
    状态索引数量 = 状态索引快照.size();
    if (状态索引快照.empty()) {
        记录慢查找(nullptr);
        return nullptr;
    }

    bool 已跳过当前状态 = false;
    const auto 倒序扫描开始 = 私有_动态阶段时间点();
    for (std::size_t i = 状态索引快照.size(); i > 0; --i) {
        const auto& 状态引用 = 状态索引快照[i - 1];
        ++扫描数量;
        auto* 候选节点 = 私有_解析状态引用(基础信息_, 状态引用);
        if (候选节点) {
            ++解析成功数量;
        }
        const auto* 候选主信息 = 基础信息_->取主信息<状态节点主信息类>(候选节点);
        if (!候选主信息) continue;
        ++主信息有效数量;

        const bool 是当前状态 =
            候选节点 == 新状态
            || (候选节点 && 新状态 && 候选节点->获取主键() == 新状态->获取主键())
            || (私有_引用匹配节点(候选主信息->状态主体, 新状态主信息->状态主体.指针)
                && 私有_引用匹配节点(候选主信息->状态特征, 新状态主信息->状态特征.指针)
                && 候选主信息->发生时间 == 新状态主信息->发生时间
                && 候选主信息->收到时间 == 新状态主信息->收到时间
                && 私有_特征值相等(候选主信息->状态值, 新状态主信息->状态值));
        if (!已跳过当前状态 && 是当前状态) {
            已跳过当前状态 = true;
            ++当前状态跳过数量;
            continue;
        }

        if (!私有_可形成基础动态(候选主信息, 新状态主信息)) {
            ++基础动态失败数量;
            continue;
        }
        倒序扫描耗时微秒 = 私有_动态阶段耗时微秒(
            倒序扫描开始,
            私有_动态阶段时间点());
        记录慢查找(候选节点);
        return 候选节点;
    }

    倒序扫描耗时微秒 = 私有_动态阶段耗时微秒(
        倒序扫描开始,
        私有_动态阶段时间点());
    记录慢查找(nullptr);
    return nullptr;
}

// 功能：记录日志、动态、证据或运行痕迹。
