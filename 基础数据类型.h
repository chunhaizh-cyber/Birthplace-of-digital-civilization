// 功能：按函数名执行对应处理。
inline bool 特征生命周期仍在试用暴露期(枚举_特征生命周期 生命周期) noexcept
{
    return 生命周期 == 枚举_特征生命周期::候选
        || 生命周期 == 枚举_特征生命周期::试用;
}

inline bool 特征统计应保留(
    const 结构_特征使用统计& 统计,
    枚举_特征生命周期 生命周期,
    bool 试用期已结束 = false) noexcept
{
    if (特征生命周期仍在试用暴露期(生命周期)) {
        return !试用期已结束;
    }

    return 统计.结果改变次数 > 0
        || 统计.下游依赖特征数 > 0
        || 统计.作为风险闸门次数 > 0
        || 统计.作为需求触发次数 > 0;
}

inline bool 特征统计应归档(
    const 结构_特征使用统计& 统计,
    枚举_特征生命周期 生命周期,
    bool 试用期已结束 = false) noexcept
{
    if (!特征生命周期仍在试用暴露期(生命周期) || !试用期已结束) {
        return false;
    }

    return 统计.结果改变次数 == 0
        && 统计.下游依赖特征数 == 0
        && 统计.作为风险闸门次数 == 0
        && 统计.作为需求触发次数 == 0;
}

inline 枚举_特征生命周期 基于使用统计更新特征生命周期(
    const 结构_特征使用统计& 统计,
    枚举_特征生命周期 当前生命周期,
    bool 试用期已结束 = false) noexcept
{
    if (当前生命周期 == 枚举_特征生命周期::候选) {
        return 枚举_特征生命周期::试用;
    }

    if (特征统计应归档(统计, 当前生命周期, 试用期已结束)) {
        return 枚举_特征生命周期::归档;
    }

    if (特征统计应保留(统计, 当前生命周期, 试用期已结束)) {
        return 枚举_特征生命周期::激活;
    }

    if (统计.历史使用次数 > 0 && 统计.近期使用次数 == 0) {
        return 枚举_特征生命周期::冷却;
    }

    return 当前生命周期;
}
