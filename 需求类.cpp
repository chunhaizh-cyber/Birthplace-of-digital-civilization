    指令.需求名称 = 目标特征;
    指令.目标特征类型缓存 = 目标特征;
    指令.满足关系 = 输入.满足关系 != 0 ? 输入.满足关系 : 关系_等于;
    指令.派生来源方法主键 = 输入.派生来源方法主键;
