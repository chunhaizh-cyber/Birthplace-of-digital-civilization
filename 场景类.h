#pragma once

#include <limits>

#include "基础信息类.h"
#include "特征类.h"

struct 结构_场景三维体素轮廓查找参数 {
    const 语素入口节点类* 三维体素特征类型 = nullptr;
    std::uint32_t 查询层级 = (std::numeric_limits<std::uint32_t>::max)();
    I64 最低相似度Q10000 = 0;
    std::uint32_t 默认存在最小体素边长_mm = 0;
    std::uint64_t 最大返回数量 = 0;
};

struct 结构_场景三维体素轮廓存在比较结果 {
    存在节点类* 存在 = nullptr;
    特征节点类* 三维体素特征 = nullptr;
    I64 相似度Q10000 = 0;
    结构_三维体素局部轮廓相似度结果 比较结果{};
};

class 场景类 {
public:
    explicit 场景类(基础信息类* 基础信息 = nullptr) noexcept;

    void 绑定基础信息(基础信息类* 基础信息) noexcept;

    场景节点主信息类* 取场景主信息(场景节点类* 节点) const noexcept;
    const 场景节点主信息类* 取场景主信息(const 场景节点类* 节点) const noexcept;

    // 功能：判断基础信息节点是否为场景节点，不创建或修改节点。
    bool 是场景节点(const 基础信息节点类* 节点) const noexcept;

    // 功能：按主键查找并解析场景节点，不创建或修改节点。
    场景节点类* 按主键解析场景节点(const std::string& 主键) const noexcept;

    场景节点类* 创建场景(基础信息节点类* 父节点, 场景节点主信息类* 主信息);
    场景节点类* 创建场景_按名称(
        基础信息节点类* 父节点,
        const 语素入口节点类* 名称,
        枚举_世界类型 世界类型 = 枚举_世界类型::其它
    );
    场景节点类* 取或创建子场景_按名称(
        基础信息节点类* 父节点,
        const 语素入口节点类* 名称,
        枚举_世界类型 世界类型 = 枚举_世界类型::其它
    );
    bool 删除场景(场景节点类* 节点);

    std::vector<场景节点类*> 枚举全部场景() const;
    std::vector<场景节点类*> 获取子场景(const 基础信息节点类* 父节点) const;
    std::vector<存在节点类*> 获取子存在(const 基础信息节点类* 父节点) const;
    std::vector<特征节点类*> 获取子特征(const 基础信息节点类* 父节点) const;
    场景节点类* 查找子场景_按名称(const 基础信息节点类* 父节点, const 语素入口节点类* 名称) const;
    std::vector<结构_场景三维体素轮廓存在比较结果> 查找存在_按深度或彩图轮廓图(
        const 场景节点类* 场景,
        const std::vector<结构_三维体素轮廓图视角>& 局部视角集合,
        const 结构_三维体素轮廓融合参数& 局部融合参数,
        const 结构_场景三维体素轮廓查找参数& 参数,
        const 特征值类& 值池,
        const 存在节点类* 存在概念根) const;

    bool 绑定宿主(场景节点类* 节点, 存在节点类* 宿主存在);
    bool 绑定来源文章(场景节点类* 节点, 文章节点类* 来源文章);
    存在节点类* 读取场景宿主存在(const 场景节点类* 场景) const noexcept;
    std::vector<可解析引用<状态节点类>> 读取场景状态索引快照(
        const 场景节点类* 场景) const;
    std::vector<可解析引用<动态节点类>> 读取场景动态索引快照(
        const 场景节点类* 场景) const;
    bool 追加状态(场景节点类* 节点, 状态节点类* 状态节点);
    bool 移除场景状态索引(场景节点类* 场景, 状态节点类* 状态节点);
    bool 移除场景状态索引引用(场景节点类* 场景, const 可解析引用<状态节点类>& 状态引用);
    bool 追加动态(场景节点类* 节点, 动态节点类* 动态节点);
    bool 移除场景动态索引(场景节点类* 场景, 动态节点类* 动态节点);
    bool 追加关系(场景节点类* 节点, 二次特征节点类* 二次特征节点);
    bool 追加二次特征(场景节点类* 节点, 二次特征节点类* 二次特征节点);
    bool 移除场景二次特征索引(场景节点类* 场景, 二次特征节点类* 二次特征节点);
    std::vector<可解析引用<二次特征节点类>> 读取场景二次特征索引快照(
        const 场景节点类* 场景) const;

private:
    基础信息类* 基础信息_ = nullptr;
};
