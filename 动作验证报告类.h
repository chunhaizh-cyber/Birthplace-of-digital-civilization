#pragma once

#include <cstdint>
#include <sstream>
#include <string>
#include <vector>

#include "基础数据类型.h"

namespace 动作验证报告 {
    enum class 枚举_动作验证状态 : std::uint8_t {
        未开始 = 0,
        已建立事务 = 1,
        已生成目标 = 2,
        已生成预测 = 3,
        已调用方法 = 4,
        等待实际回读 = 5,
        实际回读不足 = 6,
        已获得实际回读 = 7,
        验证成功 = 8,
        验证相似 = 9,
        验证失败 = 10,
        回读超时 = 11,
        已提交正常事实 = 12,
        已提交异常事实 = 13,
        已中止 = 14,
    };

    enum class 枚举_事实提交等级 : std::uint8_t {
        未定义 = 0,
        不可提交 = 1,
        待复核事实 = 2,
        异常事实 = 3,
        正常事实 = 4,
    };

    struct 结构_动作验证值 {
        bool 已设置 = false;
        VecI64 值{};
    };

    struct 结构_动作验证报告 {
        std::string 动作事务ID{};
        std::uintptr_t 来源任务指针 = 0;
        std::string 来源任务主键{};
        std::uintptr_t 来源方法指针 = 0;
        std::string 来源方法主键{};

        结构_动作验证值 目标值{};
        结构_动作验证值 预测值{};
        结构_动作验证值 实际值{};
        结构_动作验证值 执行报告值{};

        VecI64 目标偏差{};
        VecI64 预测偏差{};
        VecI64 报告偏差{};
        I64 回读置信度_Q10000 = 0;
        枚举_动作验证状态 验证状态 = 枚举_动作验证状态::未开始;
        枚举_事实提交等级 事实提交等级 = 枚举_事实提交等级::未定义;
    };

    struct 结构_动作验证报告摘要 {
        bool 有报告 = false;
        std::string 动作验证报告ID{};
        枚举_动作验证状态 验证状态 = 枚举_动作验证状态::未开始;
        枚举_事实提交等级 事实提交等级 = 枚举_事实提交等级::未定义;
        I64 回读置信度_Q10000 = 0;
        VecI64 目标偏差{};
        VecI64 预测偏差{};
        VecI64 报告偏差{};
    };

    // 功能：设置对象字段、状态或运行参数。
    inline 结构_动作验证值 已设置值(const VecI64& 值)
    {
        return 结构_动作验证值{ true, 值 };
    }

    // 功能：按函数名执行对应处理。
    inline const char* 转文本(const 枚举_动作验证状态 状态) noexcept
    {
        switch (状态) {
        case 枚举_动作验证状态::未开始: return "未开始";
        case 枚举_动作验证状态::已建立事务: return "已建立事务";
        case 枚举_动作验证状态::已生成目标: return "已生成目标";
        case 枚举_动作验证状态::已生成预测: return "已生成预测";
        case 枚举_动作验证状态::已调用方法: return "已调用方法";
        case 枚举_动作验证状态::等待实际回读: return "等待实际回读";
        case 枚举_动作验证状态::实际回读不足: return "实际回读不足";
        case 枚举_动作验证状态::已获得实际回读: return "已获得实际回读";
        case 枚举_动作验证状态::验证成功: return "验证成功";
        case 枚举_动作验证状态::验证相似: return "验证相似";
        case 枚举_动作验证状态::验证失败: return "验证失败";
        case 枚举_动作验证状态::回读超时: return "回读超时";
        case 枚举_动作验证状态::已提交正常事实: return "已提交正常事实";
        case 枚举_动作验证状态::已提交异常事实: return "已提交异常事实";
        case 枚举_动作验证状态::已中止: return "已中止";
        default: return "未知验证状态";
        }
    }

    // 功能：按函数名执行对应处理。
    inline const char* 转文本(const 枚举_事实提交等级 等级) noexcept
    {
        switch (等级) {
        case 枚举_事实提交等级::未定义: return "未定义";
        case 枚举_事实提交等级::不可提交: return "不可提交";
        case 枚举_事实提交等级::待复核事实: return "待复核事实";
        case 枚举_事实提交等级::异常事实: return "异常事实";
        case 枚举_事实提交等级::正常事实: return "正常事实";
        default: return "未知事实提交等级";
        }
    }

    // 功能：计算权重、状态、差值或派生结果。
    inline VecI64 计算偏差_实际减基准(
        const 结构_动作验证值& 实际值,
        const 结构_动作验证值& 基准值)
    {
        if (!实际值.已设置 || !基准值.已设置 || 实际值.值.size() != 基准值.值.size()) {
            return {};
        }

        VecI64 输出{};
        输出.reserve(实际值.值.size());
        for (std::size_t i = 0; i < 实际值.值.size(); ++i) {
            输出.push_back(实际值.值[i] - 基准值.值[i]);
        }
        return 输出;
    }

    // 功能：按函数名执行对应处理。
    inline void 刷新偏差(结构_动作验证报告& 报告)
    {
        报告.目标偏差 = 计算偏差_实际减基准(报告.实际值, 报告.目标值);
        报告.预测偏差 = 计算偏差_实际减基准(报告.实际值, 报告.预测值);
        报告.报告偏差 = 计算偏差_实际减基准(报告.实际值, 报告.执行报告值);
    }

    // 功能：按函数名执行对应处理。
    inline 结构_动作验证报告摘要 提取摘要(const 结构_动作验证报告& 报告)
    {
        结构_动作验证报告摘要 摘要{};
        摘要.动作验证报告ID = 报告.动作事务ID;
        摘要.验证状态 = 报告.验证状态;
        摘要.事实提交等级 = 报告.事实提交等级;
        摘要.回读置信度_Q10000 = 报告.回读置信度_Q10000;
        摘要.目标偏差 = 报告.目标偏差;
        摘要.预测偏差 = 报告.预测偏差;
        摘要.报告偏差 = 报告.报告偏差;
        摘要.有报告 =
            !摘要.动作验证报告ID.empty()
            || 摘要.验证状态 != 枚举_动作验证状态::未开始
            || 摘要.事实提交等级 != 枚举_事实提交等级::未定义
            || 摘要.回读置信度_Q10000 != 0
            || !摘要.目标偏差.empty()
            || !摘要.预测偏差.empty()
            || !摘要.报告偏差.empty();
        return 摘要;
    }

    // 功能：按函数名执行对应处理。
    inline std::string 值转文本(const 结构_动作验证值& 值)
    {
        if (!值.已设置) {
            return "未设置";
        }

        std::ostringstream 输出;
        输出 << '[';
        for (std::size_t i = 0; i < 值.值.size(); ++i) {
            if (i != 0) {
                输出 << ',';
            }
            输出 << 值.值[i];
        }
        输出 << ']';
        return 输出.str();
    }

    // 功能：按函数名执行对应处理。
    inline std::string 向量转文本(const VecI64& 值)
    {
        if (值.empty()) {
            return "未形成";
        }

        std::ostringstream 输出;
        输出 << '[';
        for (std::size_t i = 0; i < 值.size(); ++i) {
            if (i != 0) {
                输出 << ',';
            }
            输出 << 值[i];
        }
        输出 << ']';
        return 输出.str();
    }

    // 功能：按函数名执行对应处理。
    inline std::string 摘要转日志文本(const 结构_动作验证报告摘要& 摘要)
    {
        if (!摘要.有报告) {
            return "动作验证报告摘要=无";
        }

        std::ostringstream 输出;
        输出 << "动作验证报告摘要"
            << " | 报告ID=" << (摘要.动作验证报告ID.empty() ? "空" : 摘要.动作验证报告ID)
            << " | 验证状态=" << 转文本(摘要.验证状态)
            << " | 事实提交等级=" << 转文本(摘要.事实提交等级)
            << " | 回读置信度=" << 摘要.回读置信度_Q10000
            << " | 目标偏差=" << 向量转文本(摘要.目标偏差)
            << " | 预测偏差=" << 向量转文本(摘要.预测偏差)
            << " | 报告偏差=" << 向量转文本(摘要.报告偏差);
        return 输出.str();
    }

    // 功能：按函数名执行对应处理。
    inline std::string 转日志文本(const 结构_动作验证报告& 报告)
    {
        std::ostringstream 输出;
        输出 << "动作验证报告"
            << " | 事务=" << (报告.动作事务ID.empty() ? "空" : 报告.动作事务ID)
            << " | 来源任务=" << (报告.来源任务主键.empty() ? "空" : 报告.来源任务主键)
            << " | 来源方法=" << (报告.来源方法主键.empty() ? "空" : 报告.来源方法主键)
            << " | 目标=" << 值转文本(报告.目标值)
            << " | 预测=" << 值转文本(报告.预测值)
            << " | 实际=" << 值转文本(报告.实际值)
            << " | 执行报告=" << 值转文本(报告.执行报告值)
            << " | 目标偏差=" << 向量转文本(报告.目标偏差)
            << " | 预测偏差=" << 向量转文本(报告.预测偏差)
            << " | 报告偏差=" << 向量转文本(报告.报告偏差)
            << " | 回读置信度=" << 报告.回读置信度_Q10000
            << " | 验证状态=" << 转文本(报告.验证状态)
            << " | 事实提交等级=" << 转文本(报告.事实提交等级);
        return 输出.str();
    }
}
