    // 功能：服务所在模块的内部辅助流程。
    const 语素入口节点类* 私有_动作名转方法概念词(const 语素入口节点类* 动作名) noexcept
    {
        if (!动作名) {
            return nullptr;
        }
        // 动作名本身是动态模板入口，只能表示“做什么”；方法概念必须使用方法概念入口。
        // 若直接把动态入口绑定到存在概念，会触发“动态入口 -> 存在节点”的类型冲突。
        return 语素集.取或创建同词信息入口(动作名, 枚举_信息入口类型::方法概念入口);
    }

