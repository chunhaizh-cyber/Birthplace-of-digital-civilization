    // 功能：服务所在模块的内部辅助流程。
    方法类::节点类* 私有_归一到方法首节点(方法类::节点类* 节点) noexcept
    {
        auto* 当前 = 节点;
        while (当前) {
            if (方法类::方法节点种类(当前) == 枚举_方法节点种类::方法首节点) {
                return 当前;
            }
            当前 = static_cast<方法类::节点类*>(当前->父);
        }
        return nullptr;
    }

