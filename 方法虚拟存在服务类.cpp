    // 功能：服务所在模块的内部辅助流程。
    枚举_方法类型 私有_推导方法类型(const 方法类::节点类* 方法首节点) noexcept
    {
        switch (方法类::方法动作句柄(方法首节点).类型) {
        case 枚举_动作句柄类型::外部实现主键:
            return 枚举_方法类型::外部方法;
        case 枚举_动作句柄类型::本能函数ID:
        case 枚举_动作句柄类型::动作序列主键:
            return 枚举_方法类型::内部方法;
        default:
            return 枚举_方法类型::未定义;
        }
    }

