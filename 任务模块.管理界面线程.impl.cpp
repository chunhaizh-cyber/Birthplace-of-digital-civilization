struct 结构_任务域本能调用上下文 {
    方法类::节点类* 方法首节点 = nullptr;
    场景节点类* 输入参数场景 = nullptr;
    基础信息节点类* 输入条件包 = nullptr;
    场景节点类* 输出结果场景 = nullptr;
};

结构_任务域本能调用上下文 私有_准备任务域本能调用(
    任务节点* 任务,
    枚举_本能方法ID 本能ID,
    const char* 场景标签,
    场景节点类* 请求场景,
    时间戳 now) noexcept
{
    结构_任务域本能调用上下文 上下文{};
    if (!任务 || 本能ID == 枚举_本能方法ID::未定义) {
        return 上下文;
    }

    auto* 自我存在 = 世界树.自我指针;
    if (!自我存在) {
        项目运行日志("任务管理界面线程/任务域本能调用 | 缺少当前自我存在，无法定位自我本能方法");
        return 上下文;
    }

    上下文.方法首节点 = 本能方法类::查找或创建本能方法首节点(
        自我存在,
        本能ID,
        now);
    if (!上下文.方法首节点) {
        std::ostringstream 日志;
        日志 << "任务管理界面线程/任务域本能调用"
            << " | 本能ID=" << static_cast<std::uint32_t>(本能ID)
            << " | 任务=" << 任务->获取主键()
            << " | 方法首节点缺失";
        项目运行日志(日志.str());
        return 上下文;
    }

    auto* 父场景 = reinterpret_cast<基础信息节点类*>(
        请求场景 ? 请求场景 : 任务->主信息.场景.指针);
    const std::string 基础标签 = 场景标签 && 场景标签[0] != '\0'
        ? 场景标签
        : "任务域本能调用";
    const auto* 输入场景名 = 语素集.添加信息入口词(
        基础标签 + "_输入_" + std::to_string(now),
        枚举_信息入口类型::场景实例入口);
    const auto* 输出场景名 = 语素集.添加信息入口词(
        基础标签 + "_输出_" + std::to_string(now),
        枚举_信息入口类型::场景实例入口);

    上下文.输入参数场景 = 世界树.场景().创建场景_按名称(
        父场景,
        输入场景名,
        枚举_世界类型::内部世界);
    上下文.输出结果场景 = 世界树.场景().创建场景_按名称(
        父场景,
        输出场景名,
        枚举_世界类型::内部世界);
    if (!上下文.输入参数场景) {
        return 上下文;
    }

    上下文.输入条件包 = 世界树.取或创建子特征_按类型(
        reinterpret_cast<基础信息节点类*>(上下文.输入参数场景),
        私有_特征_输入条件包());
    (void)私有_写基础节点指针特征(
        上下文.输入条件包,
        私有_特征_任务信息节点(),
        任务,
        now);
    return 上下文;
}

