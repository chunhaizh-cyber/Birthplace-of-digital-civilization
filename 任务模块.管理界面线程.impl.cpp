bool 私有_工作项已到最早派发时间(
    const 任务管理线程协议::结构_任务工作项& 工作项,
    时间戳 now) noexcept
{
    const auto 最早派发时间 = 私有_工作项最早派发时间(工作项);
    return 最早派发时间 == 0
        || now == 0
        || 最早派发时间 <= now;
}

std::string 私有_工作项任务排序键(
    const 任务管理线程协议::结构_任务工作项& 工作项)
{
    const auto* 任务 = reinterpret_cast<const 任务节点*>(工作项.任务信息节点);
    if (!任务) {
        return {};
    }
    const auto 主键 = 任务->获取主键();
    if (!主键.empty()) {
        return 主键;
    }
    return std::to_string(reinterpret_cast<std::uintptr_t>(任务));
}

I64 私有_工作项调度优先级(
    const 任务管理线程协议::结构_任务工作项& 工作项) noexcept
{
    if (工作项.任务控制态.全局优先级 != 0) {
        return 工作项.任务控制态.全局优先级;
    }
    const auto* 任务 = reinterpret_cast<const 任务节点*>(工作项.任务信息节点);
    return 任务
        ? 任务类::读取任务调度优先级(任务)
        : 0;
}

int 私有_工作项阶段排序值(
    const 任务管理线程协议::枚举_任务工作项类型 工作类型) noexcept
{
    using enum 任务管理线程协议::枚举_任务工作项类型;
    switch (工作类型) {
    case 执行:
        return 2;
    case 筹办:
        return 1;
    default:
        return 0;
    }
}

