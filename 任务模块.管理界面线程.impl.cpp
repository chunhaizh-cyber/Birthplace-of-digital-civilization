void 私有_同步等待挂起索引_已持锁(
    结构_任务界面线程状态& 状态,
    const 结构_调度任务状态快照& 快照)
{
    if (快照.任务主键.empty()) {
        return;
    }

    状态.等待任务索引.erase(快照.任务主键);
    状态.挂起任务索引.erase(快照.任务主键);

    if (快照.任务状态 != 枚举_任务状态::等待中
        && 快照.任务状态 != 枚举_任务状态::挂起) {
        return;
    }

    结构_等待挂起任务索引记录 记录{};
    记录.任务主键 = 快照.任务主键;
    记录.任务状态 = 快照.任务状态;
    记录.状态版本 = 快照.状态版本;
    记录.最近工作项ID = 快照.最近工作项ID;
    记录.更新时间 = 快照.更新时间;
    记录.原因 = 快照.最近原因;

    if (快照.任务状态 == 枚举_任务状态::等待中) {
        状态.等待任务索引[快照.任务主键] = std::move(记录);
    } else {
        状态.挂起任务索引[快照.任务主键] = std::move(记录);
    }
}

