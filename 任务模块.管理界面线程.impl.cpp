        错误日志 << "任务管理界面线程/拒绝归并完成项"
            << " | 请求=" << 工作项.请求ID
            << " | 工作项=" << 工作项.工作项ID
            << " | 工作结果请求=" << 工作结果.请求ID
            << " | 工作结果工作项=" << 工作结果.工作项ID
            << " | 状态版本=" << 工作项.状态版本
            << " | 租约截止=" << 工作项.租约截止时间
            << " | 派发时间=" << 完成项.派发时间
            << " | 原因=" << 承接.说明;
        项目运行错误日志(错误日志.str());
