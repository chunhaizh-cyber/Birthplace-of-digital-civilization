bool 私有_提交界面任务状态变化(
    任务节点* 任务,
    枚举_任务状态 新状态,
    枚举_任务阶段 新阶段,
    场景节点类* 请求场景,
    时间戳 now,
    const std::string& 原因) noexcept
{
    if (!任务 || 新状态 == 枚举_任务状态::未定义) {
        return false;
    }
    std::lock_guard<std::mutex> 生命周期锁(私有_任务生命周期调用互斥());
    const auto 旧状态 = 任务类::读取任务状态(任务, 枚举_任务状态::未定义);
    const auto 旧阶段 = 任务类::读取任务当前阶段(任务, 枚举_任务阶段::未定义);
    if (任务类::任务状态已终结(旧状态)) {
        std::ostringstream 日志;
        日志 << "任务管理界面线程/任务状态提交跳过"
            << " | 任务=" << 任务->获取主键()
            << " | 旧状态=" << 私有_任务状态文本(旧状态)
            << " | 目标状态=" << 私有_任务状态文本(新状态)
            << " | 原因=任务已终结，不再由调度消息推进";
        项目运行日志(日志.str());
        私有_记录调度侧任务状态快照(任务, nullptr, false, now, 原因);
        return false;
    }

    if (旧状态 == 新状态
        && (新阶段 == 枚举_任务阶段::未定义 || 旧阶段 == 新阶段)) {
        私有_记录调度侧任务状态快照(任务, nullptr, false, now, 原因);
        return true;
    }

    auto 上下文 = 私有_准备任务域本能调用(
        任务,
        枚举_本能方法ID::自我_提交任务状态变化,
        "界面线程提交调度任务状态变化",
        请求场景,
        now);
    if (!上下文.输入条件包) {
        项目运行错误日志(
            "任务管理界面线程/任务状态提交失败"
            " | 任务=" + 任务->获取主键()
            + " | 原因=无法构造任务域本能输入包");
        return false;
    }

    (void)私有_写基础节点I64特征(
        上下文.输入条件包,
        私有_特征_建议任务状态(),
        static_cast<I64>(新状态),
        now);
    if (新阶段 != 枚举_任务阶段::未定义) {
        (void)私有_写基础节点I64特征(
            上下文.输入条件包,
            私有_特征_建议任务阶段(),
            static_cast<I64>(新阶段),
            now);
    }

    auto* 运行存在 = 私有_执行任务域本能方法(
        枚举_本能方法ID::自我_提交任务状态变化,
        上下文);
    const bool 已提交 = 运行存在 != nullptr;
    (void)任务类::同步任务运行镜像特征(任务, 请求场景, now);
    私有_记录调度侧任务状态快照(任务, nullptr, false, now, 原因);

    std::ostringstream 日志;
    日志 << "任务管理界面线程/任务状态提交"
        << " | 任务=" << 任务->获取主键()
        << " | 旧状态=" << 私有_任务状态文本(旧状态)
        << " | 新状态=" << 私有_任务状态文本(任务类::读取任务状态(任务, 枚举_任务状态::未定义))
        << " | 旧阶段=" << static_cast<int>(旧阶段)
        << " | 新阶段=" << static_cast<int>(任务类::读取任务当前阶段(任务, 枚举_任务阶段::未定义))
        << " | 成功=" << (已提交 ? 1 : 0)
        << " | 原因=" << 原因;
    项目运行日志(日志.str());
    return 已提交;
}

方法类::节点类* 私有_工作结果当前方法(
    const 任务管理线程协议::结构_任务工作结果& 工作结果) noexcept
{
    auto* 方法 = 工作结果.治理结果.当前方法;
    if (!方法
        && 工作结果.存在任务筹办情况
        && 工作结果.任务筹办情况.筹办回执.当前方法.指针) {
        方法 = reinterpret_cast<方法类::节点类*>(
            工作结果.任务筹办情况.筹办回执.当前方法.指针);
    }
    if (!方法
        && 工作结果.存在任务执行情况
        && 工作结果.任务执行情况.执行回执.当前方法.指针) {
        方法 = reinterpret_cast<方法类::节点类*>(
            工作结果.任务执行情况.执行回执.当前方法.指针);
    }
    if (!方法
        && 工作结果.存在任务执行情况
        && 工作结果.任务执行情况.执行数据.当前方法) {
        方法 = 工作结果.任务执行情况.执行数据.当前方法;
    }
    if (!方法
        && 工作结果.存在任务推进回执
        && 工作结果.任务推进回执.当前方法.指针) {
        方法 = reinterpret_cast<方法类::节点类*>(
            工作结果.任务推进回执.当前方法.指针);
    }
    if (!方法 && 工作结果.存在方法执行数据) {
        方法 = 工作结果.方法执行数据.当前方法;
    }
    return 方法;
}

const 任务模块::筹办::结构_任务推进回执* 私有_工作结果推进回执(
    const 任务管理线程协议::结构_任务工作结果& 工作结果) noexcept
{
    if (工作结果.存在任务筹办情况
        && 工作结果.任务筹办情况.有效) {
        return &工作结果.任务筹办情况.筹办回执;
    }
    if (工作结果.存在任务执行情况
        && 工作结果.任务执行情况.有效) {
        return &工作结果.任务执行情况.执行回执;
    }
    if (工作结果.存在任务推进回执) {
        return &工作结果.任务推进回执;
    }
    return nullptr;
}

