时间戳 私有_计算租约重派退避微秒(std::uint32_t 重试次数) noexcept
{
    if (重试次数 == 0) {
        return 私有_租约重派退避基准微秒;
    }
    auto 退避 = 私有_租约重派退避基准微秒;
    for (std::uint32_t i = 1; i < 重试次数; ++i) {
        if (退避 >= 私有_租约重派退避上限微秒 / 2) {
            return 私有_租约重派退避上限微秒;
        }
        退避 *= 2;
    }
    return std::min(退避, 私有_租约重派退避上限微秒);
}

