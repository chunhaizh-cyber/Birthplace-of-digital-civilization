    输出->质量要求摘要 =
        "任务管理按当前方法供料要求创建外设观察等待项"
        + std::string(";方法=") + 方法主键
        + ";结构化口径=" + 私有_外设观察需求口径文本_任务管理(外设观察口径)
        + ";来源=" + (使用兼容本能ID ? "兼容本能ID" : "方法结果能力")
        + ";按目标特征名映射=0"
        + (目标特征主键.empty() ? "" : ";目标特征主键=" + 目标特征主键)
        + (需求主键.empty() ? "" : ";需求=" + 需求主键);
