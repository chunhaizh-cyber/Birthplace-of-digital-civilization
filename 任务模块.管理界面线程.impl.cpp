bool 私有_工作结果可归并(
    const 任务管理线程协议::结构_任务工作项& 工作项,
    const 任务管理线程协议::结构_任务工作结果& 工作结果,
    时间戳 now) noexcept
{
    if (工作结果.请求ID != 工作项.请求ID
        || 工作结果.工作项ID != 工作项.工作项ID) {
        std::ostringstream 日志;
        日志 << "任务管理界面线程/拒绝归并错配工作结果"
            << " | 工作项请求=" << 工作项.请求ID
            << " | 结果请求=" << 工作结果.请求ID
            << " | 工作项=" << 工作项.工作项ID
            << " | 结果工作项=" << 工作结果.工作项ID;
        项目运行错误日志(日志.str());
        return false;
    }
    if (工作项.租约截止时间 != 0
        && now != 0
        && now > 工作项.租约截止时间) {
        std::ostringstream 日志;
        日志 << "任务管理界面线程/拒绝归并过期租约工作结果"
            << " | 请求=" << 工作项.请求ID
            << " | 工作项=" << 工作项.工作项ID
            << " | 租约截止=" << 工作项.租约截止时间
            << " | 当前=" << now;
        项目运行错误日志(日志.str());
        return false;
    }
    return true;
}

