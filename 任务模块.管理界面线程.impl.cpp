bool 启动任务管理工作线程池(
    自我类& 自我对象,
    std::size_t worker数量) noexcept
{
    (void)启动任务管理界面线程();
    if (worker数量 == 0) {
        auto& 状态 = 私有_界面状态();
        {
            std::lock_guard<std::mutex> 锁(状态.锁);
            状态.运行参数.任务管理工作线程池待保存大小 = 0;
            状态.运行参数.最近参数保存结果 = "拒绝非法 worker pool 大小";
            状态.运行参数.最近参数错误 =
                "任务管理工作线程池大小不能为 0";
            状态.运行参数.最近参数应用结果 = "未启动";
            状态.快照.最近后台worker状态 = "启动拒绝";
            状态.快照.最近后台worker原因 =
                状态.运行参数.最近参数错误;
            私有_刷新队列快照_已持锁(状态);
        }
        项目运行错误日志(
            "任务管理界面线程/后台工作线程池启动拒绝 | worker数=0");
        return false;
    }
    if (!私有_worker池大小有效(static_cast<std::uint64_t>(worker数量))) {
        auto& 状态 = 私有_界面状态();
        const auto 错误 =
            "任务管理工作线程池大小越界 | worker数="
            + std::to_string(worker数量)
            + " | 有效范围="
            + std::to_string(
                任务管理线程协议::任务管理工作线程池最小大小_常量)
            + "-"
            + std::to_string(
                任务管理线程协议::任务管理工作线程池最大大小_常量);
        {
            std::lock_guard<std::mutex> 锁(状态.锁);
            状态.运行参数.任务管理工作线程池待保存大小 =
                static_cast<std::uint64_t>(worker数量);
            状态.运行参数.最近参数保存结果 = "拒绝非法 worker pool 大小";
            状态.运行参数.最近参数错误 = 错误;
            状态.运行参数.最近参数应用结果 = "未启动";
            状态.快照.最近后台worker状态 = "启动拒绝";
            状态.快照.最近后台worker原因 = 错误;
            私有_刷新队列快照_已持锁(状态);
        }
        项目运行错误日志("任务管理界面线程/后台工作线程池启动拒绝 | " + 错误);
        return false;
    }

    auto& 状态 = 私有_界面状态();
    {
        std::lock_guard<std::mutex> 锁(状态.锁);
        if (私有_后台worker池运行_已持锁(状态)) {
            return true;
        }
        状态.后台worker停止请求 = false;
        状态.后台worker自我对象 = &自我对象;
        状态.后台worker已启动 = true;
    }

    try {
        std::vector<std::thread> 新线程{};
        新线程.reserve(worker数量);
        for (std::size_t i = 0; i < worker数量; ++i) {
            新线程.emplace_back(私有_后台worker循环, i + 1);
        }
        {
            std::lock_guard<std::mutex> 锁(状态.锁);
            for (auto& 线程 : 新线程) {
                状态.后台worker线程.emplace_back(std::move(线程));
            }
            状态.快照.后台worker池运行 = true;
            状态.快照.后台worker线程数 =
                static_cast<std::uint64_t>(状态.后台worker线程.size());
            状态.快照.最近后台worker状态 = "已启动";
            状态.快照.最近后台worker原因 =
                "任务管理界面线程/后台工作线程池已启动";
            状态.运行参数.最近参数应用结果 =
                "已按 worker pool 大小 "
                + std::to_string(worker数量)
                + " 启动";
            状态.运行参数.最近参数错误.clear();
            私有_刷新队列快照_已持锁(状态);
        }
        状态.工作项条件变量.notify_all();
        项目运行日志(
            "任务管理界面线程/后台工作线程池已启动"
            " | worker数=" + std::to_string(worker数量));
        return true;
    } catch (const std::exception& 异常) {
        项目运行错误日志(
            std::string("任务管理界面线程/后台工作线程池启动失败 | 异常=")
            + 异常.what());
        私有_停止任务管理工作线程池();
        return false;
    } catch (...) {
        项目运行错误日志("任务管理界面线程/后台工作线程池启动失败 | 异常=未知");
        私有_停止任务管理工作线程池();
        return false;
    }
}

bool 保存任务管理工作线程池大小(
    自我类& 自我对象,
    std::size_t worker数量,
    任务管理线程协议::结构_任务界面线程快照* 输出快照) noexcept
{
    (void)启动任务管理界面线程();
    const auto worker数量64 = static_cast<std::uint64_t>(worker数量);
    auto& 状态 = 私有_界面状态();
    if (!私有_worker池大小有效(worker数量64)) {
        const auto 错误 =
            "任务管理工作线程池大小非法 | worker数="
            + std::to_string(worker数量)
            + " | 有效范围="
            + std::to_string(
                任务管理线程协议::任务管理工作线程池最小大小_常量)
            + "-"
            + std::to_string(
                任务管理线程协议::任务管理工作线程池最大大小_常量);
        {
            std::lock_guard<std::mutex> 锁(状态.锁);
            状态.运行参数.任务管理工作线程池待保存大小 = worker数量64;
            状态.运行参数.最近参数保存结果 = "保存失败";
            状态.运行参数.最近参数错误 = 错误;
            状态.运行参数.最近参数应用结果 = "未应用";
            私有_刷新队列快照_已持锁(状态);
            if (输出快照) {
                *输出快照 = 状态.快照;
            }
        }
        项目运行错误日志("任务管理界面线程/参数保存失败 | " + 错误);
        return false;
    }

    bool 保存前worker池运行 = false;
    {
        std::lock_guard<std::mutex> 锁(状态.锁);
        保存前worker池运行 = 私有_后台worker池运行_已持锁(状态);
        状态.运行参数.任务管理工作线程池待保存大小 = worker数量64;
        状态.运行参数.任务管理工作线程池当前有效大小 = worker数量64;
        状态.运行参数.任务管理工作线程池参数版本 += 1;
        状态.运行参数.最近参数保存结果 =
            "保存成功 | worker pool 大小=" + std::to_string(worker数量);
        状态.运行参数.最近参数错误.clear();
        状态.运行参数.最近参数应用结果 =
            保存前worker池运行 ? "等待重建 worker pool" : "已保存，等待下次启动应用";
        私有_刷新队列快照_已持锁(状态);
    }

    if (保存前worker池运行) {
        私有_停止任务管理工作线程池();
        const bool 已重启 = 启动任务管理工作线程池(自我对象);
        std::lock_guard<std::mutex> 锁(状态.锁);
        状态.运行参数.最近参数应用结果 = 已重启
            ? "保存后已安全重建 worker pool"
            : "保存成功但 worker pool 重建失败";
        if (!已重启) {
            状态.运行参数.最近参数错误 =
                "保存成功但 worker pool 重建失败";
        }
        私有_刷新队列快照_已持锁(状态);
        if (输出快照) {
            *输出快照 = 状态.快照;
        }
        return 已重启;
    }

    {
        std::lock_guard<std::mutex> 锁(状态.锁);
        状态.运行参数.最近参数应用结果 =
            "已保存，worker pool 未运行，等待下次启动应用";
        私有_刷新队列快照_已持锁(状态);
        if (输出快照) {
            *输出快照 = 状态.快照;
        }
    }
    项目运行日志(
        "任务管理界面线程/参数保存成功 | worker数="
        + std::to_string(worker数量));
    return true;
}

