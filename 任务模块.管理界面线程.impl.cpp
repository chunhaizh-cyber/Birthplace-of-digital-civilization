std::size_t 私有_同步回执候选方法集到任务普通函数(
    任务节点* 任务,
    const 任务模块::筹办::结构_任务推进回执* 回执,
    场景节点类* 承载场景,
    时间戳 now) noexcept
{
    if (!任务 || !回执) {
        return 0;
    }

    std::size_t 已同步数量 = 0;
    for (const auto& 候选方法引用 : 回执->候选方法集) {
        auto* 候选方法 = reinterpret_cast<方法类::节点类*>(候选方法引用.指针);
        auto* 方法存在 = 私有_取或创建回执方法虚拟存在_普通同步(候选方法, now);
        if (!候选方法 || !方法存在) {
            std::ostringstream 日志;
            日志 << "任务管理界面线程/普通整理候选方法无效"
                << " | 任务=" << 任务->获取主键()
                << " | 候选指针=" << 候选方法引用.指针;
            项目运行错误日志(日志.str());
            continue;
        }
        if (任务类::追加任务方法候选虚拟存在(
                任务,
                方法存在,
                承载场景,
                now)) {
            ++已同步数量;
        }
    }
    return 已同步数量;
}

bool 私有_同步当前方法到任务普通函数(
    任务节点* 任务,
    方法类::节点类* 方法,
    场景节点类* 承载场景,
    时间戳 now) noexcept
{
    if (!任务 || !方法) {
        return false;
    }
    auto* 方法存在 = 私有_取或创建回执方法虚拟存在_普通同步(方法, now);
    if (!方法存在) {
        std::ostringstream 日志;
        日志 << "任务管理界面线程/普通整理当前方法缺少虚拟存在"
            << " | 任务=" << 任务->获取主键()
            << " | 方法=" << 方法->获取主键();
        项目运行错误日志(日志.str());
        return false;
    }

    const bool 已入候选集 = 任务类::追加任务方法候选虚拟存在(
        任务,
        方法存在,
        承载场景,
        now);
    const bool 已写执行方法 = 任务类::写入任务执行方法(
        任务,
        reinterpret_cast<方法节点类*>(方法),
        承载场景,
        now);
    const bool 已写当前方法存在 = 任务类::写入任务当前方法虚拟存在(
        任务,
        方法存在,
        承载场景,
        now);
    if (const I64 能力值 = 私有_方法自我能力值(方法); 能力值 != 0) {
        (void)任务类::写入任务选中自我能力值(
            任务,
            能力值,
            承载场景,
            now);
    }

    std::ostringstream 日志;
    日志 << "任务管理界面线程/普通整理当前方法到任务"
        << " | 任务=" << 任务->获取主键()
        << " | 方法=" << 方法->获取主键()
        << " | 方法虚拟存在=" << 方法存在->获取主键()
        << " | 入候选集=" << (已入候选集 ? 1 : 0)
        << " | 执行方法=" << (已写执行方法 ? 1 : 0)
        << " | 当前方法存在=" << (已写当前方法存在 ? 1 : 0);
    if (已写执行方法 && 已写当前方法存在) {
        项目运行日志(日志.str());
    } else {
        项目运行错误日志(日志.str());
    }
    return 已写执行方法 && 已写当前方法存在;
}

bool 私有_同步工作回执方法到任务壳(
    任务节点* 任务,
    const 任务管理线程协议::结构_任务工作结果& 工作结果,
    场景节点类* 请求场景,
    时间戳 now) noexcept
{
    if (!任务) {
        return false;
    }

    // 被动整理退回生命周期普通代码：这里只同步任务账字段，不生成主链动作动态。
    auto* 方法 = 私有_工作结果当前方法(工作结果);
    const auto* 回执 = 私有_工作结果推进回执(工作结果);
    const bool 回执阶段为执行 =
        回执 && 回执->阶段 == 任务模块::筹办::枚举_任务推进阶段::执行;
    const bool 执行回执 =
        工作结果.存在任务执行情况
        || 工作结果.已执行方法
        || 回执阶段为执行;
    auto* 承载场景 = 请求场景 ? 请求场景 : 任务->主信息.场景.指针;

    bool 任一写入 = false;
    const auto 已同步候选数量 = 私有_同步回执候选方法集到任务普通函数(
        任务,
        回执,
        承载场景,
        now);
    任一写入 = 已同步候选数量 > 0 || 任一写入;
    任一写入 = 私有_同步当前方法到任务普通函数(
        任务,
        方法,
        承载场景,
        now) || 任一写入;

    const auto 候选方法集 = 任务类::读取任务方法候选虚拟存在集(
        任务,
        承载场景);
    if (!候选方法集.empty() || 已同步候选数量 > 0 || 方法) {
        任一写入 = 私有_写任务虚拟存在I64特征(
            任务,
            私有_特征_候选方法数量(),
            static_cast<I64>(候选方法集.size()),
            承载场景,
            now) || 任一写入;
    }

    if (回执) {
        if (执行回执) {
            任一写入 = 私有_写任务虚拟存在I64特征(
                任务,
                私有_特征_目标是否达成(),
                回执->当前任务目标达成 ? 1 : 0,
                承载场景,
                now) || 任一写入;
            任一写入 = 私有_写任务虚拟存在I64特征(
                任务,
                私有_特征_本轮是否有推进(),
                回执->本轮是否有推进 ? 1 : 0,
                承载场景,
                now) || 任一写入;
            任一写入 = 私有_写任务虚拟存在I64特征(
                任务,
                私有_特征_本轮推进量(),
                回执->本轮推进量,
                承载场景,
                now) || 任一写入;
            任一写入 = 私有_写任务虚拟存在I64特征(
                任务,
                私有_特征_剩余差距(),
                回执->剩余差距,
                承载场景,
                now) || 任一写入;
            任一写入 = 私有_写任务虚拟存在I64特征(
                任务,
                私有_特征_执行结果类型(),
                static_cast<I64>(回执->执行结果类型),
                承载场景,
                now) || 任一写入;
            if (回执->缺口特征类型) {
                任一写入 = 私有_写任务虚拟存在指针特征(
                    任务,
                    私有_特征_执行缺口类型(),
                    回执->缺口特征类型,
                    承载场景,
                    now) || 任一写入;
            }
        } else {
            if (回执->可执行输入参数场景.指针) {
                任一写入 = 私有_写任务虚拟存在指针特征(
                    任务,
                    私有_特征_可执行输入参数场景(),
                    reinterpret_cast<void*>(回执->可执行输入参数场景.指针),
                    承载场景,
                    now) || 任一写入;
            }
            if (回执->缺口特征类型) {
                任一写入 = 私有_写任务虚拟存在指针特征(
                    任务,
                    私有_特征_筹办缺口类型(),
                    回执->缺口特征类型,
                    承载场景,
                    now) || 任一写入;
            }
        }

        if (回执->缺口特征类型) {
            任一写入 = 私有_写任务虚拟存在指针特征(
                任务,
                私有_特征_等待原因(),
                回执->缺口特征类型,
                承载场景,
                now) || 任一写入;
            if (回执->需要创建或复用子需求) {
                任一写入 = 私有_写任务虚拟存在指针特征(
                    任务,
                    私有_特征_派生需求提示(),
                    回执->缺口特征类型,
                    承载场景,
                    now) || 任一写入;
            }
        }
    }

    if (auto* 方法运行结果 = 私有_工作结果方法运行结果(工作结果)) {
        任一写入 = 私有_写任务虚拟存在指针特征(
            任务,
            私有_特征_当前方法运行存在(),
            方法运行结果,
            承载场景,
            now) || 任一写入;
        任一写入 = 私有_写任务虚拟存在指针特征(
            任务,
            私有_特征_最近运行虚拟存在(),
            方法运行结果,
            承载场景,
            now) || 任一写入;
    }
    if (auto* 输出结果场景 = 私有_工作结果输出结果场景(工作结果)) {
        任一写入 = 私有_写任务虚拟存在指针特征(
            任务,
            私有_特征_输出结果场景(),
            输出结果场景,
            承载场景,
            now) || 任一写入;
    }

    {
        std::ostringstream 日志;
        auto* 回执方法 = 回执 && 回执->当前方法.指针
            ? reinterpret_cast<方法类::节点类*>(回执->当前方法.指针)
            : nullptr;
        日志 << "任务管理界面线程/普通整理回执到任务壳"
            << " | 任务=" << 任务->获取主键()
            << " | 类型=" << (执行回执 ? "执行" : "筹办")
            << " | 工作结果方法=" << (方法 ? 方法->获取主键() : std::string("空"))
            << " | 回执方法=" << (回执方法 ? 回执方法->获取主键() : std::string("空"))
            << " | 回执候选数=" << (回执 ? 回执->候选方法集.size() : 0)
            << " | 已同步候选数=" << 已同步候选数量
            << " | 任务候选数=" << 候选方法集.size()
            << " | 任一写入=" << (任一写入 ? 1 : 0);
        项目运行日志(日志.str());
    }
    return 任一写入;
}

任务管理线程协议::枚举_任务界面调度动作 私有_裁决工作结果调度动作(
    bool 已派发,
    const 任务管理线程协议::结构_任务工作结果& 工作结果) noexcept
{
    using enum 任务管理线程协议::枚举_任务界面调度动作;
    if (工作结果.建议进入收束) {
        return 结束调度;
    }
    if (工作结果.建议界面线程下一轮) {
        return 重新排队;
    }
    if (工作结果.需要等待) {
        return 挂起等待;
    }
    if (已派发) {
        return 派发工作线程;
    }
    return 拒绝请求;
}

// 工作结果任务域提交点。
// 工作线程只给出建议状态和回执字段；本函数是界面线程唯一把工作结果
// 写入任务壳 / 任务虚拟存在的位置。若任务状态发生变化，这里同步生成
// 任务状态动作动态，并把动态引用放回治理结果，供上行和需求域继续串链。
void 私有_应用工作结果到任务壳(
    任务节点* 任务,
    任务管理线程协议::结构_任务工作结果& 工作结果,
    场景节点类* 请求场景,
    时间戳 now) noexcept
{
    if (!任务) {
        return;
    }
    (void)私有_同步工作回执方法到任务壳(任务, 工作结果, 请求场景, now);
    const auto* 回执 = 私有_工作结果推进回执(工作结果);
    if (回执 && !回执->实际结果状态集.empty()) {
        const auto& 实际结果 = 回执->实际结果状态集.front();
        if (实际结果.指针) {
            (void)任务类::写入任务结果状态摘要_兼容(任务, 实际结果);
        } else if (!实际结果.主键.empty()) {
            (void)任务类::写入任务结果状态摘要_兼容(任务, 实际结果);
        }
        const auto& 兼容结果状态 = 任务类::读取任务结果状态摘要_兼容(任务);
        std::ostringstream 输出;
        输出 << "任务管理界面线程/同步任务实际结果状态兼容摘要"
            << " | 任务=" << 任务->获取主键()
            << " | 兼容结果状态="
            << (兼容结果状态.指针
                ? 兼容结果状态.指针->获取主键()
                : 兼容结果状态.主键)
            << " | 目标达成=" << (回执->当前任务目标达成 ? 1 : 0)
            << " | 有推进=" << (回执->本轮是否有推进 ? 1 : 0)
            << " | 推进量=" << 回执->本轮推进量
            << " | 剩余差距=" << 回执->剩余差距;
        项目运行日志(输出.str());
    }
    if (工作结果.治理结果.宿主任务新状态 != 枚举_任务状态::未定义) {
        auto 上下文 = 私有_准备任务域本能调用(
            任务,
            枚举_本能方法ID::自我_提交任务状态变化,
            "提交任务状态变化",
            请求场景,
            now);
        if (上下文.输入条件包) {
            私有_写工作结果输入特征(上下文.输入条件包, 工作结果, now);
            (void)私有_写基础节点I64特征(
                上下文.输入条件包,
                私有_特征_建议任务状态(),
                static_cast<I64>(工作结果.治理结果.宿主任务新状态),
                now);
            if (回执 && 回执->建议任务阶段 != 枚举_任务阶段::未定义) {
                (void)私有_写基础节点I64特征(
                    上下文.输入条件包,
                    私有_特征_建议任务阶段(),
                    static_cast<I64>(回执->建议任务阶段),
                    now);
            }
            if (auto* 状态提交运行 = 私有_执行任务域本能方法(
                    枚举_本能方法ID::自我_提交任务状态变化,
                    上下文)) {
                if (auto* 动态 = 私有_读取动作动态(状态提交运行)) {
                    工作结果.治理结果.任务状态动作动态 = 动态;
                    工作结果.治理结果.最新动态 = 动态;
                }
            }
        }
    }
    auto* 当前方法 = 私有_工作结果当前方法(工作结果);
    const bool 本轮按方法供料创建外设等待项 =
        私有_按当前方法供料要求提交外设等待项(
            任务,
            工作结果,
            当前方法);
    const bool 既有等待缺口唤醒 =
        任务类::读取任务等待缺口唤醒(
            任务,
            false,
            任务->主信息.场景.指针);
    const bool 本轮产生等待缺口唤醒 = 本轮按方法供料创建外设等待项;
    (void)任务类::写入任务等待缺口唤醒(
        任务,
        既有等待缺口唤醒 || 本轮产生等待缺口唤醒,
        任务->主信息.场景.指针,
        now);
    (void)任务类::同步任务运行镜像特征(任务, 请求场景, now);
    {
        const bool 当前等待缺口唤醒 = 任务类::读取任务等待缺口唤醒(
            任务,
            false,
            任务->主信息.场景.指针);
        std::ostringstream 输出;
        输出 << "任务管理界面线程/工作结果应用尾部证据"
            << " | 任务=" << 任务->获取主键()
            << " | 当前方法=" << (当前方法 ? 当前方法->获取主键() : std::string{})
            << " | 已执行筹办=" << (工作结果.已执行筹办 ? 1 : 0)
            << " | 已执行方法=" << (工作结果.已执行方法 ? 1 : 0)
            << " | 产生派生需求=" << (工作结果.产生派生需求 ? 1 : 0)
            << " | 需要等待=" << (工作结果.需要等待 ? 1 : 0)
            << " | 建议进入收束=" << (工作结果.建议进入收束 ? 1 : 0)
            << " | 建议任务状态=" << 私有_任务状态文本(工作结果.治理结果.宿主任务新状态)
            << " | 实际任务状态=" << 私有_任务状态文本(任务类::读取任务状态(任务, 枚举_任务状态::未定义))
            << " | 推进状况=" << (回执 ? static_cast<int>(回执->状况) : -1)
            << " | 回执摘要=" << (回执 ? 回执->摘要 : std::string{})
            << " | 既有等待缺口唤醒=" << (既有等待缺口唤醒 ? 1 : 0)
            << " | 本轮产生等待缺口唤醒=" << (本轮产生等待缺口唤醒 ? 1 : 0)
            << " | 方法供料等待项=" << (本轮按方法供料创建外设等待项 ? 1 : 0)
            << " | 当前等待缺口唤醒=" << (当前等待缺口唤醒 ? 1 : 0)
            << " | 摘要=" << 工作结果.摘要;
        项目运行日志(输出.str());
    }
}

