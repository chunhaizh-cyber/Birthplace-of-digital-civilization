void 私有_推入上行消息集(
    const std::vector<结构_任务管理上行消息>& 消息集,
    const 任务管理线程协议::结构_任务界面承接结果& 承接) noexcept
{
    if (消息集.empty()) {
        return;
    }
    auto& 状态 = 私有_界面状态();
    std::lock_guard<std::mutex> 锁(状态.锁);
    std::size_t 已推入 = 0;
    for (const auto& 消息 : 消息集) {
        const auto 幂等键 = 私有_任务管理上行消息幂等键(消息);
        if (!幂等键.empty()) {
            if (状态.外设承接上行幂等表.find(幂等键)
                != 状态.外设承接上行幂等表.end()) {
                continue;
            }
            状态.外设承接上行幂等表.emplace(幂等键, 私有_时间(0));
        }
        状态.上行队列.push_back(消息);
        ++已推入;
    }
    状态.快照.累计上行消息数 += 已推入;
    状态.快照.当前上行队列长度 = 状态.上行队列.size();
    状态.快照.最近请求ID = 承接.请求ID;
}

std::size_t 私有_巡检外设观察等待项并生成上行(
    std::size_t 最大数量,
    时间戳 now) noexcept
{
    const auto 队列状态 = 读取外设观察队列状态();
    if (队列状态.等待项数量 == 0 || 队列状态.最新报告ID == 0) {
        if (队列状态.等待项数量 > 0 && 队列状态.最新报告ID == 0) {
            auto& 状态 = 私有_界面状态();
            std::lock_guard<std::mutex> 锁(状态.锁);
            if (状态.外设承接最近巡检报告ID != 队列状态.最新报告ID
                || 状态.外设承接最近巡检等待项数量 != 队列状态.等待项数量) {
                状态.外设承接最近巡检报告ID = 队列状态.最新报告ID;
                状态.外设承接最近巡检等待项数量 = 队列状态.等待项数量;
                项目运行日志(
                    "任务管理界面线程/外设等待项巡检跳过 | 原因=暂无外设观察报告"
                    " | 等待项数量=" + std::to_string(队列状态.等待项数量)
                    + " | 最新报告ID=0 | 不生成观察事实承接请求=1");
            }
        }
        return 0;
    }

    {
        auto& 状态 = 私有_界面状态();
        std::lock_guard<std::mutex> 锁(状态.锁);
        if (状态.外设承接最近巡检报告ID == 队列状态.最新报告ID
            && 状态.外设承接最近巡检等待项数量 == 队列状态.等待项数量) {
            return 0;
        }
        状态.外设承接最近巡检报告ID = 队列状态.最新报告ID;
        状态.外设承接最近巡检等待项数量 = 队列状态.等待项数量;
    }

    const auto 等待项集合 = 读取外设观察等待项集合(
        std::string{},
        枚举_外设观察运行模式::未指定);
    const auto 数量上限 = 最大数量 == 0 ? 等待项集合.size() : 最大数量;
    std::vector<结构_任务管理上行消息> 上行消息集{};
    std::size_t 已巡检 = 0;
    for (const auto& 等待项 : 等待项集合) {
        if (已巡检 >= 数量上限) {
            break;
        }
        ++已巡检;
        auto 承接结果 = 任务管理工作线程::任务管理外设消息承接_处理一次(等待项);
        if (!承接结果.上行消息集.empty()) {
            上行消息集.insert(
                上行消息集.end(),
                承接结果.上行消息集.begin(),
                承接结果.上行消息集.end());
        }
    }

    if (上行消息集.empty()) {
        return 0;
    }

    任务管理线程协议::结构_任务界面承接结果 承接{};
    承接.请求ID = 0;
    承接.说明 = "任务管理外设等待项巡检命中报告，生成观察事实承接上行消息";
    承接.上行消息集 = 上行消息集;
    私有_推入上行消息集(上行消息集, 承接);
    项目运行日志(
        "任务管理界面线程/外设等待项巡检生成上行"
        " | 最新报告ID=" + std::to_string(队列状态.最新报告ID)
        + " | 等待项数量=" + std::to_string(队列状态.等待项数量)
        + " | 巡检数量=" + std::to_string(已巡检)
        + " | 上行消息数=" + std::to_string(上行消息集.size())
        + " | 直接写需求树=0 | 直接写世界树=0");
    (void)now;
    return 上行消息集.size();
}

