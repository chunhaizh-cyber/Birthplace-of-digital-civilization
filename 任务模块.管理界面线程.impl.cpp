bool 私有_工作项排序在前(
    const 结构_任务调度队列项& 左,
    const 结构_任务调度队列项& 右,
    时间戳 now)
{
    const auto 左键 = 私有_计算工作项排序键(左.工作项, now);
    const auto 右键 = 私有_计算工作项排序键(右.工作项, now);
    if (左键.已到最早派发时间 != 右键.已到最早派发时间) {
        return 左键.已到最早派发时间;
    }
    if (左键.调度优先级 != 右键.调度优先级) {
        return 左键.调度优先级 > 右键.调度优先级;
    }
    if (左键.阶段排序值 != 右键.阶段排序值) {
        return 左键.阶段排序值 > 右键.阶段排序值;
    }
    if (左键.重试次数 != 右键.重试次数) {
        return 左键.重试次数 < 右键.重试次数;
    }
    if (左键.最早派发时间 != 右键.最早派发时间) {
        return 左键.最早派发时间 < 右键.最早派发时间;
    }
    if (左键.入队时间 != 右键.入队时间) {
        return 左键.入队时间 < 右键.入队时间;
    }
    if (左键.任务排序键 != 右键.任务排序键) {
        return 左键.任务排序键 < 右键.任务排序键;
    }
    return 左键.工作项ID < 右键.工作项ID;
}

void 私有_重排调度队列_已持锁(
    结构_任务界面线程状态& 状态,
    std::deque<结构_任务调度队列项>& 队列,
    时间戳 now,
    const std::string& 原因)
{
    std::stable_sort(
        队列.begin(),
        队列.end(),
        [now](const 结构_任务调度队列项& 左, const 结构_任务调度队列项& 右) {
            return 私有_工作项排序在前(左, 右, now);
        });
    状态.快照.最近排序原因 = 原因;
}

std::deque<结构_任务调度队列项>* 私有_选择可派发工作项队列_已持锁(
    结构_任务界面线程状态& 状态,
    时间戳 now) noexcept
{
    const bool 执行可派发 =
        !状态.待执行队列.empty()
        && 私有_工作项已到最早派发时间(
            状态.待执行队列.front().工作项,
            now);
    const bool 筹办可派发 =
        !状态.待筹办队列.empty()
        && 私有_工作项已到最早派发时间(
            状态.待筹办队列.front().工作项,
            now);

    if (执行可派发) {
        return &状态.待执行队列;
    }
    if (筹办可派发) {
        return &状态.待筹办队列;
    }
    return nullptr;
}

bool 私有_弹出可派发工作项_已持锁(
    结构_任务界面线程状态& 状态,
    时间戳 now,
    结构_任务调度队列项* 输出) noexcept
{
    if (!输出) {
        return false;
    }

    auto 找可派发 = [now](std::deque<结构_任务调度队列项>& 队列) {
        return std::find_if(
            队列.begin(),
            队列.end(),
            [now](const 结构_任务调度队列项& 项) noexcept {
                return 私有_工作项已到最早派发时间(项.工作项, now);
            });
    };

    auto 执行项 = 找可派发(状态.待执行队列);
    auto 筹办项 = 找可派发(状态.待筹办队列);
    const bool 有执行 = 执行项 != 状态.待执行队列.end();
    const bool 有筹办 = 筹办项 != 状态.待筹办队列.end();

    if (!有执行 && !有筹办) {
        return false;
    }

    if (有执行) {
        *输出 = std::move(*执行项);
        状态.待执行队列.erase(执行项);
        return true;
    }

    *输出 = std::move(*筹办项);
    状态.待筹办队列.erase(筹办项);
    return true;
}

