任务管理线程协议::结构_任务工作项 私有_构造任务工作项(
    const 任务管理线程协议::结构_任务治理请求& 请求,
    const 任务管理线程协议::结构_任务界面承接结果& 承接,
    存在节点类* 任务存在,
    时间戳 now) noexcept
{
    auto& 状态 = 私有_界面状态();
    任务管理线程协议::结构_任务工作项 工作项{};
    工作项.请求ID = 请求.请求ID;
    auto* 任务 = reinterpret_cast<任务节点*>(请求.任务信息节点);
    {
        std::lock_guard<std::mutex> 锁(状态.锁);
        工作项.工作项ID = 状态.下一个工作项ID++;
        const auto 任务主键 = 私有_任务调度键(任务);
        if (!任务主键.empty()) {
            const auto it = 状态.任务状态快照表.find(任务主键);
            if (it != 状态.任务状态快照表.end()) {
                工作项.状态版本 = it->second.状态版本;
            }
        }
        状态.快照.最近工作项ID = 工作项.工作项ID;
    }
    工作项.幂等键 = 请求.幂等键;
    工作项.任务信息节点 = 请求.任务信息节点;
    工作项.任务虚拟存在 = 任务存在;
    工作项.来源需求 = 请求.来源需求;
    工作项.当前时间 = now;
    工作项.创建时间 = now;
    工作项.入队时间 = now;
    工作项.最早派发时间 = now;
    if (工作项.状态版本 == 0) {
        工作项.状态版本 = now > 0 ? static_cast<std::uint64_t>(now) : 0;
    }
    工作项.租约截止时间 = 0;
    工作项.任务根节点 = 承接.任务根节点;
    工作项.任务控制态 = 承接.最新任务控制态;
    工作项.任务局部运行态 = 承接.最新任务局部运行态;
    const auto 当前任务状态 = 任务 ? 任务类::读取任务状态(任务) : 枚举_任务状态::未定义;
    const auto 推进裁决 = 私有_裁决任务推进(请求, 当前任务状态);
    工作项.工作类型 = 推进裁决.工作类型;
    工作项.来源调度事件类型 = 推进裁决.调度事件类型;
    工作项.任务摘要 = 请求.请求摘要;
    工作项.摘要 = 请求.请求摘要;
    工作项.入队原因 = 请求.请求摘要.empty()
        ? std::string(推进裁决.原因)
        : 请求.请求摘要;
    if (工作项.工作类型 != 任务管理线程协议::枚举_任务工作项类型::未定义
        && 请求.来源需求) {
        项目运行日志(
            "任务管理界面线程/外设观察等待项创建延后"
            " | 任务=" + (任务 ? 任务->获取主键() : std::string("空"))
            + " | 来源需求=" + reinterpret_cast<需求节点*>(请求.来源需求)->获取主键()
            + " | 依据=当前方法供料要求"
            + " | 入队阶段按目标特征名映射=0"
            + " | 直接写需求树=0 | 直接写世界树=0");
    }
    {
        std::lock_guard<std::mutex> 锁(状态.锁);
        状态.快照.最近工作项类型 = 私有_工作项类型文本(工作项.工作类型);
        状态.快照.最近入队原因 = 工作项.入队原因;
    }
    return 工作项;
}

