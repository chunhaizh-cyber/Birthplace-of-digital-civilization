bool 私有_任务节点相同(const 任务节点* 左, const 任务节点* 右) noexcept
{
    if (左 == 右) {
        return true;
    }
    return 左
        && 右
        && !左->获取主键().empty()
        && 左->获取主键() == 右->获取主键();
}

bool 私有_任务已有有效入队执行工作项(
    const 任务节点* 任务,
    时间戳 now) noexcept
{
    if (!任务) {
        return false;
    }
    auto& 状态 = 私有_界面状态();
    std::lock_guard<std::mutex> 锁(状态.锁);
    for (const auto& 项 : 状态.待执行队列) {
        const auto* 入队任务 = reinterpret_cast<const 任务节点*>(项.工作项.任务信息节点);
        if (!私有_任务节点相同(入队任务, 任务)
            || 项.工作项.工作类型 != 任务管理线程协议::枚举_任务工作项类型::执行) {
            continue;
        }
        if (项.工作项.租约截止时间 == 0
            || now == 0
            || now <= 项.工作项.租约截止时间) {
            return true;
        }
    }
    for (const auto& [键, 记录] : 状态.在途工作项索引) {
        (void)键;
        const auto* 在途任务 = reinterpret_cast<const 任务节点*>(记录.工作项.任务信息节点);
        if (!私有_任务节点相同(在途任务, 任务)
            || 记录.工作项.工作类型 != 任务管理线程协议::枚举_任务工作项类型::执行) {
            continue;
        }
        if (记录.工作项.租约截止时间 == 0
            || now == 0
            || now <= 记录.工作项.租约截止时间) {
            return true;
        }
    }
    return false;
}

bool 私有_任务已有有效入队或在途工作项(
    const 任务节点* 任务,
    时间戳 now,
    任务管理线程协议::枚举_任务工作项类型 指定类型 =
        任务管理线程协议::枚举_任务工作项类型::未定义) noexcept
{
    if (!任务) {
        return false;
    }
    auto 工作类型命中 = [指定类型](任务管理线程协议::枚举_任务工作项类型 类型) noexcept {
        return 指定类型 == 任务管理线程协议::枚举_任务工作项类型::未定义
            || 类型 == 指定类型;
    };
    auto 工作项仍有效 = [now](const 任务管理线程协议::结构_任务工作项& 工作项) noexcept {
        return 工作项.租约截止时间 == 0
            || now == 0
            || now <= 工作项.租约截止时间;
    };

    auto& 状态 = 私有_界面状态();
    std::lock_guard<std::mutex> 锁(状态.锁);
    const auto 队列命中 = [&](const std::deque<结构_任务调度队列项>& 队列) noexcept {
        for (const auto& 项 : 队列) {
            const auto* 入队任务 = reinterpret_cast<const 任务节点*>(项.工作项.任务信息节点);
            if (私有_任务节点相同(入队任务, 任务)
                && 工作类型命中(项.工作项.工作类型)
                && 工作项仍有效(项.工作项)) {
                return true;
            }
        }
        return false;
    };
    if (队列命中(状态.待筹办队列) || 队列命中(状态.待执行队列)) {
        return true;
    }
    for (const auto& [键, 记录] : 状态.在途工作项索引) {
        (void)键;
        const auto* 在途任务 = reinterpret_cast<const 任务节点*>(记录.工作项.任务信息节点);
        if (私有_任务节点相同(在途任务, 任务)
            && 工作类型命中(记录.工作项.工作类型)
            && 工作项仍有效(记录.工作项)) {
            return true;
        }
    }
    return false;
}

void 私有_收集任务树头节点(
    任务节点* 任务根,
    std::vector<任务节点*>& 输出) noexcept
{
    if (!任务根) {
        return;
    }
    std::vector<任务节点*> 待访问{};
    待访问.push_back(任务根);
    std::size_t 总保护 = 0;
    while (!待访问.empty() && 总保护++ < 100000) {
        auto* 父节点 = 待访问.back();
        待访问.pop_back();
        if (!父节点 || !父节点->子) {
            continue;
        }

        auto* 首节点 = reinterpret_cast<任务节点*>(父节点->子);
        auto* 当前 = 首节点;
        std::size_t 子保护 = 0;
        do {
            if (!当前 || 子保护++ > 10000) {
                break;
            }
            if (任务类::读取任务节点种类(当前) == 枚举_任务节点种类::头结点) {
                输出.push_back(当前);
            }
            if (当前->子) {
                待访问.push_back(当前);
            }
            当前 = reinterpret_cast<任务节点*>(当前->下);
        } while (当前 && 当前 != 首节点);
    }
}

