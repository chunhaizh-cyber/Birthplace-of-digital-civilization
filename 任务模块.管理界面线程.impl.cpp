std::size_t 归并任务工作完成队列(
    std::size_t 最大数量,
    任务管理线程协议::结构_任务界面线程快照* 输出快照) noexcept
{
    (void)启动任务管理界面线程();
    const auto 归并上限 = 最大数量 == 0 ? static_cast<std::size_t>(4) : 最大数量;
    结构_任务调度消费统计 消费统计{};
    std::size_t 已归并 = 0;

    while (已归并 < 归并上限) {
        结构_任务完成队列项 完成队列项{};
        if (!私有_弹出完成队列项(&完成队列项)) {
            break;
        }

        auto 承接 = 完成队列项.调度项.承接;
        const auto 完成时刻 = 完成队列项.完成项.完成时间 != 0
            ? 完成队列项.完成项.完成时间
            : 私有_时间(0);
        const bool 已归并当前项 = 私有_归并完成队列项(
            完成队列项,
            消费统计,
            &承接);
        if (已归并当前项) {
            私有_推入上行消息集(承接.上行消息集, 承接);
            私有_刷新快照(承接, 承接.说明);
            私有_记录承接结果(
                承接,
                承接.调度动作 == 任务管理线程协议::枚举_任务界面调度动作::结束调度
                    || 承接.调度动作 == 任务管理线程协议::枚举_任务界面调度动作::拒绝请求,
                完成时刻);

            const auto& 完成项 = 完成队列项.完成项;
            const auto& 工作结果 = 完成项.工作结果;
            if (完成项.已派发
                && 工作结果.建议界面线程下一轮
                && !工作结果.建议进入收束
                && !工作结果.需要等待) {
                auto 下一轮工作项 = 私有_构造任务工作项(
                    完成队列项.调度项.请求,
                    承接,
                    完成队列项.调度项.任务虚拟存在,
                    完成时刻);
                if (下一轮工作项.工作类型 != 任务管理线程协议::枚举_任务工作项类型::未定义) {
                    私有_登记等待工作项(
                        完成队列项.调度项.请求,
                        承接,
                        下一轮工作项,
                        完成队列项.调度项.任务虚拟存在,
                        完成队列项.调度项.请求场景,
                        工作结果.已执行筹办
                            ? 任务管理线程协议::枚举_任务调度事件类型::筹办回执已同步
                            : (工作结果.已执行方法
                                ? 任务管理线程协议::枚举_任务调度事件类型::执行回执已同步
                                : 任务管理线程协议::枚举_任务调度事件类型::普通推进),
                        "后台worker完成项归并后生成后续调度事件",
                        完成时刻);
                }
            }
        } else {
            私有_记录承接结果(承接, true, 完成时刻);
        }

        ++已归并;
    }

    if (消费统计.收到工作结果数 > 0) {
        auto& 状态 = 私有_界面状态();
        std::lock_guard<std::mutex> 锁(状态.锁);
        状态.快照.累计收到工作结果数 += 消费统计.收到工作结果数;
    }
    if (输出快照) {
        (void)读取任务管理界面线程快照(输出快照);
    }
    return 已归并;
}

bool 提交任务治理请求(
    自我类& 自我对象,
    const 任务管理线程协议::结构_任务治理请求& 请求,
    任务管理线程协议::结构_任务界面承接结果* 输出) noexcept
{
    (void)启动任务管理界面线程();
    auto& 状态 = 私有_界面状态();

    auto now = 私有_时间(请求.当前时间);
    auto 请求副本 = 请求;
    请求副本.请求类型 = 私有_归一请求类型(请求副本);
    if (请求副本.请求ID == 0) {
        std::lock_guard<std::mutex> 锁(状态.锁);
        请求副本.请求ID = 状态.下一个请求ID++;
    }
    if (请求副本.幂等键.empty()) {
        请求副本.幂等键 = 私有_构造任务治理幂等键(请求副本);
    }
    if (请求副本.允许复用等待任务) {
        任务管理线程协议::结构_任务界面承接结果 已有承接{};
        if (私有_尝试复用幂等承接结果(请求副本.幂等键, &已有承接)) {
            if (输出) {
                *输出 = 已有承接;
            }
            return 已有承接.已校验;
        }
    }

    {
        std::lock_guard<std::mutex> 锁(状态.锁);
        状态.正在处理 = true;
        状态.快照.正在处理 = true;
        状态.快照.累计接收请求数 += 1;
    }
    私有_登记请求已接收(请求副本, now);

    任务管理线程协议::结构_任务界面承接结果 承接{};
    承接.请求ID = 请求副本.请求ID;
    承接.幂等键 = 请求副本.幂等键;
    承接.任务信息节点 = 请求副本.任务信息节点;
    承接.来源需求 = 请求副本.来源需求;
    承接.已接收 = true;
    承接.请求状态 = 任务管理线程协议::枚举_任务界面请求状态::已接收;

    auto* 任务 = reinterpret_cast<任务节点*>(请求副本.任务信息节点);
    auto* 需求 = reinterpret_cast<需求节点*>(请求副本.来源需求);
    if (!任务
        && 需求
        && 请求副本.请求类型 == 任务管理线程协议::枚举_任务管理请求类型::发起任务
        && 请求副本.允许创建任务信息节点) {
        任务 = 私有_按需求创建任务并初始化(
            自我对象,
            需求,
            reinterpret_cast<任务节点*>(请求副本.上级任务信息节点),
            now);
        请求副本.任务信息节点 = reinterpret_cast<任务节点类*>(任务);
        承接.任务信息节点 = 请求副本.任务信息节点;
    }

    if (!需求
        || (!任务 && 请求副本.请求类型 != 任务管理线程协议::枚举_任务管理请求类型::发起任务)
        || (!任务 && 请求副本.请求类型 == 任务管理线程协议::枚举_任务管理请求类型::发起任务)) {
        承接.请求状态 = 任务管理线程协议::枚举_任务界面请求状态::校验失败;
        承接.调度动作 = 任务管理线程协议::枚举_任务界面调度动作::拒绝请求;
        承接.说明 = 请求副本.请求类型 == 任务管理线程协议::枚举_任务管理请求类型::发起任务
            ? "任务发起请求缺少来源需求或任务信息节点创建失败"
            : "任务治理请求缺少任务信息节点或来源需求";
        {
            std::lock_guard<std::mutex> 锁(状态.锁);
            状态.正在处理 = false;
            状态.故障 = true;
        }
        私有_刷新快照(承接, 承接.说明);
        私有_记录承接结果(承接, true, now);
        if (输出) {
            *输出 = 承接;
        }
        return false;
    }

    承接.已校验 = true;
    私有_绑定任务需求关系(任务, 需求);
    私有_准备任务运行壳(任务, 需求, now);

    auto* 任务存在 = 请求副本.允许创建任务虚拟存在
        ? 私有_确保任务虚拟存在(自我对象, 任务, 需求, 请求副本.所属场景, now)
        : reinterpret_cast<存在节点类*>(任务->主信息.任务虚拟存在.指针);
    if (!任务存在) {
        承接.请求状态 = 任务管理线程协议::枚举_任务界面请求状态::故障;
        承接.调度动作 = 任务管理线程协议::枚举_任务界面调度动作::拒绝请求;
        承接.说明 = "任务虚拟存在创建或解析失败，拒绝派发工作线程";
        {
            std::lock_guard<std::mutex> 锁(状态.锁);
            状态.正在处理 = false;
            状态.故障 = true;
        }
        私有_刷新快照(承接, 承接.说明);
        私有_记录承接结果(承接, true, now);
        const auto 错误文本 =
            "任务管理界面线程/任务语义绑定失败"
            " | 任务=" + 私有_安全主键(任务)
            + " | 需求=" + 私有_安全主键(需求)
            + " | 原因=" + 承接.说明;
        项目运行错误日志(错误文本);
        项目弹窗错误提示("鱼巢 - 任务语义绑定逻辑错误", 错误文本);
        if (输出) {
            *输出 = 承接;
        }
        return false;
    }

    承接.任务虚拟存在 = 任务存在;
    承接.已绑定任务虚拟存在 = true;
    承接.请求状态 = 任务管理线程协议::枚举_任务界面请求状态::已绑定任务虚拟存在;
    {
        std::lock_guard<std::mutex> 锁(状态.锁);
        状态.快照.累计绑定任务虚拟存在数 += 1;
    }

    if (请求副本.允许初始化任务语义) {
        承接.已初始化任务语义 =
            私有_用需求初始化任务虚拟存在(
                自我对象,
                任务,
                需求,
                请求副本.所属场景,
                now);
        if (承接.已初始化任务语义) {
            承接.请求状态 = 任务管理线程协议::枚举_任务界面请求状态::已初始化任务语义;
        }
    }

    承接.任务根节点 = 私有_构造任务根节点(请求副本, 请求副本.请求ID);
    承接.最新任务控制态 = 私有_构造任务控制态(承接.任务根节点, 任务);
    承接.最新任务局部运行态 = 私有_构造任务局部运行态(承接.任务根节点, 任务);
    auto 工作项 = 私有_构造任务工作项(请求副本, 承接, 任务存在, now);
    承接.已构造工作项 = true;
    承接.工作项ID = 工作项.工作项ID;

    if (!请求副本.允许派发工作线程) {
        if (工作项.工作类型 == 任务管理线程协议::枚举_任务工作项类型::未定义) {
            // 发起任务的只创建请求已经在界面线程内完成任务信息节点和任务虚拟存在创建。
            // 它不是等待执行的工作项；后续筹办 / 执行必须由自我线程提交调度意图后重新进入任务管理线程。
            承接.请求状态 = 任务管理线程协议::枚举_任务界面请求状态::已完成;
            承接.调度动作 = 任务管理线程协议::枚举_任务界面调度动作::结束调度;
            承接.已进入等待队列 = false;
            承接.说明 = "任务发起请求已完成任务创建，未派发工作线程";
        } else {
            承接.请求状态 = 任务管理线程协议::枚举_任务界面请求状态::等待工作线程;
            承接.调度动作 = 任务管理线程协议::枚举_任务界面调度动作::挂起等待;
            承接.已进入等待队列 = true;
            承接.说明 = "任务治理请求只完成界面线程承接，未派发工作线程";
            私有_登记等待工作项(
                请求副本,
                承接,
                工作项,
                任务存在,
                请求副本.所属场景,
                任务管理线程协议::枚举_任务调度事件类型::普通推进,
                承接.说明,
                now);
        }
        {
            std::lock_guard<std::mutex> 锁(状态.锁);
            状态.正在处理 = false;
        }
        私有_刷新快照(承接, 承接.说明);
        私有_记录承接结果(承接, false, now);
        if (输出) {
            *输出 = 承接;
        }
        return true;
    }

    if (工作项.工作类型 == 任务管理线程协议::枚举_任务工作项类型::未定义) {
        承接.请求状态 = 任务管理线程协议::枚举_任务界面请求状态::已完成;
        承接.调度动作 = 任务管理线程协议::枚举_任务界面调度动作::结束调度;
        承接.已进入等待队列 = false;
        承接.说明 = "任务治理请求没有可派发工作项";
        {
            std::lock_guard<std::mutex> 锁(状态.锁);
            状态.正在处理 = false;
        }
        私有_刷新快照(承接, 承接.说明);
        私有_记录承接结果(承接, true, now);
        if (输出) {
            *输出 = 承接;
        }
        return true;
    }

    私有_登记等待工作项(
        请求副本,
        承接,
        工作项,
        任务存在,
        请求副本.所属场景,
        任务管理线程协议::枚举_任务调度事件类型::普通推进,
        "任务治理请求允许派发，提交调度事件",
        now);

    if (私有_后台worker池运行()) {
        承接.请求状态 = 任务管理线程协议::枚举_任务界面请求状态::等待工作线程;
        承接.调度动作 = 任务管理线程协议::枚举_任务界面调度动作::重新排队;
        承接.已进入等待队列 = true;
        承接.说明 = "任务治理请求已入队，等待后台 worker 消费";
        {
            std::lock_guard<std::mutex> 锁(状态.锁);
            状态.正在处理 = false;
            状态.故障 = false;
        }
        私有_刷新快照(承接, 承接.说明);
        私有_记录承接结果(承接, false, now);
        if (输出) {
            *输出 = 承接;
        }
        return true;
    }

    // 单线程调度泵：本轮请求只消费有限预算。若工作结果建议继续，
    // 后续工作项会重新入队，而不是在调用栈内直接递归续派。
    constexpr std::size_t 本轮调度预算 = 4;
    结构_任务调度消费统计 消费统计{};
    私有_消费任务调度队列_按请求(
        自我对象,
        请求副本,
        承接,
        任务存在,
        now,
        本轮调度预算,
        消费统计);
    if (!消费统计.推进事件列表.empty() || !消费统计.上行消息集.empty()) {
        承接.推进事件列表 = std::move(消费统计.推进事件列表);
        承接.上行消息集 = std::move(消费统计.上行消息集);
    }
    承接.已派发工作线程 = 消费统计.派发工作项数 > 0;

    {
        std::lock_guard<std::mutex> 锁(状态.锁);
        状态.快照.累计派发工作项数 += 消费统计.派发工作项数;
        状态.快照.累计收到工作结果数 += 消费统计.收到工作结果数;
        状态.正在处理 = false;
        状态.故障 = 承接.请求状态 == 任务管理线程协议::枚举_任务界面请求状态::故障;
    }
    私有_推入上行消息集(承接.上行消息集, 承接);
    私有_刷新快照(承接, 承接.说明);
    私有_记录承接结果(
        承接,
        承接.调度动作 == 任务管理线程协议::枚举_任务界面调度动作::结束调度
            || 承接.调度动作 == 任务管理线程协议::枚举_任务界面调度动作::拒绝请求,
        now);

    if (输出) {
        *输出 = 承接;
    }
    return 承接.已校验;
}

bool 巡检并派发就绪任务(
    自我类& 自我对象,
    std::uint64_t 当前时间,
    std::size_t 本轮最大消费数,
    任务管理线程协议::结构_任务界面线程快照* 输出快照) noexcept
{
    (void)启动任务管理界面线程();
    auto& 状态 = 私有_界面状态();
    const auto now = 私有_时间(当前时间);
    const auto 消费上限 = 本轮最大消费数 == 0 ? static_cast<std::size_t>(4) : 本轮最大消费数;

    {
        std::lock_guard<std::mutex> 锁(状态.锁);
        状态.正在处理 = true;
        状态.快照.正在处理 = true;
    }

    const auto 已归并完成项 = 归并任务工作完成队列(消费上限, nullptr);
    const auto 入队数 = 私有_巡检全部任务状态并入队(
        自我对象,
        now,
        消费上限);

    结构_任务调度消费统计 消费统计{};
    if (私有_后台worker池运行()) {
        (void)自我对象;
    } else {
        私有_消费任务调度队列(
            自我对象,
            now,
            消费上限,
            消费统计);
    }
    const auto 外设承接上行数 = 私有_巡检外设观察等待项并生成上行(
        消费上限,
        now);

    {
        std::lock_guard<std::mutex> 锁(状态.锁);
        状态.快照.累计派发工作项数 += 消费统计.派发工作项数;
        状态.快照.累计收到工作结果数 += 消费统计.收到工作结果数;
        状态.正在处理 = false;
        状态.快照.正在处理 = false;
    }

    if (输出快照) {
        (void)读取任务管理界面线程快照(输出快照);
    }
    return 入队数 > 0
        || 已归并完成项 > 0
        || 消费统计.派发工作项数 > 0
        || 消费统计.收到工作结果数 > 0
        || 外设承接上行数 > 0;
}

bool 提交任务状态推进请求(
    const 任务管理线程协议::结构_任务状态推进请求& 请求,
    任务管理线程协议::结构_任务状态推进结果* 输出结果) noexcept
{
    auto* 任务 = reinterpret_cast<任务节点*>(请求.任务信息节点);
    if (输出结果) {
        *输出结果 = {};
        输出结果->任务信息节点 = 请求.任务信息节点;
        输出结果->来源需求 = 请求.来源需求;
    }
    if (!任务) {
        return false;
    }
    const auto now = 私有_时间(请求.当前时间);
    auto* 场景 = 任务->主信息.场景.指针;
    const auto 原任务状态 =
        任务类::读取任务状态(任务, 枚举_任务状态::未定义);
    const auto 原任务阶段 =
        任务类::读取任务当前阶段(任务, 枚举_任务阶段::未定义);
    if (输出结果) {
        输出结果->原任务状态 = 原任务状态;
        输出结果->原任务阶段 = 原任务阶段;
    }

    bool 已写入 = false;
    动态节点类* 任务状态动作动态 = nullptr;
    if ((请求.写入任务状态 && 请求.建议任务状态 != 枚举_任务状态::未定义)
        || (请求.写入任务阶段 && 请求.建议任务阶段 != 枚举_任务阶段::未定义)) {
        const auto 提交状态 = 请求.写入任务状态
            && 请求.建议任务状态 != 枚举_任务状态::未定义
            ? 请求.建议任务状态
            : 任务类::读取任务状态(任务, 枚举_任务状态::未定义);
        if (提交状态 == 枚举_任务状态::未定义) {
            std::ostringstream 日志;
            日志 << "任务管理界面线程/任务状态推进"
                << " | 任务=" << 任务->获取主键()
                << " | 阶段推进缺少有效任务状态";
            项目运行日志(日志.str());
            return false;
        }

        auto 上下文 = 私有_准备任务域本能调用(
            任务,
            枚举_本能方法ID::自我_提交任务状态变化,
            "显式提交任务状态变化",
            场景,
            now);
        if (上下文.输入条件包) {
            (void)私有_写基础节点I64特征(
                上下文.输入条件包,
                私有_特征_建议任务状态(),
                static_cast<I64>(提交状态),
                now);
            if (请求.写入任务阶段
                && 请求.建议任务阶段 != 枚举_任务阶段::未定义) {
                (void)私有_写基础节点I64特征(
                    上下文.输入条件包,
                    私有_特征_建议任务阶段(),
                    static_cast<I64>(请求.建议任务阶段),
                    now);
            }
            if (auto* 状态提交运行 = 私有_执行任务域本能方法(
                    枚举_本能方法ID::自我_提交任务状态变化,
                    上下文)) {
                任务状态动作动态 = 私有_读取动作动态(状态提交运行);
            }
        }
        已写入 = true;
    }
    const bool 既有等待缺口唤醒 =
        任务类::读取任务等待缺口唤醒(任务, false, 场景);
    (void)任务类::写入任务等待缺口唤醒(
        任务,
        既有等待缺口唤醒 || 请求.等待缺口唤醒,
        场景,
        now);
    (void)任务类::同步任务运行镜像特征(任务, 场景, now);
    私有_记录调度侧任务状态快照(任务, nullptr, false, now);
    if (已写入) {
        std::ostringstream 日志;
        日志 << "任务管理界面线程/任务状态推进"
            << " | 任务=" << 任务->获取主键()
            << " | 原状态=" << static_cast<int>(原任务状态)
            << " | 状态=" << static_cast<int>(任务类::读取任务状态(任务))
            << " | 原阶段=" << static_cast<int>(原任务阶段)
            << " | 阶段=" << static_cast<int>(任务类::读取任务当前阶段(任务));
        if (任务状态动作动态) {
            日志 << " | 任务状态动作动态=" << 任务状态动作动态->获取主键();
        } else {
            日志 << " | 任务状态动作动态=缺";
        }
        项目运行日志(日志.str());
    }
    if (输出结果) {
        输出结果->新任务状态 =
            任务类::读取任务状态(任务, 枚举_任务状态::未定义);
        输出结果->新任务阶段 =
            任务类::读取任务当前阶段(任务, 枚举_任务阶段::未定义);
        输出结果->已提交任务状态 =
            已写入 && 请求.写入任务状态;
        输出结果->已提交任务阶段 =
            已写入 && 请求.写入任务阶段;
        输出结果->等待缺口唤醒 =
            任务类::读取任务等待缺口唤醒(任务, false, 场景);
        输出结果->任务状态动作动态 = 任务状态动作动态;

        std::ostringstream 摘要;
        摘要 << "任务状态推进结果"
            << " | 任务=" << 任务->获取主键()
            << " | 原状态=" << static_cast<int>(输出结果->原任务状态)
            << " | 新状态=" << static_cast<int>(输出结果->新任务状态)
            << " | 原阶段=" << static_cast<int>(输出结果->原任务阶段)
            << " | 新阶段=" << static_cast<int>(输出结果->新任务阶段)
            << " | 等待缺口唤醒=" << (输出结果->等待缺口唤醒 ? 1 : 0)
            << " | 任务状态动作动态="
            << (任务状态动作动态 ? 任务状态动作动态->获取主键() : std::string("缺"));
        输出结果->摘要 = 摘要.str();
    }
    return true;
}

bool 提交任务权重固化请求(
    const 任务管理线程协议::结构_任务权重固化请求& 请求) noexcept
{
    auto* 任务 = reinterpret_cast<任务节点*>(请求.任务信息节点);
    if (!任务) {
        return false;
    }
    const auto now = 私有_时间(请求.当前时间);
    auto* 场景 = 任务->主信息.场景.指针;
    (void)任务类::写入任务承接安全权重上限(
        任务,
        (std::max<I64>)(0, 请求.承接安全权重上限),
        场景,
        now);
    (void)任务类::写入任务承接服务权重上限(
        任务,
        (std::max<I64>)(0, 请求.承接服务权重上限),
        场景,
        now);
    (void)任务类::写入任务权重评分(
        任务,
        (std::max<I64>)(0, 请求.任务权重评分),
        场景,
        now);
    (void)任务类::写入任务权重版本号(
        任务,
        请求.任务权重版本号 > 0 ? 请求.任务权重版本号 : (now > 0 ? static_cast<I64>(now) : 1),
        场景,
        now);
    (void)任务类::同步任务运行镜像特征(任务, 场景, now);
    std::ostringstream 日志;
    日志 << "任务管理界面线程/任务承接权重固化"
        << " | 任务=" << 任务->获取主键()
        << " | 安全上限=" << 请求.承接安全权重上限
        << " | 服务上限=" << 请求.承接服务权重上限
        << " | 评分=" << 请求.任务权重评分;
    项目运行日志(日志.str());
    return true;
}

bool 提交任务价值结算回执(
    const 任务管理线程协议::结构_任务价值结算回执& 回执) noexcept
{
    auto* 任务 = reinterpret_cast<任务节点*>(回执.任务信息节点);
    if (!任务) {
        return false;
    }
    const auto now = 私有_时间(回执.当前时间);
    auto* 场景 = 任务->主信息.场景.指针;
    bool 已写入 = false;
    if (回执.写入已折算安全值) {
        (void)任务类::写入任务已折算安全值(
            任务,
            (std::max<I64>)(0, 回执.已折算安全值),
            场景,
            now);
        已写入 = true;
    }
    if (回执.写入已折算服务值) {
        (void)任务类::写入任务已折算服务值(
            任务,
            (std::max<I64>)(0, 回执.已折算服务值),
            场景,
            now);
        已写入 = true;
    }
    if (已写入) {
        (void)任务类::同步任务运行镜像特征(任务, 场景, now);
        std::ostringstream 日志;
        日志 << "任务管理界面线程/任务价值折算回执"
            << " | 任务=" << 任务->获取主键()
            << " | 已折算安全=" << 回执.已折算安全值
            << " | 已折算服务=" << 回执.已折算服务值
            << " | 事件=" << 回执.反馈事件主键;
        项目运行日志(日志.str());
    }
    return true;
}

bool 提交派生需求入树回执(
    const 任务管理线程协议::结构_派生需求入树回执& 回执) noexcept
{
    (void)启动任务管理界面线程();
    auto* 任务 = reinterpret_cast<任务节点*>(回执.任务信息节点);
    auto* 父需求 = reinterpret_cast<需求节点*>(回执.父需求);
    auto* 派生需求 = reinterpret_cast<需求节点*>(回执.派生需求);
    const auto now = 私有_时间(回执.当前时间);
    const auto* 结果文本 = 私有_派生需求入树处理结果文本(回执.处理结果);
    const std::string 摘要 =
        回执.原因摘要.empty()
            ? std::string("派生需求入树回执")
            : 回执.原因摘要;

    if (任务) {
        私有_记录调度侧任务状态快照(
            任务,
            nullptr,
            false,
            now,
            "派生需求入树回执 | 结果=" + std::string(结果文本));
    }

    {
        auto& 状态 = 私有_界面状态();
        std::lock_guard<std::mutex> 锁(状态.锁);
        状态.快照.累计派生需求入树回执数 += 1;
        状态.快照.累计调度事件数 += 1;
        状态.快照.最近调度事件ID = 状态.下一个调度事件ID++;
        状态.快照.最近调度事件类型 =
            私有_调度事件类型文本(
                任务管理线程协议::枚举_任务调度事件类型::派生需求已回写);
        状态.快照.最近任务主键 = 私有_安全主键(任务);
        状态.快照.最近需求主键 =
            派生需求 ? 私有_安全主键(派生需求) : 私有_安全主键(父需求);
        状态.快照.最近派生需求入树处理结果 = 结果文本;
        状态.快照.最近派生需求入树摘要 = 摘要;
        状态.快照.最近说明 = 摘要;
    }

    std::ostringstream 日志;
    日志 << "任务管理界面线程/派生需求入树回执"
        << " | 任务=" << 私有_安全主键(任务)
        << " | 父需求=" << 私有_安全主键(父需求)
        << " | 派生需求=" << 私有_安全主键(派生需求)
        << " | 处理结果=" << 结果文本
        << " | 阻塞父任务=" << (回执.是否阻塞父任务推进 ? 1 : 0)
        << " | 原消息键=" << 回执.原派生消息幂等键
        << " | 原因=" << 摘要;
    项目运行日志(日志.str());
    return 任务 || 父需求 || 派生需求;
}

bool 提取任务管理上行消息(
    std::vector<结构_任务管理上行消息>* 输出,
    std::size_t 最大数量) noexcept
{
    if (!输出) {
        return false;
    }
    auto& 状态 = 私有_界面状态();
    std::lock_guard<std::mutex> 锁(状态.锁);
    const auto 数量上限 = 最大数量 == 0 ? 状态.上行队列.size() : 最大数量;
    std::size_t 已取 = 0;
    while (!状态.上行队列.empty() && 已取 < 数量上限) {
        输出->push_back(状态.上行队列.front());
        状态.上行队列.pop_front();
        ++已取;
    }
    状态.快照.当前上行队列长度 = 状态.上行队列.size();
    return 已取 > 0;
}

bool 读取任务管理界面线程快照(
    任务管理线程协议::结构_任务界面线程快照* 输出) noexcept
{
    if (!输出) {
        return false;
    }
    auto& 状态 = 私有_界面状态();
    std::lock_guard<std::mutex> 锁(状态.锁);
    *输出 = 状态.快照;
    return true;
}

